    [TestMethod]
    public void Emit_writes_template_files_per_dto_and_reports_unwritable_ones()
    {
        const string profile = """
            using Nextended.Core.CodeGen;
            using Shop.Domain;

            public sealed class Emits : CodeGenConfig
            {
                public Emits()
                {
                    Defaults(d => d.Emit("{Dto}.meta.json", "{ \"dto\": \"{DtoFullName}\", \"source\": \"{SourceFullName}\" }", "meta/"));
                    Dto<OrderLine>(l => l
                        .Emit("{Dto}Validator.g.cs", "namespace {DtoNamespace}; public partial class {Dto}Validator { }")
                        .Emit("{Source}.txt", "no path")                  // NCG024: not .cs, no output path
                        .Emit("Same.g.cs", "// one")
                        .View("OrderLineRow", v => v.Emit("Same.g.cs", "// two")));   // NCG024: same file name
                }
            }
            """;
        var (files, diagnostics) = Run(Config(), Entities, profile);

        File(files, "OrderLineDtoValidator.g.cs").ShouldBe("namespace Shop.Contracts; public partial class OrderLineDtoValidator { }");
        var meta = files.Single(f => f.FileName == "OrderLineDto.meta.json");
        meta.OutputPath.ShouldBe("meta/");
        meta.Content.ShouldBe("{ \"dto\": \"Shop.Contracts.OrderLineDto\", \"source\": \"Shop.Domain.OrderLine\" }");
        files.ShouldContain(f => f.FileName == "OrderLineRowDto.meta.json"); // defaults reach views too
        diagnostics.Count(d => d.Id == "NCG024").ShouldBe(2, string.Join(Environment.NewLine, diagnostics));
        File(files, "Same.g.cs").ShouldBe("// one");
    }

