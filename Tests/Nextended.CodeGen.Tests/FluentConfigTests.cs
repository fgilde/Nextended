    [TestMethod]
    public void Every_settings_method_of_the_api_is_known_to_the_generator()
    {
        // one call of every settings method, built from the API itself: none may be unknown to the generator (NCG026)
        const string item = "namespace Probe; public class Item { public string Name { get; set; } = \"\"; }";
        var api = CompileWithInTreeAttributes(item);
        string Calls(string interfaceName, string receiver, params string[] skip)
        {
            var type = api.GetTypeByMetadataName($"Nextended.Core.CodeGen.{interfaceName}")!;
            var methods = type.AllInterfaces.Append(type).SelectMany(i => i.GetMembers().OfType<IMethodSymbol>())
                .Where(m => !skip.Contains(m.Name) && !m.IsGenericMethod && m.Parameters.All(p => p.Type is not INamedTypeSymbol { Name: "Action" or "Expression" }))
                .GroupBy(m => m.Name).Select(g => g.First());
            return string.Concat(methods.Select(m => $"{receiver}.{m.Name}({string.Join(", ", m.Parameters.Where(p => !p.HasExplicitDefaultValue).Select(Argument))});" + Environment.NewLine));
        }
        static string Argument(IParameterSymbol p) => p.Type switch
        {
            { SpecialType: SpecialType.System_String } => "\"X\"",
            { SpecialType: SpecialType.System_Boolean } => "false",
            { SpecialType: SpecialType.System_Int32 } => "1",
            IArrayTypeSymbol => "\"X\"",
            { TypeKind: TypeKind.Enum } t => $"({t.ToDisplayString()})1",
            var t => throw new InvalidOperationException($"no sample for {t}")
        };

        var profile = $$"""
            using Nextended.Core.CodeGen;
            public sealed class All : CodeGenConfig
            {
                public All()
                {
                    Defaults(d => { {{Calls("IDtoDefaults", "d", "Emit", "DisableGeneration")}} });
                    Defaults(d => d.DefaultMappingSettings(m => { {{Calls("IMappingDefaults", "m")}} }));
                    Dto<Probe.Item>(i => { {{Calls("IDtoBuilder`1", "i", "Emit", "Ignore", "Include", "Order", "Property")}} });
                    Dto<Probe.Item>(i => { {{Calls("IPropertyBuilder", "i.Property(\"Name\")")}} });
                    ExcelGeneration(e => { {{Calls("IExcelGeneration", "e")}} });
                    StructureGeneration(s => { {{Calls("IStructureGeneration", "s")}} });
                }
            }
            """;

        var (_, diagnostics) = Run(Config(), item, profile);
        diagnostics.Where(d => d.Id is "NCG026" or "NCG020").ShouldBeEmpty(profile + Environment.NewLine + string.Join(Environment.NewLine, diagnostics));
    }
