    // ... and fluently, on entities without attributes
    private const string ShopProfile = """
        using Nextended.Core.CodeGen;
        using Shop.Domain;

        namespace Shop.CodeGen;

        public sealed class ShopCodeGen : CodeGenConfig
        {
            public ShopCodeGen()
            {
                Dto<Entity>(e => e.Ignore(x => x.TenantId));
                Dto<Order>(o => o
                    .Ignore(x => x.InternalNote)
                    .View("OrderRow", v => v.Ignore(x => x.Lines)));   // TenantId: the rule of Entity reaches Order and the view too
                Dto<OrderLine>();
                Dto<OrderState>(s => s.Ignore(nameof(OrderState.Legacy)));
            }
        }

        public sealed class OrderDtoConfig : DtoConfig<Order>
        {
            public OrderDtoConfig()
            {
                Property(x => x.Number).PropertyName("No");
            }
        }
        """;

    [TestMethod]
    public void Fluent_configuration_generates_the_same_files_as_the_equivalent_attributes()
    {
        var (attributed, attributeDiagnostics) = Run(Config(), AttributedEntities);
        var (fluent, fluentDiagnostics) = Run(Config(), Entities, ShopProfile);

        NoDiagnostics(attributeDiagnostics);
        NoDiagnostics(fluentDiagnostics);
        fluent.Select(f => f.FileName).OrderBy(n => n).ShouldBe(attributed.Select(f => f.FileName).OrderBy(n => n));
        foreach (var file in attributed)
            File(fluent, file.FileName).ShouldBe(file.Content, file.FileName);

        var orderRow = File(fluent, "OrderRowDto.g.cs");
        orderRow.ShouldContain("No { get; set; }");
        orderRow.ShouldNotContain("Lines");
        orderRow.ShouldNotContain("TenantId");
        File(fluent, "OrderStateDto.g.cs").ShouldNotContain("Legacy");
        CompileWithGenerated(CompileWithInTreeAttributes(Entities, ShopProfile), fluent);
    }

    [TestMethod]
    public void Fluent_rules_win_over_attributes_and_json()
    {
        const string profile = """
            using Nextended.Core.CodeGen;
            using Shop.Domain;

            public sealed class Rules : DtoConfig<Order>
            {
                public Rules()
                {
                    Suffix("Model");
                    Include(x => x.InternalNote);                   // [IgnoreOnGeneration] on the entity
                    Property(x => x.Number).PropertyName("OrderNo"); // [GenerationPropertySetting(PropertyName = "No")]
                    Include("Total");                               // json PropertiesToIgnore
                }
            }
            """;
        var (files, diagnostics) = Run(Config(c => c.PropertiesToIgnore = ["Total"]), AttributedEntities, profile);

        NoDiagnostics(diagnostics);
        var order = File(files, "OrderModel.g.cs");
        order.ShouldContain("class OrderModel");
        order.ShouldContain("InternalNote { get; set; }");
        order.ShouldContain("OrderNo { get; set; }");
        order.ShouldNotContain(" No { get; set; }");
        order.ShouldContain("Total { get; set; }");
    }

    [TestMethod]
    public void Defaults_override_json_but_attributes_still_win_over_defaults()
    {
        const string entities = """
            using Nextended.Core.Attributes;
            namespace Shop.Domain;

            [AutoGenerateDto]
            public class Customer { public string Name { get; set; } = ""; public string? Secret { get; set; } }

            [AutoGenerateDto(Namespace = "Shop.Special")]
            public class Supplier { public string Name { get; set; } = ""; }
            """;
        const string profile = """
            using Nextended.Core.CodeGen;
            using Nextended.Core.Enums;

            public sealed class Defaults : CodeGenConfig
            {
                public Defaults()
                {
                    Defaults(d => d
                        .Namespace("Shop.Api")
                        .PropertiesToIgnore("Secret")
                        .InitializeCollections()
                        .DefaultMappingSettings(m => m.Strategy(DtoMappingStrategy.Extensions).SkipReverseMapping()));
                }
            }
            """;
        var config = Config();
        var (files, diagnostics) = Run(config, entities, profile);

        NoDiagnostics(diagnostics);
        File(files, "CustomerDto.g.cs").ShouldContain("namespace Shop.Api");
        File(files, "CustomerDto.g.cs").ShouldNotContain("Secret");
        File(files, "SupplierDto.g.cs").ShouldContain("namespace Shop.Special");
        files.Where(f => f.FileName.StartsWith("MappingExtensions")).ShouldAllBe(f => !f.Content.Contains("ToNet("));
        config.Namespace.ShouldBe("Shop.Contracts"); // the given configuration object stays untouched
    }

    [TestMethod]
    public void Namespace_rules_apply_to_a_group_and_type_rules_win_over_them()
    {
        const string entities = """
