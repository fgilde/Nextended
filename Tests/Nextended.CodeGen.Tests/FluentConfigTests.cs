    [TestMethod]
    public void Dynamic_code_is_reported_and_never_silently_ignored()
    {
        const string profile = """
            using System;
            using Nextended.Core.CodeGen;
            using Shop.Domain;

            public sealed class Dynamic : CodeGenConfig
            {
                private static string Compute() => "X";

                public Dynamic()
                {
                    var suffix = "Dto";                                  // a statement that is not a call
                    Dto<Order>(o => o.Suffix(suffix));                   // a variable
                    Dto<OrderLine>(l => l.Suffix(Compute()));            // a computed value
                    if (DateTime.Now.Year > 2000)                        // a statement that is not a call
                        Dto<Entity>();
                    Dto<Order>(o => o.Ignore(x => x.Number.Length));     // a nested selector
                    Console.WriteLine("hello");                          // a call outside the API
                    Dto<OrderLine>(l => l.Suffix("Line"));               // readable: applied
                }
            }
            """;
        var (files, diagnostics) = Run(Config(), Entities, profile);

        diagnostics.Count(d => d.Id == "NCG020").ShouldBe(6, string.Join(Environment.NewLine, diagnostics));
        diagnostics.Where(d => d.Id == "NCG020").ShouldAllBe(d => d.Severity == DiagnosticSeverity.Error && d.Location.IsInSource);
        files.ShouldContain(f => f.FileName == "OrderLineLine.g.cs");
    }

