    [TestMethod]
    public void Fluent_views_refine_attribute_views_and_order_their_members()
    {
        const string entities = """
            using System;
            using Nextended.Core.Attributes;
            namespace Shop.Domain;

            public abstract class Entity { public Guid Id { get; set; } public DateTime CreatedUtc { get; set; } }

            [AutoGenerateDto]
            [AutoGenerateDto(GeneratedClassName = "QuoteAbp")]
            public class Quote : Entity
            {
                public string Number { get; set; } = "";
                public decimal Price { get; set; }
                public string? Note { get; set; }
            }
            """;
        const string profile = """
            using Nextended.Core.CodeGen;
            using Shop.Domain;

            public sealed class QuoteConfig : DtoConfig<Quote>
            {
                public QuoteConfig()
                {
                    View("QuoteAbp", v => v.BaseMembersFirst().Property(x => x.CreatedUtc).PropertyName("CreationTime"));
                    View("QuoteRow", v => v.Order(x => x.Price, x => x.Number).Ignore(x => x.Note).ToDtoMethodName("ToRow"));
                }
            }
            """;
        var (files, diagnostics) = Run(Config(), entities, profile);

        NoDiagnostics(diagnostics);
        var abp = File(files, "QuoteAbpDto.g.cs");
        var classPart = abp.Substring(abp.IndexOf("class QuoteAbpDto", StringComparison.Ordinal));
        classPart.IndexOf(" Id {", StringComparison.Ordinal).ShouldBeLessThan(classPart.IndexOf(" Number {", StringComparison.Ordinal));
        classPart.ShouldContain("CreationTime { get; set; }");

        var row = File(files, "QuoteRowDto.g.cs");
        var rowClass = row.Substring(row.IndexOf("class QuoteRowDto", StringComparison.Ordinal));
        rowClass.IndexOf(" Price {", StringComparison.Ordinal).ShouldBeLessThan(rowClass.IndexOf(" Number {", StringComparison.Ordinal));
        rowClass.ShouldNotContain("Note");
        files.ShouldContain(f => f.Content.Contains("QuoteRowDto ToRow("));
        CompileWithGenerated(CompileWithInTreeAttributes(entities, profile), files);
    }

