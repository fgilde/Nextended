    private static DtoGenerationConfig Config(Action<DtoGenerationConfig>? configure = null)
    {
        var config = new DtoGenerationConfig
        {
            Namespace = "Shop.Contracts",
            CreateFileHeaders = false,
            CreateRegions = false,
            CreateComments = false
        };
        configure?.Invoke(config);
        return config;
    }

    private static (List<GeneratedFile> Files, List<Diagnostic> Diagnostics) Run(DtoGenerationConfig config, params string[] sources)
        => GenerateWithDiagnostics(CompileWithInTreeAttributes(sources), config);

    private static string File(IEnumerable<GeneratedFile> files, string name)
        => files.SingleOrDefault(f => f.FileName == name)?.Content ?? throw new ShouldAssertException($"{name} not generated: {string.Join(", ", files.Select(f => f.FileName))}");

    private static void NoDiagnostics(IEnumerable<Diagnostic> diagnostics)
        => diagnostics.Where(d => d.Severity >= DiagnosticSeverity.Warning).ShouldBeEmpty();

