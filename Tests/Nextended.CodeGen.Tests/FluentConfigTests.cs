                    Facet(x => x.Port, o => o.Label("Port"));
                }
            }
            """;
        var compilation = CompileWithInTreeAttributes(FacetEntities, profile);
        var file = Generators.FacetRegistration.FacetRegistrationGenerator.Generate(compilation, out var diagnostic);

        diagnostic.ShouldBeNull();
        file!.Content.ShouldContain("FacetRegistry.Register(typeof(global::Shop.Domain.Shipment), \"Hidden\");");
        file.Content.ShouldContain("f.Label = \"Port\";");
        // the facets do not change the DTO
        var (withFacets, diagnostics) = Run(Config(), FacetEntities, profile);
        NoDiagnostics(diagnostics);
        var (plain, _) = Run(Config(), FacetEntities, profile.Replace("Facet(x => x.Hidden);", "").Replace("Facet(x => x.Port, o => o.Label(\"Port\"));", ""));
        withFacets.Select(f => (f.FileName, f.Content)).ShouldBe(plain.Select(f => (f.FileName, f.Content)));

        Generators.FacetRegistration.FacetRegistrationGenerator.Generate(CompileWithInTreeAttributes(FacetEntities), out _).ShouldBeNull();
    }
