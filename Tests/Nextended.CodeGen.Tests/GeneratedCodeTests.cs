namespace Nextended.CodeGen.Tests;

/// <summary>
/// [GeneratedCode("Nextended.CodeGen", ...)] on every generated type (GeneratedCodeAttribute / GeneratedCodeVersion) and the TypeScript
/// selection by type attributes (IncludeTypesWithAttributes).
/// </summary>
[TestClass]
public class GeneratedCodeTests
{
    private const string Line = "[global::System.CodeDom.Compiler.GeneratedCode(\"Nextended.CodeGen\", null)]";

    private const string Entities = """
        using System;
        using System.Collections.Generic;
        using Nextended.Core.Attributes;
        using Nextended.Core.Enums;

        namespace Shop.Domain;

        [AutoGenerateDto(Namespace = "Shop.Contracts")]
        public class Order
        {
            public string Number { get; set; } = "";
            public OrderState State { get; set; }
            public List<OrderLine> Lines { get; set; } = [];
        }

        [AutoGenerateDto(Namespace = "Shop.Contracts", MappingStrategy = DtoMappingStrategy.Mapperly)]
        public class OrderLine { public string Sku { get; set; } = ""; }

        [AutoGenerateDto(Namespace = "Shop.Contracts")]
        public enum OrderState { Draft, Placed }

        [AutoGenerateDto(Namespace = "Shop.Contracts", KeepAttributesOnGeneratedClass = true)]
        [System.CodeDom.Compiler.GeneratedCode("OtherTool", "1.0")]
        public class Imported { public int Id { get; set; } }

        [AutoGenerateDto(Namespace = "Shop.Contracts", PreClassString = "[System.CodeDom.Compiler.GeneratedCode(\"Mine\", null)]")]
        public class Written { public int Id { get; set; } }
        """;

    private static DtoGenerationConfig Config(Action<DtoGenerationConfig>? configure = null)
    {
        var config = new DtoGenerationConfig
        {
            Namespace = "Shop.Mapping",
            OutputPath = "dtos/",
            MappingOutputPath = "mapping/",
            CreateFileHeaders = false,
            CreateRegions = false,
            CreateComments = false
        };
        configure?.Invoke(config);
        return config;
    }

    private static int Count(string text, string part) => Regex.Matches(text, Regex.Escape(part)).Count;

    private static string File(IEnumerable<GeneratedFile> files, string name)
        => files.SingleOrDefault(f => f.FileName == name)?.Content ?? throw new ShouldAssertException($"{name} not generated: {string.Join(", ", files.Select(f => f.FileName))}");

    [TestMethod]
    public void Every_generated_type_carries_the_attribute_once()
    {
        var compilation = CompileWithInTreeAttributes(Entities);
        var files = Generate(compilation, Config());

        var order = File(files, "OrderDto.g.cs");
        Count(order, Line).ShouldBe(2);                                           // the interface and the class
        order.ShouldContain($"\t{Line}\n\tpublic partial interface IOrderDto".Replace("\n", Environment.NewLine));
        order.ShouldContain($"\t{Line}\n\tpublic partial class OrderDto".Replace("\n", Environment.NewLine));
        Count(File(files, "OrderStateDto.g.cs"), Line).ShouldBe(1);               // the enum
        File(files, "OrderLineMapper.g.cs").ShouldContain($"\t{Line}{Environment.NewLine}\t[Mapper(");
        // a partial container shared by many files may carry it once at most: none of its parts gets it
        files.Where(f => f.FileName.StartsWith("MappingExtensions")).ShouldAllBe(f => !f.Content.Contains("GeneratedCode"));

        // never twice: a kept [GeneratedCode] or one in PreClassString stands alone
        var imported = File(files, "ImportedDto.g.cs");
        Count(imported, "GeneratedCode(").ShouldBe(2);                            // the interface gets ours, the class keeps its own
        imported.ShouldContain("GeneratedCode(\"OtherTool\", \"1.0\")");
        var written = File(files, "WrittenDto.g.cs");
        Count(written, "GeneratedCode(").ShouldBe(2);                             // the interface gets ours, the class has the PreClassString's
        Count(written, "GeneratedCode(\"Mine\"").ShouldBe(1);

        CompileWithGenerated(compilation, files);
    }

    [TestMethod]
    public void Switched_off_the_output_is_the_one_without_the_attribute()
    {
        var compilation = CompileWithInTreeAttributes(Entities);
        var on = Generate(compilation, Config());
        var off = Generate(compilation, Config(c => c.GeneratedCodeAttribute = false));

        off.ShouldAllBe(f => !f.Content.Contains(Line));
        off.Select(f => (f.FileName, f.Content)).ShouldBe(on.Select(f => (f.FileName, f.Content.Replace("\t" + Line + Environment.NewLine, ""))));

        // the same with the fluent defaults (also for the facet registration)
        const string profile = """
            using Nextended.Core.CodeGen;
            public sealed class P : CodeGenConfig
            {
                public P() { Defaults(d => d.GeneratedCodeAttribute(false)); Dto<Shop.Domain.Order>(o => o.Facet(x => x.Number, f => f.Label("No"))); }
            }
            """;
        var fluent = Generate(CompileWithInTreeAttributes(Entities, profile), Config());
        fluent.ShouldAllBe(f => !f.Content.Contains(Line));
        var withProfile = CompileWithInTreeAttributes(Entities, profile);
        FacetRegistrationGenerator.Generate(withProfile, out _)!.Content.ShouldContain("GeneratedCode");
        FacetRegistrationGenerator.Generate(withProfile, out _, generatedCode: false)!.Content.ShouldNotContain("GeneratedCode");
    }

    [TestMethod]
    public void GeneratedCodeVersion_writes_the_package_version_of_the_generator()
    {
        var files = Generate(CompileWithInTreeAttributes(Entities), Config(c => c.GeneratedCodeVersion = true));

        var version = typeof(DtoGenerator).Assembly.GetCustomAttributes(typeof(System.Reflection.AssemblyMetadataAttribute), false)
            .OfType<System.Reflection.AssemblyMetadataAttribute>().Single(a => a.Key == "PackageVersion").Value;
        version.ShouldNotBeNullOrWhiteSpace();
        File(files, "OrderDto.g.cs").ShouldContain($"[global::System.CodeDom.Compiler.GeneratedCode(\"Nextended.CodeGen\", \"{version}\")]");
    }

    [TestMethod]
    public void Structure_and_Excel_generations_mark_their_types_and_can_switch_it_off()
    {
        string Source(string name, [System.Runtime.CompilerServices.CallerFilePath] string file = "")
            => Path.GetFullPath(Path.Combine(Path.GetDirectoryName(file)!, "..", "TestProjects", "CodeGenSample", "Sources", name)).Replace(Path.DirectorySeparatorChar, '/');
        string Profile(string structure, string excel) => $$"""
            using Nextended.Core.CodeGen;
            public sealed class P : CodeGenConfig
            {
                public P()
                {
                    StructureGeneration(s => s.SourceFile("{{Source("appsettings.json")}}").Namespace("Shop.Settings").RootClassName("Settings"){{structure}});
                    ExcelGeneration(e => e.SourceFile("{{Source("scac_codes.xlsx")}}").Namespace("Shop.Scac").RootClassName("Scac").StaticClassName("ScacTable"){{excel}});
                }
            }
            """;
        Dictionary<string, string> Run(string profile)
            => CSharpGeneratorDriver.Create(new MainGenerator()).RunGenerators(CompileWithInTreeAttributes(profile)).GetRunResult()
                .GeneratedTrees.ToDictionary(t => Path.GetFileName(t.FilePath), t => t.ToString());

        var on = Run(Profile("", ""));
        on["appsettings.g.cs"].ShouldContain("\t" + Line + "\n\tpublic partial class Settings");
        on["scac_codes.row.g.cs"].ShouldContain("    " + Line);
        on["scac_codes.table.g.cs"].ShouldContain("    " + Line);
        on["scac_codes.table.g.cs"].IndexOf(Line).ShouldBeLessThan(on["scac_codes.table.g.cs"].IndexOf("public static partial class ScacTable"));

        var off = Run(Profile(".GeneratedCodeAttribute(false)", ".GeneratedCodeAttribute(false)"));
        off["appsettings.g.cs"].ShouldNotContain("GeneratedCode");
        off["scac_codes.row.g.cs"].ShouldNotContain("GeneratedCode");
        off["scac_codes.table.g.cs"].ShouldNotContain("GeneratedCode");
    }

    // ---------------------------------------------------------------- TypeScript: IncludeTypesWithAttributes

    private const string Remote = """
        namespace Remote.Contracts;
        [System.CodeDom.Compiler.GeneratedCode("Nextended.CodeGen", null)] public class RemoteDto { public int Id { get; set; } }
        [System.CodeDom.Compiler.GeneratedCode("Nextended.CodeGen", null)] public class ExcludedDto { public int Id { get; set; } }
        public class Unmarked { public int Id { get; set; } }
        """;

    private const string Local = """
        namespace App.Contracts;
        public sealed class MarkerAttribute : System.Attribute { }
        [Marker] public class Marked { public string Name { get; set; } = ""; }
        [Marker] public interface IMarked { string Name { get; } }
        public class Plain { public int X { get; set; } }
        """;

    private static Compilation WithRemote(params string[] sources)
    {
        var remote = Compile(Remote).WithAssemblyName("Remote.Contracts");
        using var image = new MemoryStream();
        remote.Emit(image).Success.ShouldBeTrue();
        return CompileWithInTreeAttributes(sources).AddReferences(MetadataReference.CreateFromImage(image.ToArray()));
    }

    [TestMethod]
    public void IncludeTypesWithAttributes_selects_marked_types_of_the_project_and_of_referenced_assemblies()
    {
        var config = new TypescriptGenerationConfig
        {
            IncludeTypesWithAttributes = ["GeneratedCode=Nextended.CodeGen", "App.Contracts.Marker"], // not [GeneratedCode] of other tools
            ExcludeTypes = ["Remote.Contracts.ExcludedDto"],                     // Exclude wins
            Barrel = false
        };

        var files = TypescriptGenerator.Generate(WithRemote(Local), config).Files;

        files.Keys.ShouldBe(["App/Contracts/Marked.ts", "Remote/Contracts/RemoteDto.ts"]); // interfaces only by name, unmarked types not
    }

    [TestMethod]
    public void IncludeTypesWithAttribute_of_the_fluent_configuration()
    {
        const string profile = """
            using Nextended.Core.CodeGen;
            public sealed class P : CodeGenConfig
            {
                public P() { Typescript(t => t.IncludeTypesWithAttribute<System.CodeDom.Compiler.GeneratedCodeAttribute>("Nextended.CodeGen").IncludeTypesWithAttributes("Marker")); }
            }
            """;
        var compilation = WithRemote(Local, profile);

        var config = TypescriptGenerator.FluentGenerations(compilation).Single();

        config.IncludeTypesWithAttributes.ShouldBe(["System.CodeDom.Compiler.GeneratedCodeAttribute=Nextended.CodeGen", "Marker"]);
        config.Barrel = false;
        TypescriptGenerator.Generate(compilation, config).Files.Keys
            .ShouldBe(["App/Contracts/Marked.ts", "Remote/Contracts/ExcludedDto.ts", "Remote/Contracts/RemoteDto.ts"]);
    }

    [TestMethod]
    public void IncludeTypesWithAttributes_with_FromGeneratedDtos_finds_the_DTOs_of_the_same_run()
    {
        var compilation = CompileWithInTreeAttributes(Entities);
        var dtoGenerator = new DtoGenerator(Config(c => { c.OutputPath = null; c.MappingOutputPath = null; }));
        var dtoFiles = dtoGenerator.Execute(compilation).ToList();
        // Shop.Domain.Imported carries a [GeneratedCode] of another tool, Nextended.Core one on its resources: excluded
        var config = new TypescriptGenerationConfig { IncludeTypesWithAttributes = ["GeneratedCode"], ExcludeNamespaces = ["Shop.Domain"], ExcludeTypes = ["*.Resources"], Barrel = false };

        // the DTOs of this run are not in the compilation yet: only FromGeneratedDtos adds them (the attribute selects nothing else here)
        TypescriptGenerator.Generate(compilation, config, dtoFiles, dtoGenerator.GeneratedDtos()).Files.ShouldBeEmpty();
        config.FromGeneratedDtos = true;
        var files = TypescriptGenerator.Generate(compilation, config, dtoFiles, dtoGenerator.GeneratedDtos()).Files;
        files.Keys.ShouldContain("Shop/Contracts/OrderDto.ts");
        files.Keys.ShouldContain("Shop/Contracts/OrderStateDto.ts");
        files.Keys.ShouldNotContain(k => k.StartsWith("Shop/Domain/"));
    }
}
