using System.Reflection;
using System.Runtime.Loader;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Nextended.CodeGen.Config;
using Nextended.CodeGen.Contracts;
using Nextended.CodeGen.Generators.DtoGeneration;
using Nextended.Core.Attributes;
using Riok.Mapperly;
using Riok.Mapperly.Abstractions;
using Shouldly;

namespace Nextended.CodeGen.Tests;

/// <summary>Compiles sources, runs the DTO generator over them and, if asked, compiles and loads the result (with Mapperly).</summary>
internal static class TestCompilation
{
    public static List<GeneratedFile> Generate(Compilation compilation, DtoGenerationConfig config)
        => new DtoGenerator(config).Execute(compilation).ToList();

    public static SyntaxTree Parse(string source, string path = "")
        => CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.Latest), path);

    public static CSharpCompilation Compile(params string[] sources)
    {
        var references = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!)
            .Split(Path.PathSeparator)
            .Append(typeof(AutoGenerateDtoAttribute).Assembly.Location)
            .Append(typeof(MapperAttribute).Assembly.Location)
            .Distinct()
            .Select(p => MetadataReference.CreateFromFile(p));
        return CSharpCompilation.Create("Shop", sources.Select((s, i) => Parse(s, $"Source{i}.cs")), references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
    }

    /// <summary>Runs the DTO generator and returns its files and diagnostics.</summary>
    public static (List<GeneratedFile> Files, List<Diagnostic> Diagnostics) GenerateWithDiagnostics(Compilation compilation, DtoGenerationConfig config)
    {
        var generator = new DtoGenerator(config);
        var files = generator.Execute(compilation).ToList();
        return (files, generator.Diagnostics.ToList());
    }

    /// <summary>
    /// Like <see cref="Compile"/>, but against the attribute and fluent configuration (Nextended.Core.CodeGen) sources of the in-tree Nextended.Core instead of the released package the
    /// generator references: tests of attribute settings that are not released yet. The package stays referenced under an alias.
    /// </summary>
    public static CSharpCompilation CompileWithInTreeAttributes(params string[] sources)
    {
        var core = Path.GetFullPath(Path.Combine(RepoDir(), "Nextended.Core"));
        var attributeSources = new[]
            {
                "Attributes/AutoGenerateDtoAttribute.cs", "Attributes/GenerationPropertySettingAttribute.cs", "Attributes/IgnoreOnGenerationAttribute.cs",
                "Attributes/GenerateBeforeAndAfterAssignPartialsInMappingAttribute.cs", "Enums/Modifier.cs", "Enums/InterfaceProperty.cs", "Enums/DtoMappingStrategy.cs",
                "Enums/GeneratedModelType.cs", "Enums/JsonArrayGeneration.cs", "CodeGen/CodeGenConfig.cs", "CodeGen/DtoConfig.cs"
            }
            .Select(f => "#nullable disable warnings\n" + File.ReadAllText(Path.Combine(core, f)));
        var references = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!)
            .Split(Path.PathSeparator)
            .Where(p => !string.Equals(Path.GetFileName(p), "Nextended.Core.dll", StringComparison.OrdinalIgnoreCase))
            .Append(typeof(MapperAttribute).Assembly.Location)
            .Distinct()
            .Select(p => MetadataReference.CreateFromFile(p))
            .Append(MetadataReference.CreateFromFile(typeof(AutoGenerateDtoAttribute).Assembly.Location, new MetadataReferenceProperties(aliases: ["releasedcore"])));
        return CSharpCompilation.Create("Shop", sources.Concat(attributeSources).Select((s, i) => Parse(s, $"Source{i}.cs")), references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
    }

    private static string RepoDir([System.Runtime.CompilerServices.CallerFilePath] string file = "")
        => Path.Combine(Path.GetDirectoryName(file)!, "..", "..");

    /// <summary>Adds the generated files, runs Mapperly and fails on any warning or error.</summary>
    public static Compilation CompileWithGenerated(Compilation compilation, IEnumerable<GeneratedFile> files)
    {
        var withGenerated = compilation.AddSyntaxTrees(files.Select(f => Parse(f.Content, f.FileName)));
        CSharpGeneratorDriver.Create(new MapperGenerator())
            .RunGeneratorsAndUpdateCompilation(withGenerated, out var final, out _);
        var problems = final.GetDiagnostics().Where(d => d.Severity >= DiagnosticSeverity.Warning).ToList();
        problems.ShouldBeEmpty(string.Join(Environment.NewLine, problems));
        return final;
    }

    public static Assembly Load(Compilation compilation)
    {
        using var stream = new MemoryStream();
        var result = compilation.Emit(stream);
        result.Success.ShouldBeTrue(string.Join(Environment.NewLine, result.Diagnostics));
        stream.Position = 0;
        return new AssemblyLoadContext(null, isCollectible: true).LoadFromStream(stream);
    }

    public static object New(Assembly assembly, string type, params (string Name, object? Value)[] values)
    {
        var instance = Activator.CreateInstance(assembly.GetType(type)!)!;
        foreach (var (name, value) in values)
            instance.GetType().GetProperty(name)!.SetValue(instance, value);
        return instance;
    }

    public static object Invoke(Assembly assembly, string type, string method, object argument)
        => assembly.GetType(type)!.GetMethods().Single(m => m.Name == method && m.GetParameters().Length == 1 && m.GetParameters()[0].ParameterType == argument.GetType())
            .Invoke(null, [argument])!;

    public static object? Get(object instance, string property) => instance.GetType().GetProperty(property)!.GetValue(instance);
}
