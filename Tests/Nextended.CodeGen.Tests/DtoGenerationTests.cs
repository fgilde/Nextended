    private const string Shop = """
        using System;
        using System.Collections.Generic;
        using Nextended.Core.Attributes;

        namespace Shop.Domain;

        [AutoGenerateDto]
        public class Line { public string? Sku { get; set; } }

        [AutoGenerateDto]
        public class Order
        {
            public string? Number { get; set; }
            public List<Line> Lines { get; set; } = new();
            public ICollection<int> Ids { get; set; } = new List<int>();
            public string[] Tags { get; set; } = Array.Empty<string>();
            public Dictionary<string, int> Counts { get; set; } = new();
            public List<int>? Maybe { get; set; }
        }

        [AutoGenerateDto(AutoGenerateDerived = true)]
        public abstract class Entity { public Guid Id { get; set; } }
        public class Connector : Entity { public string? Name { get; set; } }
        public class SubConnector : Connector { }
        [AutoGenerateDto]
        public class OwnConnector : Connector { }
        public class Customer : Entity { }
        """;

    [TestMethod]
    public void InitializeCollections_initializes_collection_members()
    {
        var compilation = Compile(Shop);
        Generate(compilation, Config()).ShouldAllBe(f => !f.Content.Contains("= [];"));

        var files = Generate(compilation, Config(c => c.InitializeCollections = true));
        var order = File(files, "OrderDto.g.cs");
        order.ShouldContain("public System.Collections.Generic.List<Shop.Contracts.LineDto> Lines { get; set; } = [];");
        order.ShouldContain("public System.Collections.Generic.ICollection<int> Ids { get; set; } = [];");
        order.ShouldContain("public string[] Tags { get; set; } = [];");
        order.ShouldContain("public System.Collections.Generic.Dictionary<string, int> Counts { get; set; } = [];");
        order.ShouldContain("public System.Collections.Generic.List<int>? Maybe { get; set; }\r\n");
        order.ShouldContain("public string? Number { get; set; }\r\n");
        CompileWithGenerated(compilation, files);
    }

    [TestMethod]
    public void SkipReverseMapping_generates_only_the_mapping_to_the_dto()
    {
        var compilation = Compile(Shop);
        File(Generate(compilation, Config()), "MappingExtensions.g.Order.cs").ShouldContain(" ToNet(");

        var files = Generate(compilation, Config(c => c.DefaultMappingSettings = new DefaultMappingSettings { SkipReverseMapping = true }));
        var order = File(files, "MappingExtensions.g.Order.cs");
        order.ShouldNotContain(" ToNet(");
        order.ShouldContain("AssignTo(this Shop.Domain.Order src");
        order.ShouldNotContain("AssignTo(this Shop.Contracts.OrderDto src");
        CompileWithGenerated(compilation, files);

        files = Generate(compilation, Config(c => c.DefaultMappingSettings = new DefaultMappingSettings { SkipReverseMapping = true, Strategy = DtoMappingStrategy.Mapperly }));
        var mapper = File(files, "OrderMapper.g.cs");
        mapper.ShouldContain(" ToDto(this Shop.Domain.Order src);");
        mapper.ShouldNotContain(" ToNet(");
        mapper.ShouldNotContain("AssignTo(this Shop.Contracts.OrderDto src");
        CompileWithGenerated(compilation, files);
    }

    [TestMethod]
    public void TypesToIgnore_leaves_out_a_type_and_what_derives_from_it_through_AutoGenerateDerived()
    {
        var compilation = Compile(Shop);
        Generate(compilation, Config()).Select(f => f.FileName).ShouldContain("SubConnectorDto.g.cs");

        var names = Generate(compilation, Config(c => c.TypesToIgnore = ["Shop.Domain.Connector"])).Select(f => f.FileName).ToList();
        names.ShouldNotContain("ConnectorDto.g.cs");
        names.ShouldNotContain("SubConnectorDto.g.cs");
        names.ShouldContain("OwnConnectorDto.g.cs"); // has an attribute of its own
        names.ShouldContain("CustomerDto.g.cs");
        Generate(compilation, Config(c => c.TypesToIgnore = ["SubConnector"])).Select(f => f.FileName).ShouldNotContain("SubConnectorDto.g.cs");
    }

    // ---------------------------------------------------------------- Mapperly: derived types

    private const string Documents = """
        using System.Collections.Generic;
        using Nextended.Core.Attributes;

        namespace Shop.Domain;

        [AutoGenerateDto(AutoGenerateDerived = true)]
        public abstract class Document { public string? Name { get; set; } }
        public class Invoice : Document { public decimal Total { get; set; } }
        public class CreditNote : Invoice { public string? Reason { get; set; } }
        public class Packing : Document { }

        // abstract, but no DTO carries it as a member: no mapper of its own
        [AutoGenerateDto(AutoGenerateDerived = true)]
        public abstract class Party { public string? Name { get; set; } }
        public class Person : Party { }

        [AutoGenerateDto]
        public class Shipment
        {
            public string? Number { get; set; }
            public Document? Main { get; set; }
            public List<Document> Documents { get; set; } = new();
            public Invoice? Invoice { get; set; }
        }
        """;

    [TestMethod]
    public void MapDerivedTypes_maps_abstract_members_to_the_dto_of_their_runtime_type()
    {
        var compilation = Compile(Documents);
        var plain = Generate(compilation, Config(c => c.DefaultMappingSettings = new DefaultMappingSettings { Strategy = DtoMappingStrategy.Mapperly }));
        plain.Select(f => f.FileName).ShouldNotContain("DocumentMapper.g.cs");
        plain.ShouldAllBe(f => !f.Content.Contains("MapDerivedType"));

        var files = Generate(compilation, Config(c => c.DefaultMappingSettings = new DefaultMappingSettings { Strategy = DtoMappingStrategy.Mapperly, MapDerivedTypes = true }));
        var document = File(files, "DocumentMapper.g.cs");
        document.ShouldContain("[MapDerivedType(typeof(Shop.Domain.CreditNote), typeof(Shop.Contracts.CreditNoteDto))]\r\n\t\t[MapDerivedType(typeof(Shop.Domain.Invoice), typeof(Shop.Contracts.InvoiceDto))]");
        document.ShouldContain("public static partial Shop.Contracts.DocumentDto ToDto(this Shop.Domain.Document src);");
        document.ShouldContain("public static partial Shop.Domain.Document ToNet(this Shop.Contracts.DocumentDto src);");
        File(files, "MappingExtensions.g.Document.cs").ShouldContain("Func<Shop.Contracts.DocumentDto> factory"); // kept
        files.Select(f => f.FileName).ShouldNotContain("PartyMapper.g.cs");
        File(files, "ShipmentMapper.g.cs").ShouldContain("[UseStaticMapper(typeof(Shop.Contracts.DocumentMapper))]");
        File(files, "InvoiceMapper.g.cs").ShouldContain("[MapDerivedType(typeof(Shop.Domain.CreditNote), typeof(Shop.Contracts.CreditNoteDto))]");

        var assembly = Load(CompileWithGenerated(compilation, files));
        var credit = New(assembly, "Shop.Domain.CreditNote", ("Name", "c1"), ("Reason", "damaged"));
        var packing = New(assembly, "Shop.Domain.Packing", ("Name", "p1"));
        var shipment = New(assembly, "Shop.Domain.Shipment", ("Number", "S1"), ("Main", credit), ("Invoice", credit));
        var list = Get(shipment, "Documents")!;
        list.GetType().GetMethod("Add")!.Invoke(list, [packing]);

        var dto = Invoke(assembly, "Shop.Contracts.ShipmentMapper", "ToDto", shipment);
        Get(dto, "Main")!.GetType().Name.ShouldBe("CreditNoteDto");
        Get(Get(dto, "Main")!, "Reason").ShouldBe("damaged");
        Get(dto, "Invoice")!.GetType().Name.ShouldBe("CreditNoteDto");
        ((System.Collections.IEnumerable)Get(dto, "Documents")!).Cast<object>().Single().GetType().Name.ShouldBe("PackingDto");

        var back = Invoke(assembly, "Shop.Contracts.ShipmentMapper", "ToNet", dto);
        Get(back, "Main")!.GetType().Name.ShouldBe("CreditNote");
    }
