using Nextended.CodeGen.Config;
using Nextended.CodeGen.Contracts;
using Nextended.Core.Enums;
using Shouldly;
using static Nextended.CodeGen.Tests.TestCompilation;

namespace Nextended.CodeGen.Tests;

[TestClass]
public class DtoGenerationTests
{
    private static DtoGenerationConfig Config(Action<DtoGenerationConfig>? configure = null)
    {
        var config = new DtoGenerationConfig
        {
            Namespace = "Shop.Contracts",
            OutputPath = "dtos/",
            MappingOutputPath = "mapping/",
            DeepProperties = true,
            CreateFileHeaders = false,
            CreateRegions = false,
            CreateComments = false
        };
        configure?.Invoke(config);
        return config;
    }

    private static string File(IEnumerable<GeneratedFile> files, string name) => files.Single(f => f.FileName == name).Content;

    // ---------------------------------------------------------------- enums

    private const string Enums = """
        using System;
        using System.ComponentModel;
        using Nextended.Core.Attributes;

        namespace Shop.Domain;

        [Flags]
        [Description("states")]
        [AutoGenerateDto(GenerateMapping = false)]
        public enum State : short { None = 0, Booked = 1, Delayed = 2 }

        [AutoGenerateDto(GenerateMapping = false, PreClassString = "[System.Text.Json.Serialization.JsonConverter(typeof(System.Text.Json.Serialization.JsonStringEnumConverter))]")]
        public enum Mode { Sea, Air }

        [AutoGenerateDto(GenerateMapping = false, KeepAttributesOnGeneratedClass = true)]
        [Flags, Description("kept")]
        public enum Kept : byte { A = 1, B = 2 }
        """;

    [TestMethod]
    public void Enums_by_default_keep_neither_flags_nor_underlying_type()
    {
        var files = Generate(Compile(Enums), Config(c => c.PreClassString = "[System.Serializable]"));

        var state = File(files, "StateDto.g.cs");
        state.ShouldContain("public enum StateDto\r\n");
        state.ShouldNotContain("Flags");
        state.ShouldNotContain("Serializable"); // the configuration's PreClassString is meant for classes
        CompileWithGenerated(Compile(Enums), files);
    }

    [TestMethod]
    public void KeepEnumFlagsAndUnderlyingType_keeps_flags_and_underlying_type()
    {
        var files = Generate(Compile(Enums), Config(c => c.KeepEnumFlagsAndUnderlyingType = true));

        var state = File(files, "StateDto.g.cs");
        state.ShouldContain("\t[System.Flags]\r\n\tpublic enum StateDto : short\r\n");
        state.ShouldNotContain("Description");
        File(files, "ModeDto.g.cs").ShouldContain("public enum ModeDto\r\n"); // int stays implicit
        CompileWithGenerated(Compile(Enums), files);
    }

    [TestMethod]
    public void Enum_attribute_settings_apply_to_the_generated_enum()
    {
        var files = Generate(Compile(Enums), Config());

        File(files, "ModeDto.g.cs").ShouldContain(
            "[System.Text.Json.Serialization.JsonConverter(typeof(System.Text.Json.Serialization.JsonStringEnumConverter))]\r\n\tpublic enum ModeDto");
        var kept = File(files, "KeptDto.g.cs");
        kept.ShouldContain("\t[System.Flags]\r\n\t[System.ComponentModel.Description(\"kept\")]\r\n\tpublic enum KeptDto\r\n");

        files = Generate(Compile(Enums), Config(c => c.KeepEnumFlagsAndUnderlyingType = true));
        File(files, "KeptDto.g.cs").ShouldContain("\t[System.Flags]\r\n\t[System.ComponentModel.Description(\"kept\")]\r\n\tpublic enum KeptDto : byte\r\n");
        CompileWithGenerated(Compile(Enums), files);
    }

    // ---------------------------------------------------------------- property attributes

    private const string Attributed = """
        using System.ComponentModel;
        using System.ComponentModel.DataAnnotations;
        using Nextended.Core.Attributes;

        namespace Shop.Domain;

        [AutoGenerateDto(GenerateMapping = false)]
        public enum Mode { Sea, Air }

        [AutoGenerateDto(GenerateMapping = false)]
        public class Address { public string? City { get; set; } }

        [AutoGenerateDto(GenerateMapping = false, KeepPropertyAttributesOnGeneratedClass = KEEP)]
        public class Row
        {
            [MaxLength(3)] public string? Country { get; set; }
            [Description("mode")] public Mode Mode { get; set; }
            [GenerationPropertySetting(PreClassString = "\t\t[System.ComponentModel.DisplayName(\"Total\")]")] public decimal Amount { get; set; }
            [Description("address")] public Address? Address { get; set; }
        }
        """;

    [TestMethod]
    public void Property_attributes_reach_scalar_members_of_the_class()
    {
        var source = Attributed.Replace("KEEP", "true");
        var files = Generate(Compile(source), Config());

        var row = File(files, "RowDto.g.cs");
        var cls = row[row.IndexOf("public partial class", StringComparison.Ordinal)..];
        cls.ShouldContain("\t\t[System.ComponentModel.DataAnnotations.MaxLength(3)]\r\n\t\tpublic string? Country { get; set; }");
        cls.ShouldContain("\t\t[System.ComponentModel.Description(\"mode\")]\r\n\t\tpublic Shop.Contracts.ModeDto Mode { get; set; }");
        cls.ShouldContain("\t\t[System.ComponentModel.DisplayName(\"Total\")]\r\n\t\tpublic decimal Amount { get; set; }");
        // a member typed by a DTO class keeps its attributes where they were: on the explicit interface implementation
        cls.ShouldContain("\t\tpublic Shop.Contracts.AddressDto? Address { get; set; }\r\n");
        cls.ShouldContain("\t\t[System.ComponentModel.Description(\"address\")]\r\n\t\tShop.Contracts.IAddressDto IRowDto.Address");
        CompileWithGenerated(Compile(source), files);
    }

    [TestMethod]
    public void Property_attributes_stay_off_without_the_setting()
    {
        var files = Generate(Compile(Attributed.Replace("KEEP", "false")), Config());

        var row = File(files, "RowDto.g.cs");
        row.ShouldNotContain("MaxLength");
        row.ShouldNotContain("Description");
        row.ShouldContain("DisplayName"); // the property's own PreClassString
    }

    // ---------------------------------------------------------------- generics

    private const string Generics = """
        using System.Collections.Generic;
        using Nextended.Core.Attributes;

        namespace Shop.Domain;

        [AutoGenerateDto(AutoGenerateDerived = true)]
        public class Unit { public string? Code { get; set; } }
        public class WeightUnit : Unit { }

        // the constraint type has its DTO only through Unit's AutoGenerateDerived
        [AutoGenerateDto]
        public class Measure<TUnit> where TUnit : WeightUnit
        {
            public decimal Value { get; set; }
            public TUnit? Unit { get; set; }
        }

        [AutoGenerateDto]
        public class Dimension<TUnit> where TUnit : Unit
        {
            public decimal? Value { get; set; }
            public TUnit? Unit { get; set; }
            public List<TUnit> History { get; set; } = new();
        }

        [AutoGenerateDto]
        public class Address { public string? City { get; set; } }

        [AutoGenerateDto(AutoGenerateDerived = true)]
        public abstract class Holder<T> { public T? Value { get; set; } }
        public class AddressHolder : Holder<Address> { public string? Name { get; set; } }
        public class NumberHolder : Holder<int> { }

        [AutoGenerateDto]
        public class Weight : Dimension<WeightUnit> { }
        """;

    [TestMethod]
    public void Constraint_names_the_dto_of_a_type_generated_through_AutoGenerateDerived()
    {
        var files = Generate(Compile(Generics), Config());

        var measure = File(files, "MeasureDto.g.cs");
        measure.ShouldContain("public partial interface IMeasureDto<TUnit>  where TUnit : WeightUnitDto");
        measure.ShouldContain("public partial class MeasureDto<TUnit> : IMeasureDto<TUnit> where TUnit : WeightUnitDto");
    }

    [TestMethod]
    public void Type_arguments_of_a_generic_base_are_replaced_by_their_dtos()
    {
        var files = Generate(Compile(Generics), Config());

        var holder = File(files, "AddressHolderDto.g.cs");
        holder.ShouldContain("public partial interface IAddressHolderDto : Shop.Contracts.IHolderDto<Shop.Contracts.AddressDto>");
        holder.ShouldContain("public partial class AddressHolderDto :  Shop.Contracts.HolderDto<Shop.Contracts.AddressDto>, IAddressHolderDto");
        File(files, "NumberHolderDto.g.cs").ShouldContain("Shop.Contracts.HolderDto<int>, INumberHolderDto");
    }

    [TestMethod]
    public void Generic_mappings_compile_and_map()
    {
        var compilation = Compile(Generics);
        var files = Generate(compilation, Config());

        var dimension = File(files, "MappingExtensions.g.Dimension.cs");
        dimension.ShouldContain("static void AssignTo<TUnit, TUnitDto>(this Shop.Domain.Dimension<TUnit> src, Shop.Contracts.DimensionDto<TUnitDto> dest) where TUnit : Shop.Domain.Unit where TUnitDto : UnitDto");
        dimension.ShouldContain("dest.Unit = src.Unit?.MapTo<TUnitDto>();");
        // a closed generic base whose arguments need no DTO is mapped through its AssignTo
        File(files, "MappingExtensions.g.NumberHolder.cs").ShouldContain("((Shop.Domain.Holder<int>)src).AssignTo(( HolderDto<int> )dest);");
        File(files, "MappingExtensions.g.Weight.cs").ShouldContain("((Shop.Domain.Dimension<Shop.Domain.WeightUnit>)src).AssignTo(( DimensionDto<Shop.Contracts.WeightUnitDto> )dest);");

        var assembly = Load(CompileWithGenerated(compilation, files));
        var unit = New(assembly, "Shop.Domain.WeightUnit", ("Code", "kg"));
        var weight = New(assembly, "Shop.Domain.Weight", ("Value", 12.5m), ("Unit", unit));
        var dto = Invoke(assembly, "Shop.Contracts.MappingExtensions", "ToDto", weight);
        Get(dto, "Value").ShouldBe(12.5m);
        Get(Get(dto, "Unit")!, "Code").ShouldBe("kg");
        var holder = New(assembly, "Shop.Domain.NumberHolder", ("Value", 7));
        Get(Invoke(assembly, "Shop.Contracts.MappingExtensions", "ToDto", holder), "Value").ShouldBe(7);
    }

    [TestMethod]
    public void Mapperly_maps_members_of_a_generic_base_with_dto_arguments()
    {
        var compilation = Compile(Generics);
        var files = Generate(compilation, Config(c => c.DefaultMappingSettings = new DefaultMappingSettings { Strategy = DtoMappingStrategy.Mapperly }));

        var assembly = Load(CompileWithGenerated(compilation, files));
        var address = New(assembly, "Shop.Domain.Address", ("City", "Kiel"));
        var holder = New(assembly, "Shop.Domain.AddressHolder", ("Name", "home"), ("Value", address));
        var dto = Invoke(assembly, "Shop.Contracts.AddressHolderMapper", "ToDto", holder);
        Get(dto, "Name").ShouldBe("home");
        Get(Get(dto, "Value")!, "City").ShouldBe("Kiel");
    }

