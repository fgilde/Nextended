using Nextended.Core.CodeGen;
using Nextended.Core.Enums;
using Sample.Contracts.Crm;
using Sample.Contracts.Pricing;
using Volo.Abp.Application.Dtos;

namespace Sample.CodeGen;

/// <summary>Two TypeScript generations of the same contracts. Read by Nextended.CodeGen at compile time, never executed.</summary>
public sealed class TsCodeGen : CodeGenConfig
{
    public TsCodeGen()
    {
        // enums as numbers (an ABP server), folders per namespace below Sample.Contracts, ABP paging from a hand-written module
        Typescript(t => t
            .OutputPath("ts")
            .EnumValues(TypescriptEnumValues.Number)
            .IncludeNamespaces("Sample.Contracts")
            .ExcludeNamespaces("Sample.Contracts.Pricing")
            .RootNamespace("Sample.Contracts")
            .TypeMap(typeof(PagedResultDto<>), "PagedResult from '../ts-support/abp'")
            .Type<CustomerDto>(c => c.Property(x => x.Email).Optional()));

        // enums as names (a server with JsonStringEnumConverter), const objects instead of enums (erasableSyntaxOnly), one flat folder, aliases for ids and dates
        Typescript(t => t
            .OutputPath("ts-const")
            .EnumValues(TypescriptEnumValues.String)
            .EnumStyle(TypescriptEnumStyle.Const)
            .Layout(TypescriptLayout.Flat)
            .RootNamespace("Sample.Contracts")
            .TypeAliases()
            .IncludeDerivedFrom(typeof(EntityDto<>))
            .Exclude<CustomerPage>()
            .Type<CustomerDto>(c => c.Name("Customer")));

        // pricing contracts (enums as numbers): own header (no eslint-disable), defaults optional, a declared union, options without their secrets
        Typescript(t => t
            .OutputPath("ts-pricing")
            .EnumValues(TypescriptEnumValues.Number)
            .Layout(TypescriptLayout.Flat)
            .IncludeNamespaces("Sample.Contracts.Pricing")
            .Header("// Generated by Nextended.CodeGen. Do not edit.")
            .Type<MarginQueryDto>(q => q.OptionalDefaultValues())
            .Type<Place>(p => p.DerivedTypes("*"))
            .Type<PortalOptions>(o => o.IncludeMembersWithAttribute<PublicAttribute>()));
    }
}
