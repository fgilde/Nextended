using System;
using Nextended.Core.Enums;

namespace Nextended.Core.CodeGen;

/// <summary>
/// Fluent configuration of Nextended.CodeGen for a whole project: defaults (the code form of codegen.json), the types to generate,
/// rules per namespace and per assembly, and the other generators. Derive from it and configure in the constructor.
/// <para>
/// The class is <b>read</b> by the source generator, never executed: only calls of this API with constant arguments, <c>typeof</c>,
/// <c>nameof</c>, member selectors (<c>x =&gt; x.Name</c>) and nested lambdas are allowed; anything else is reported (NCG020).
/// The methods do nothing at runtime.
/// </para>
/// </summary>
public abstract class CodeGenConfig : ICodeGenBuilder
{
    /// <inheritdoc />
    public ICodeGenBuilder Defaults(Action<IDtoDefaults> configure) => this;
    /// <inheritdoc />
    public ICodeGenBuilder ViewDefaults(Action<IDtoTypeBuilder> configure) => this;
    /// <inheritdoc />
    public ICodeGenBuilder Dto<T>(Action<IDtoBuilder<T>>? configure = null) => this;
    /// <inheritdoc />
    public ICodeGenBuilder Dto(Type type, Action<IDtoTypeBuilder>? configure = null) => this;
    /// <inheritdoc />
    public ICodeGenBuilder IgnoreType<T>() => this;
    /// <inheritdoc />
    public ICodeGenBuilder IgnoreType(Type type) => this;
    /// <inheritdoc />
    public ICodeGenBuilder ForNamespace(string @namespace, Action<IDtoTypeBuilder> configure) => this;
    /// <inheritdoc />
    public ICodeGenBuilder ForAssembly(string assemblyName, Action<ICodeGenBuilder> configure) => this;
    /// <inheritdoc />
    public ICodeGenBuilder ExcelGeneration(Action<IExcelGeneration> configure) => this;
    /// <inheritdoc />
    public ICodeGenBuilder StructureGeneration(Action<IStructureGeneration> configure) => this;
    /// <inheritdoc />
    public ICodeGenBuilder Typescript(Action<ITypescriptGeneration> configure) => this;
    /// <inheritdoc />
    public ICodeGenBuilder Facets<T>(Action<IFacets<T>> configure) => this;
}

/// <summary>The project level of the fluent configuration (see <see cref="CodeGenConfig"/>).</summary>
public interface ICodeGenBuilder
{
    /// <summary>Defaults for every DTO; the code form of the "DtoGeneration" section of codegen.json (overrides its values; attributes still win).</summary>
    ICodeGenBuilder Defaults(Action<IDtoDefaults> configure);

    /// <summary>
    /// Settings and member rules (by name) for every DTO view, attribute views included: <c>ViewDefaults(v =&gt; v.Namespace("X").OutputPath("Views/"))</c>.
    /// What a view sets itself wins (its fluent View(...) and the properties its [AutoGenerateDto] sets); so do member rules of the view and of its type.
    /// </summary>
    ICodeGenBuilder ViewDefaults(Action<IDtoTypeBuilder> configure);

    /// <summary>Generates a DTO of <typeparamref name="T"/> (no [AutoGenerateDto] needed) and configures it. Wins over the attributes of the type.</summary>
    ICodeGenBuilder Dto<T>(Action<IDtoBuilder<T>>? configure = null);

    /// <summary>Like <see cref="Dto{T}"/> for a type given by <c>typeof</c>, e.g. an open generic type <c>typeof(Page&lt;&gt;)</c>.</summary>
    ICodeGenBuilder Dto(Type type, Action<IDtoTypeBuilder>? configure = null);

    /// <summary>No DTO for <typeparamref name="T"/>, also when it has [AutoGenerateDto] (like TypesToIgnore).</summary>
    ICodeGenBuilder IgnoreType<T>();

    /// <summary>No DTO for the type, also when it has [AutoGenerateDto] (like TypesToIgnore).</summary>
    ICodeGenBuilder IgnoreType(Type type);

    /// <summary>Settings and member rules (by name) for every generated type in <paramref name="namespace"/> or below it.</summary>
    ICodeGenBuilder ForNamespace(string @namespace, Action<IDtoTypeBuilder> configure);

    /// <summary>Rules that apply only when the generating project's assembly is <paramref name="assemblyName"/>.</summary>
    ICodeGenBuilder ForAssembly(string assemblyName, Action<ICodeGenBuilder> configure);

    /// <summary>One more Excel generation, exactly like an entry of "ExcelGenerations" in codegen.json.</summary>
    ICodeGenBuilder ExcelGeneration(Action<IExcelGeneration> configure);

    /// <summary>One more JSON/XML structure generation, exactly like an entry of "StructureGenerations" in codegen.json.</summary>
    ICodeGenBuilder StructureGeneration(Action<IStructureGeneration> configure);

    /// <summary>One more TypeScript generation, exactly like an entry of "Typescript" in codegen.json (needs an OutputPath).</summary>
    ICodeGenBuilder Typescript(Action<ITypescriptGeneration> configure);

    /// <summary>
    /// Facets of members of <typeparamref name="T"/> for <c>Nextended.Core.Facets.FacetBuilder</c>, like <c>[ProvideFacet]</c> on them, without
    /// touching the type and without giving it a DTO: <c>Facets&lt;Shipment&gt;(f =&gt; f.Facet(x =&gt; x.Delivered, o =&gt; o.Type(FacetType.DateRange)))</c>.
    /// </summary>
    ICodeGenBuilder Facets<T>(Action<IFacets<T>> configure);
}

/// <summary>Facets of members of <typeparamref name="T"/> (see <see cref="IDtoBuilder{T}.Facet{TProperty}"/>).</summary>
public interface IFacets<T>
{
    /// <summary>A facet of the member, like <c>[ProvideFacet]</c> on it; see <see cref="IDtoBuilder{T}.Facet{TProperty}"/>.</summary>
    IFacets<T> Facet<TProperty>(System.Linq.Expressions.Expression<Func<T, TProperty>> member, Action<IFacetBuilder>? configure = null);
}

