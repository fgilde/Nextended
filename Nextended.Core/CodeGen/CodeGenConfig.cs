    IDtoDefaults DisableGeneration(bool value = true);
    IDtoDefaults ModelType(GeneratedModelType value);
    IDtoDefaults Namespace(string? value);
    IDtoDefaults Suffix(string? value);
    IDtoDefaults Prefix(string? value);
    IDtoDefaults OutputPath(string? value);
    IDtoDefaults CreateFileHeaders(bool value = true);
    IDtoDefaults GeneratedCodeAttribute(bool value = true);
    IDtoDefaults GeneratedCodeVersion(bool value = true);
    IDtoDefaults DeepProperties(bool value = true);
    IDtoDefaults MakeDtoAbstractWhenSourceIsAbstract(bool value = true);
    IDtoDefaults GenerateToMethodsForAbstract(bool value = true);
    IDtoDefaults GenerateFactoryOverloadsForAbstract(bool value = true);
    IDtoDefaults AlwaysGenerateFactoryOverloads(bool value = true);
    IDtoDefaults ComIdClassName(string value);
    IDtoDefaults ComIdClassPropertyFormat(string value);
    IDtoDefaults ComIdClassModifier(Modifier value);
    IDtoDefaults BaseType(string? value);
    IDtoDefaults AddReferencedNamespacesUsings(bool value = true);
    IDtoDefaults AddContainingNamespaceUsings(bool value = true);
    IDtoDefaults PreInterfaceString(string? value);
    IDtoDefaults PreClassString(string? value);
    IDtoDefaults KeepAttributesOnGeneratedClass(bool value = true);
    IDtoDefaults KeepAttributesOnGeneratedInterface(bool value = true);
    IDtoDefaults Interfaces(params string[] value);
    IDtoDefaults PropertiesToIgnore(params string[] value);
    IDtoDefaults TypesToIgnore(params string[] value);
    IDtoDefaults KeepEnumFlagsAndUnderlyingType(bool value = true);
    IDtoDefaults InitializeCollections(bool value = true);
    IDtoDefaults EmitNullableAnnotations(bool value = true);
    IDtoDefaults OneFilePerClass(bool value = true);
    IDtoDefaults Usings(params string[] value);
    IDtoDefaults CreateRegions(bool value = true);
    IDtoDefaults CreateComments(bool value = true);
    IDtoDefaults GeneratePartial(bool value = true);
    IDtoDefaults MappingOutputPath(string? value);
    IDtoDefaults DeleteStaleFiles(bool value = true);
    IDtoDefaults DefaultMappingSettings(Action<IMappingDefaults> configure);
#pragma warning restore CS1591

    /// <summary><see cref="BaseType(string)"/> from a type, written with its full name (see <see cref="IDtoSettings{TSelf}.BaseType{TBase}"/>).</summary>
    IDtoDefaults BaseType<TBase>();

    /// <summary><see cref="BaseType{TBase}"/> for a type given by <c>typeof</c> (also open generic types).</summary>
    IDtoDefaults BaseType(Type type);

    /// <summary>Adds an interface to <see cref="Interfaces"/>, written with its full name; typed interfaces add up.</summary>
    IDtoDefaults Interface<TInterface>();

    /// <summary><see cref="Interface{TInterface}"/> for a type given by <c>typeof</c>.</summary>
    IDtoDefaults Interface(Type type);

    /// <summary>Writes one more file for every DTO (views included); see <see cref="IDtoSettings{TSelf}.Emit"/>.</summary>
    IDtoDefaults Emit(string fileName, string template, string? outputPath = null);
}

