using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Nextended.Core.Attributes;
using Nextended.CodeGen.Generators.DtoGeneration;

namespace Nextended.CodeGen.Helper;

internal static class StringBuilderHelper
{
    public static StringBuilder AppendIf(this StringBuilder sb, string value, bool condition = true)
    {
        if (condition)
            sb.Append(value);
        return sb;
    }

    public static StringBuilder AppendLineIf(this StringBuilder sb, string line, bool condition = true)
    {
        if (condition)
            sb.AppendLine(line);
        return sb;
    }
    public static StringBuilder AppendUsings(this StringBuilder sb, params string[] namespaces)
    {
        foreach (var ns in namespaces)
        {
            if (string.IsNullOrWhiteSpace(ns)) continue;
            sb.AppendLine($"using {ns};");
        }
        return sb;
    }


    public static StringBuilder CloseNamespace(this StringBuilder sb)
    {
        sb.AppendLine("}");
        return sb;
    }
    public static StringBuilder OpenNamespace(this StringBuilder sb, string @namespace)
    {
        sb.AppendLine($"namespace {@namespace} {{");
        return sb;
    }

    public static StringBuilder OpenRegion(this StringBuilder sb, string name, bool condition = true)
    {
        if (!condition)
            return sb;
        sb.AppendLine($"\t#region {name}");
        sb.AppendLine();
        return sb;
    }

    public static StringBuilder CloseRegion(this StringBuilder sb, string name, bool condition = true)
    {
        if (!condition)
            return sb;
        sb.AppendLine($"\t#endregion {name}");
        sb.AppendLine();
        return sb;
    }

    public static StringBuilder AppendFileHeaderIf(this StringBuilder sb, bool condition, params string[] names)
    {
        if(!condition)
            return sb;
        sb.AppendLine("/// <summary>");
        sb.AppendLine($"/// --- AUTO GENERATED CODE ({DateTime.Now:G}) ---");
        foreach (var name in names) sb.AppendLine($"/// --- {name} ---");
        sb.AppendLine("/// </summary>\n");
        return sb;
    }

    public static StringBuilder AppendClassHeader(this StringBuilder sb, bool addFileHeader,
        string className, string namespaceName, params string[] usings)
    {        
        sb.AppendFileHeaderIf(addFileHeader);        
        if (!usings.Any())
            usings = ["System"];
        sb.AppendUsings(usings);
        sb.AppendLine($"namespace {namespaceName} {{");
        sb.AppendLine($"\tpublic static partial class {className}");
        sb.AppendLine("\t{");

        return sb;
    }

    public static StringBuilder AppendAttributesIf(this StringBuilder sb, ISymbol symbol, bool condition, int indent = 1)
    {
        if (condition)
        {
            foreach (var att in symbol?.GetAttributes().Where(a => a.ShouldEmitAttribute()) ?? [])
            {
                var indentStr = string.Join("", Enumerable.Repeat("\t", indent));
                sb.AppendLine(indentStr + att.ToCSharpString());
            }
        }

        return sb;
    }

    /// <summary>The package version of the generator (assembly metadata "PackageVersion"), for <c>GeneratedCodeVersion</c>.</summary>
    private static readonly string GeneratorVersion = typeof(StringBuilderHelper).Assembly
        .GetCustomAttributes(typeof(System.Reflection.AssemblyMetadataAttribute), false).OfType<System.Reflection.AssemblyMetadataAttribute>()
        .FirstOrDefault(a => a.Key == "PackageVersion")?.Value ?? "";

    /// <summary>The [GeneratedCode] line of a generated type, or nothing when it is switched off or the type already gets one.</summary>
    public static StringBuilder AppendGeneratedCodeIf(this StringBuilder sb, Config.CodeGenerationConfigBase? config, string indent = "\t",
        ISymbol? keptFrom = null, string? preString = null)
    {
        if (config is { GeneratedCodeAttribute: false }
            || preString?.Contains("GeneratedCode") == true
            || keptFrom?.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == "System.CodeDom.Compiler.GeneratedCodeAttribute") == true)
            return sb;
        var version = config is { GeneratedCodeVersion: true } ? $"\"{GeneratorVersion}\"" : "null";
        sb.AppendLine($"{indent}[global::System.CodeDom.Compiler.GeneratedCode(\"Nextended.CodeGen\", {version})]");
        return sb;
    }

    private static readonly string OwnNamespacePrefix = typeof(AutoGenerateDtoAttribute).Namespace;

    private static bool ShouldEmitAttribute(this AttributeData att)
    {
        var ns = att.AttributeClass?.ContainingNamespace?.ToDisplayString() ?? "";
        return !ns.StartsWith(OwnNamespacePrefix, StringComparison.Ordinal);
    }

}