namespace Nextended.CodeGen.Fluent;

/// <summary>A value set in a fluent configuration, with where it was set (for conflicts and diagnostics).</summary>
internal readonly struct FluentValue(object? value, string profile, Location location)
{
    public object? Value { get; } = value;
    public string Profile { get; } = profile;
    public Location Location { get; } = location;
}

/// <summary>An additional file per DTO (Emit).</summary>
internal sealed class FluentEmit(string fileName, string template, string? outputPath, Location location)
{
    public string FileName { get; } = fileName;
    public string Template { get; } = template;
    public string? OutputPath { get; } = outputPath;
    public Location Location { get; } = location;
}

/// <summary>Settings of one member of one DTO: GenerationPropertySetting names plus "Ignore" (true = leave out, false = take in again).</summary>
internal sealed class FluentMemberRules
{
    public Dictionary<string, FluentValue> Settings { get; } = new(StringComparer.Ordinal);
}

/// <summary>
/// The fluent rules of one type (Dto&lt;T&gt;), of a namespace (ForNamespace) or of one view: AutoGenerateDto names plus the fluent-only
/// settings "UseViews", "OutputPath", "Order", "BaseMembersFirst", member rules by name, views, additional files.
/// </summary>
internal sealed class FluentTypeRules
{
    public FluentTypeRules(INamedTypeSymbol? type, string? @namespace, string? viewKey, Location location)
    {
        Type = type;
        Namespace = @namespace;
        ViewKey = viewKey;
        Location = location;
    }

    public INamedTypeSymbol? Type { get; }
    public string? Namespace { get; }
    public string? ViewKey { get; }
    public Location Location { get; }

    /// <summary>Dto&lt;T&gt;() was called: the type gets a DTO also without [AutoGenerateDto].</summary>
    public bool Generate { get; set; }

    public Dictionary<string, FluentValue> Settings { get; } = new(StringComparer.Ordinal);
    public Dictionary<string, FluentMemberRules> Members { get; } = new(StringComparer.Ordinal);
    public List<FluentTypeRules> Views { get; } = [];
    public List<FluentEmit> Emits { get; } = [];

    public FluentMemberRules Member(string name)
    {
        if (!Members.TryGetValue(name, out var rules))
            Members[name] = rules = new FluentMemberRules();
        return rules;
    }

    public FluentTypeRules View(string key, Location location)
    {
        var view = Views.FirstOrDefault(v => v.ViewKey == key);
        if (view == null)
            Views.Add(view = new FluentTypeRules(Type, null, key, location));
        return view;
    }

    public object? Get(string name) => Settings.TryGetValue(name, out var v) ? v.Value : null;
}

/// <summary>One facet of Facet(x => x.Member, o => ...): settings named like [ProvideFacet]'s properties, as C# expressions.</summary>
internal sealed class FluentFacet(INamedTypeSymbol type, string member, Location location)
{
    public INamedTypeSymbol Type { get; } = type;
    public string Member { get; } = member;
    public Location Location { get; } = location;
    public Dictionary<string, FluentValue> Settings { get; } = new(StringComparer.Ordinal);

    /// <summary>The type as written in typeof: generic type definitions unbound (<c>global::Ns.Box&lt;&gt;</c>).</summary>
    public static string TypeOfName(ITypeSymbol type)
        => (type is INamedTypeSymbol { IsGenericType: true } named && SymbolEqualityComparer.Default.Equals(named, named.OriginalDefinition)
            ? named.ConstructUnboundGenericType()
            : type).ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

    /// <summary>The enum member with the value (a cast for a value without a member, e.g. combined flags).</summary>
    public static string EnumMember(INamedTypeSymbol enumType, object value)
    {
        var name = enumType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var member = enumType.GetMembers().OfType<IFieldSymbol>().FirstOrDefault(f => f.HasConstantValue && Equals(f.ConstantValue, value));
        return member != null ? $"{name}.{member.Name}" : $"(({name}){System.Convert.ToString(value, System.Globalization.CultureInfo.InvariantCulture)})";
    }
}

/// <summary>
/// Everything the fluent configuration classes of a compilation say, merged (several profiles in the order of their full names).
/// Types are keyed by their original definition, members by name.
/// </summary>
internal sealed class FluentModel
{
    public static readonly FluentModel Empty = new();

    /// <summary>True when the compilation has at least one configuration class.</summary>
    public bool HasProfiles { get; set; }

    /// <summary>DtoGenerationConfig settings by name; "DefaultMappingSettings.X" for the nested mapping settings.</summary>
    public Dictionary<string, FluentValue> Defaults { get; } = new(StringComparer.Ordinal);
    public List<FluentEmit> DefaultEmits { get; } = [];
    public Dictionary<string, FluentTypeRules> Types { get; } = new(StringComparer.Ordinal);
    public List<FluentTypeRules> Namespaces { get; } = [];
    public Dictionary<string, (INamedTypeSymbol Type, Location Location)> IgnoredTypes { get; } = new(StringComparer.Ordinal);
    public List<ExcelGenerationConfig> ExcelGenerations { get; } = [];
    public List<ClassStructureCodeGenerationConfig> StructureGenerations { get; } = [];
    public List<TypescriptGenerationConfig> TypescriptGenerations { get; } = [];

    /// <summary>The TypeScript rules of DtoConfig&lt;T&gt;.Typescript(...), by TypeScript type key; they apply to every TypeScript generation.</summary>
    public Dictionary<string, TypescriptTypeConfig> TypescriptTypes { get; } = new(StringComparer.Ordinal);
    public List<Diagnostic> Diagnostics { get; } = [];

    /// <summary>ViewDefaults(...): settings and member rules for every view (the view's own win).</summary>
    public FluentTypeRules? ViewDefaults { get; set; }

    /// <summary>Facet(...) by type key and member; written as a FacetRegistry registration, not used by the DTO generation.</summary>
    public Dictionary<string, FluentFacet> Facets { get; } = new(StringComparer.Ordinal);

    /// <summary>True when nothing but diagnostics came out: the generators then take their exact old code paths.</summary>
    public bool HasRules => Defaults.Count > 0 || DefaultEmits.Count > 0 || Types.Count > 0 || Namespaces.Count > 0 || IgnoredTypes.Count > 0
                            || ViewDefaults != null;

    public FluentFacet Facet(INamedTypeSymbol type, string member, Location location)
    {
        var key = Key(type) + "|" + member;
        if (!Facets.TryGetValue(key, out var facet))
            Facets[key] = facet = new FluentFacet((INamedTypeSymbol)type.OriginalDefinition, member, location);
        return facet;
    }

    public static string Key(ITypeSymbol type) => type.OriginalDefinition.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

    public FluentTypeRules TypeRules(INamedTypeSymbol type, Location location)
    {
        var key = Key(type);
        if (!Types.TryGetValue(key, out var rules))
            Types[key] = rules = new FluentTypeRules((INamedTypeSymbol)type.OriginalDefinition, null, null, location);
        return rules;
    }

    public FluentTypeRules NamespaceRules(string ns, Location location)
    {
        var rules = Namespaces.FirstOrDefault(n => n.Namespace == ns);
        if (rules == null)
            Namespaces.Add(rules = new FluentTypeRules(null, ns, null, location));
        return rules;
    }

    public FluentTypeRules? Type(ITypeSymbol? type) => type != null && Types.Count > 0 && Types.TryGetValue(Key(type), out var r) ? r : null;

    /// <summary>The namespace rules of a type, the shortest (most general) namespace first.</summary>
    public IEnumerable<FluentTypeRules> NamespaceRulesOf(ITypeSymbol type)
    {
        if (Namespaces.Count == 0)
            return [];
        var ns = type.ContainingNamespace?.ToDisplayString() ?? "";
        return Namespaces.Where(n => ns == n.Namespace || ns.StartsWith(n.Namespace + ".", StringComparison.Ordinal))
            .OrderBy(n => n.Namespace!.Length);
    }

    /// <summary>The type-level rules of a type in the order they apply: namespace rules (general first), then Dto&lt;T&gt;.</summary>
    public IEnumerable<FluentTypeRules> TypeLevel(ITypeSymbol type)
    {
        foreach (var n in NamespaceRulesOf(type))
            yield return n;
        if (Type(type) is { } own)
            yield return own;
    }

    public bool IsIgnoredType(ITypeSymbol type) => IgnoredTypes.Count > 0 && IgnoredTypes.ContainsKey(Key(type));

    /// <summary>The configuration with the fluent defaults applied; a copy, the given object stays as it is.</summary>
    public DtoGenerationConfig ApplyDefaults(DtoGenerationConfig config)
    {
        if (Defaults.Count == 0)
            return config;
        var copy = JsonConvert.DeserializeObject<DtoGenerationConfig>(JsonConvert.SerializeObject(config))!;
        foreach (var setting in Defaults)
        {
            var target = (object)copy;
            var name = setting.Key;
            var dot = name.IndexOf('.');
            if (dot > 0)
            {
                copy.DefaultMappingSettings ??= new DefaultMappingSettings();
                target = copy.DefaultMappingSettings;
                name = name.Substring(dot + 1);
            }
            Set(target, name, setting.Value.Value);
        }
        return copy;
    }

    /// <summary>Applies settings by name onto a settings object (an attribute instance or a config class); unknown names are skipped.</summary>
    public static void Apply(object target, IEnumerable<KeyValuePair<string, FluentValue>> settings)
    {
        foreach (var setting in settings)
            Set(target, setting.Key, setting.Value.Value);
    }

    public static bool Set(object target, string name, object? value)
    {
        var property = target.GetType().GetProperty(name, BindingFlags.Public | BindingFlags.Instance);
        if (property is not { CanWrite: true })
            return false;
        property.SetValue(target, Convert(value, property.PropertyType));
        return true;
    }

    /// <summary>The names of the writable settings of a settings type.</summary>
    public static HashSet<string> SettingNames(Type type)
        => new(type.GetProperties(BindingFlags.Public | BindingFlags.Instance).Where(p => p.CanWrite).Select(p => p.Name), StringComparer.Ordinal);

    private static object? Convert(object? value, Type type)
    {
        if (value == null)
            return null;
        var target = Nullable.GetUnderlyingType(type) ?? type;
        if (target.IsInstanceOfType(value))
            return value;
        if (target.IsEnum)
            return Enum.ToObject(target, value);
        if (target.IsArray && value is IEnumerable items)
        {
            var element = target.GetElementType()!;
            var list = items.Cast<object?>().Select(i => Convert(i, element)).ToArray();
            var array = Array.CreateInstance(element, list.Length);
            for (var i = 0; i < list.Length; i++)
                array.SetValue(list[i], i);
            return array;
        }
        return System.Convert.ChangeType(value, target, System.Globalization.CultureInfo.InvariantCulture);
    }

    public static bool SameValue(object? a, object? b)
        => a is string[] x && b is string[] y ? x.SequenceEqual(y) : Equals(a, b);
}
