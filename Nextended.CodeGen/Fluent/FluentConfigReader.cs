/// <summary>
/// Reads the fluent configuration classes (Nextended.Core.CodeGen.CodeGenConfig / DtoConfig&lt;T&gt;) of a compilation. Nothing is
/// executed: the constructor bodies are walked as operation trees; every call of the API with constant arguments, typeof, nameof,
/// member selectors and nested lambdas becomes a rule, everything else a diagnostic.
/// </summary>
internal sealed class FluentConfigReader
{
    public const string ApiNamespace = "Nextended.Core.CodeGen";

    internal static readonly DiagnosticDescriptor NotReadable = new(
        "NCG020", "Fluent configuration not readable",
        "{0} The fluent configuration is read by the generator, not executed: only calls of the Nextended.Core.CodeGen API with constants, typeof, nameof, member selectors (x => x.Member) and nested lambdas are allowed. The statement is skipped.",
        "Nextended.CodeGen", DiagnosticSeverity.Error, isEnabledByDefault: true);

    internal static readonly DiagnosticDescriptor UnknownMember = new(
        "NCG021", "Unknown member in fluent configuration", "{0} has no member '{1}'",
        "Nextended.CodeGen", DiagnosticSeverity.Warning, isEnabledByDefault: true);

    internal static readonly DiagnosticDescriptor Conflict = new(
        "NCG022", "Conflicting fluent settings", "{0} of {1} is set to different values in {2} and {3}; {3} wins (profiles apply in the order of their full names)",
        "Nextended.CodeGen", DiagnosticSeverity.Warning, isEnabledByDefault: true);

    internal static readonly DiagnosticDescriptor InheritedMemberRule = new(
        "NCG023", "Member rule has no effect on the default DTO",
        "The rule for '{0}' on {1} has no effect on the default DTO of {1}: the member is inherited and lives in the DTO of {2}. Configure it on {2}, or use it in a view of {1}.",
        "Nextended.CodeGen", DiagnosticSeverity.Warning, isEnabledByDefault: true);

    internal static readonly DiagnosticDescriptor BadEmit = new(
        "NCG024", "Additional file cannot be written", "Emit '{0}': {1}",
        "Nextended.CodeGen", DiagnosticSeverity.Error, isEnabledByDefault: true);

    internal static readonly DiagnosticDescriptor NoDtoType = new(
        "NCG025", "Type cannot get a DTO", "{0} cannot get a DTO: only classes, records and enums can",
        "Nextended.CodeGen", DiagnosticSeverity.Warning, isEnabledByDefault: true);

    internal static readonly DiagnosticDescriptor UnknownCall = new(
        "NCG026", "Unknown fluent configuration call", "{0} is not known to this version of Nextended.CodeGen; update the Nextended.CodeGen package",
        "Nextended.CodeGen", DiagnosticSeverity.Warning, isEnabledByDefault: true);

    private static readonly ConditionalWeakTable<Compilation, FluentModel> Cache = new();

    /// <summary>Short names for the verbose settings; the originals stay. Attributes(...) joins its attributes into one PreClassString.</summary>
    private static readonly Dictionary<string, string> Aliases = new(StringComparer.Ordinal)
    {
        ["Attribute"] = "PreClassString",
        ["Attributes"] = "PreClassString",
        ["KeepAttributes"] = "KeepAttributesOnGeneratedClass"
    };

    private static string Resolve(string name, bool member)
        => member && name == "Name" ? "PropertyName" : Aliases.TryGetValue(name, out var original) ? original : name;

    private static object? AliasValue(string name, object? value)
        => name == "Attributes" && value is string[] attributes ? string.Join(" ", attributes) : value;

    private static readonly HashSet<string> DtoSettings = With(FluentModel.SettingNames(typeof(AutoGenerateDtoAttribute)), "UseViews", "OutputPath");
    private static readonly HashSet<string> PropertySettings = Without(FluentModel.SettingNames(typeof(GenerationPropertySettingAttribute)), "View");
    private static readonly HashSet<string> DefaultSettings = Without(FluentModel.SettingNames(typeof(DtoGenerationConfig)), "DefaultMappingSettings");
    private static readonly HashSet<string> MappingSettings = FluentModel.SettingNames(typeof(DefaultMappingSettings));

    private readonly Compilation _compilation;
    private readonly FluentModel _model;
    private string _profile = "";

    private FluentConfigReader(Compilation compilation, FluentModel model)
    {
        _compilation = compilation;
        _model = model;
    }

    /// <summary>The fluent model of a compilation; empty (and cheap) when the compilation has no configuration class.</summary>
    public static FluentModel Read(Compilation compilation) => Cache.GetValue(compilation, ReadCore);

    private static FluentModel ReadCore(Compilation compilation)
    {
        var configBase = compilation.GetTypeByMetadataName(ApiNamespace + ".CodeGenConfig");
        var dtoBase = compilation.GetTypeByMetadataName(ApiNamespace + ".DtoConfig`1");
        if (configBase == null && dtoBase == null)
            return FluentModel.Empty;

        var profiles = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        foreach (var tree in compilation.SyntaxTrees)
        {
            SemanticModel? semantic = null;
            foreach (var declaration in tree.GetRoot().DescendantNodes(n => n is CompilationUnitSyntax or BaseNamespaceDeclarationSyntax or TypeDeclarationSyntax)
                         .OfType<ClassDeclarationSyntax>().Where(c => c.BaseList != null))
            {
                semantic ??= compilation.GetSemanticModel(tree);
                if (semantic.GetDeclaredSymbol(declaration) is INamedTypeSymbol symbol && ProfileKind(symbol, configBase, dtoBase) != null)
                    profiles.Add(symbol);
            }
        }
        if (profiles.Count == 0)
            return FluentModel.Empty;

        var model = new FluentModel { HasProfiles = true };
        var reader = new FluentConfigReader(compilation, model);
        foreach (var profile in profiles.OrderBy(p => p.ToDisplayString(), StringComparer.Ordinal))
            reader.ReadProfile(profile, ProfileKind(profile, configBase, dtoBase)!);
        return model;
    }

    /// <summary>The CodeGenConfig or DtoConfig&lt;T&gt; base a class derives from, null when it is no configuration class.</summary>
    private static INamedTypeSymbol? ProfileKind(INamedTypeSymbol type, INamedTypeSymbol? configBase, INamedTypeSymbol? dtoBase)
    {
        for (var t = type.BaseType; t != null; t = t.BaseType)
        {
            if (configBase != null && SymbolEqualityComparer.Default.Equals(t.OriginalDefinition, configBase))
                return t;
            if (dtoBase != null && SymbolEqualityComparer.Default.Equals(t.OriginalDefinition, dtoBase))
                return t;
        }
        return null;
    }

    private void ReadProfile(INamedTypeSymbol profile, INamedTypeSymbol kind)
    {
        _profile = profile.ToDisplayString();
        Context? root;
        if (kind.IsGenericType)
        {
            var target = kind.TypeArguments[0];
            root = DtoTarget(target, profile.Locations.FirstOrDefault() ?? Location.None, _model) is { } rules
                ? new DtoContext(rules, rules.Type, false, _model)
                : null;
            if (root == null)
                return;
        }
        else
        {
            root = new RootContext(_model);
        }

        foreach (var ctor in profile.InstanceConstructors.Where(c => !c.IsImplicitlyDeclared))
        {
            foreach (var reference in ctor.DeclaringSyntaxReferences)
            {
                var syntax = reference.GetSyntax();
                if (_compilation.GetSemanticModel(syntax.SyntaxTree).GetOperation(syntax) is not IConstructorBodyOperation body)
                    continue;
                var scope = new Dictionary<IParameterSymbol, Context>(SymbolEqualityComparer.Default);
                if (body.BlockBody != null)
                    Statements(body.BlockBody, root, scope, isThis: true);
                if (body.ExpressionBody != null)
                    Statements(body.ExpressionBody, root, scope, isThis: true);
            }
        }
    }

    // ---- walking ----

    private sealed class Scope(Dictionary<IParameterSymbol, Context> parameters, Context? self)
    {
        public Dictionary<IParameterSymbol, Context> Parameters { get; } = parameters;
        public Context? Self { get; } = self;
    }

    private void Statements(IOperation body, Context self, Dictionary<IParameterSymbol, Context> parameters, bool isThis)
        => Statements(body, new Scope(parameters, isThis ? self : null));

    private void Statements(IOperation body, Scope scope)
    {
        switch (body)
        {
            case IBlockOperation block:
                foreach (var statement in block.Operations)
                    Statements(statement, scope);
                break;
            case IExpressionStatementOperation statement:
                Evaluate(statement.Operation, scope);
                break;
            case IReturnOperation { ReturnedValue: null }:
            case IEmptyOperation:
                break;
            case IReturnOperation { ReturnedValue: { } value }:
                Evaluate(value, scope);
                break;
            default:
                Report(NotReadable, body.Syntax, $"'{Short(body.Syntax)}' is not a call of the configuration API.");
                break;
        }
    }

    private Context? Evaluate(IOperation operation, Scope scope)
    {
        operation = Unwrap(operation);
        switch (operation)
        {
            case IInvocationOperation invocation:
                return Invoke(invocation, scope);
            case IInstanceReferenceOperation when scope.Self != null:
                return scope.Self;
            case IParameterReferenceOperation parameter when scope.Parameters.TryGetValue(parameter.Parameter, out var context):
                return context;
            default:
                Report(NotReadable, operation.Syntax, $"'{Short(operation.Syntax)}' cannot be read.");
                return null;
        }
    }

    private Context? Invoke(IInvocationOperation invocation, Scope scope)
    {
        var method = invocation.TargetMethod;
        if (method.ContainingType?.ContainingNamespace?.ToDisplayString() != ApiNamespace)
        {
            Report(NotReadable, invocation.Syntax, $"'{Short(invocation.Syntax)}' calls {method.ContainingType?.Name}.{method.Name}, which is not part of the configuration API.");
            return null;
        }
        if (invocation.Instance == null)
        {
            Report(NotReadable, invocation.Syntax, $"'{Short(invocation.Syntax)}' has no builder to apply to.");
            return null;
        }
        var receiver = Evaluate(invocation.Instance, scope);
        if (receiver == null)
            return null;

        var call = new Call(this, invocation, scope);
        var result = receiver.Invoke(this, call);
        if (result == Context.Unknown)
        {
            Report(UnknownCall, invocation.Syntax, $"{method.ContainingType!.Name}.{method.Name}");
            return null;
        }
        return result;
    }

    /// <summary>One API call with its arguments read (constants, arrays, typeof, selectors, lambdas).</summary>
    private sealed class Call
    {
        private readonly FluentConfigReader _reader;
        private readonly Scope _scope;
        private readonly Dictionary<string, IOperation> _arguments = new(StringComparer.Ordinal);

        public Call(FluentConfigReader reader, IInvocationOperation invocation, Scope scope)
        {
            _reader = reader;
            _scope = scope;
            Invocation = invocation;
            Method = invocation.TargetMethod;
            foreach (var argument in invocation.Arguments)
                if (argument.Parameter != null)
                    _arguments[argument.Parameter.Name] = argument.Value;
        }

        public IInvocationOperation Invocation { get; }
        public IMethodSymbol Method { get; }
        public string Name => Method.Name;
        public Location Location => Invocation.Syntax.GetLocation();
        public int Count => Method.Parameters.Length;
        public ITypeSymbol? TypeArgument => Method.TypeArguments.FirstOrDefault();
        public bool FirstIsLambdaArray => Method.Parameters.FirstOrDefault()?.Type is IArrayTypeSymbol { ElementType: INamedTypeSymbol { Name: "Expression" } };

        public IOperation? Argument(int index)
            => index < Method.Parameters.Length && _arguments.TryGetValue(Method.Parameters[index].Name, out var op) ? op : null;

        /// <summary>The constant value of an argument (also arrays of constants); false and a diagnostic when it is not constant.</summary>
        public bool TryConstant(int index, out object? value)
        {
            value = null;
            var op = Argument(index);
            if (op == null)
                return true;
            return _reader.TryConstant(op, out value);
        }

        public bool TryString(int index, out string? value)
        {
            var ok = TryConstant(index, out var v);
            value = v as string;
            return ok;
        }

        public bool IsTypeOf(int index) => Argument(index) is { } op && Unwrap(op) is ITypeOfOperation;

        public ITypeSymbol? TypeOf(int index)
        {
            if (Argument(index) is { } op && Unwrap(op) is ITypeOfOperation typeOf)
                return typeOf.TypeOperand;
            _reader.Report(NotReadable, Argument(index)?.Syntax ?? Invocation.Syntax, "Pass the type as typeof(...).");
            return null;
        }

        /// <summary>Walks the lambda argument with <paramref name="context"/> as its parameter (nothing when it is omitted or null).</summary>
        public void Lambda(int index, Context context)
        {
            var op = Argument(index);
            if (op == null || op.ConstantValue is { HasValue: true, Value: null } || Unwrap(op).ConstantValue is { HasValue: true, Value: null })
                return;
            if (AsLambda(op) is not { } lambda || lambda.Symbol.Parameters.Length != 1)
            {
                _reader.Report(NotReadable, op.Syntax, $"'{Short(op.Syntax)}' must be a lambda (x => ...).");
                return;
            }
            var parameters = new Dictionary<IParameterSymbol, Context>(_scope.Parameters, SymbolEqualityComparer.Default)
            {
                [lambda.Symbol.Parameters[0]] = context
            };
            _reader.Statements(lambda.Body, new Scope(parameters, _scope.Self));
        }

        /// <summary>The members selected by selector lambdas (x => x.Member) in a params argument.</summary>
        public List<ISymbol> Selectors(int index)
        {
            var result = new List<ISymbol>();
            var op = Argument(index);
            if (op == null)
                return result;
            var items = Unwrap(op) switch
            {
                IArrayCreationOperation { Initializer: { } init } => init.ElementValues.ToList(),
                _ => [op]
            };
            foreach (var item in items)
                if (_reader.Selector(item) is { } member)
                    result.Add(member);
            return result;
        }
    }

    private bool TryConstant(IOperation op, out object? value)
    {
        value = null;
        if (op.ConstantValue.HasValue)
        {
            value = op.ConstantValue.Value;
            return true;
        }
        var unwrapped = Unwrap(op);
        if (unwrapped.ConstantValue.HasValue)
        {
            value = unwrapped.ConstantValue.Value;
            return true;
        }
        IEnumerable<IOperation>? items = unwrapped switch
        {
            IArrayCreationOperation { Initializer: { } init } => init.ElementValues,
            IArrayCreationOperation { Initializer: null } array when array.DimensionSizes.All(d => d.ConstantValue is { HasValue: true, Value: 0 }) => [],
            ICollectionExpressionOperation collection => collection.Elements,
            _ => null
        };
        if (items == null)
        {
            Report(NotReadable, op.Syntax, $"'{Short(op.Syntax)}' is not a constant.");
            return false;
        }
        var list = new List<string>();
        foreach (var item in items)
        {
            if (!TryConstant(item, out var element))
                return false;
            if (element is string s)
                list.Add(s);
        }
        value = list.ToArray();
        return true;
    }

    /// <summary>The member of a selector lambda x => x.Member; null and a diagnostic for anything else.</summary>
    private ISymbol? Selector(IOperation op)
    {
        if (AsLambda(op) is { } lambda && lambda.Symbol.Parameters.Length == 1
            && lambda.Body.Operations.Length >= 1 && lambda.Body.Operations[0] is IReturnOperation { ReturnedValue: { } returned })
        {
            var body = Unwrap(returned);
            var (member, instance) = body switch
            {
                IPropertyReferenceOperation p => ((ISymbol?)p.Property, p.Instance),
                IFieldReferenceOperation f => (f.Field, f.Instance),
                _ => (null, null)
            };
            if (member != null && instance is IParameterReferenceOperation pr
                               && SymbolEqualityComparer.Default.Equals(pr.Parameter, lambda.Symbol.Parameters[0]))
                return member;
        }
        Report(NotReadable, op.Syntax, $"'{Short(op.Syntax)}' must select a member of the lambda parameter (x => x.Member).");
        return null;
    }

    private static IAnonymousFunctionOperation? AsLambda(IOperation op)
    {
        while (true)
        {
            switch (op)
            {
                case IAnonymousFunctionOperation lambda:
                    return lambda;
                case IDelegateCreationOperation creation:
                    op = creation.Target;
                    continue;
                case IConversionOperation conversion:
                    op = conversion.Operand;
                    continue;
                default:
                    return null;
            }
        }
    }

    private static IOperation Unwrap(IOperation op)
    {
        while (op is IConversionOperation { IsImplicit: true } conversion)
            op = conversion.Operand;
        return op;
    }

    private void Report(DiagnosticDescriptor descriptor, SyntaxNode syntax, params object[] args)
        => _model.Diagnostics.Add(Diagnostic.Create(descriptor, syntax.GetLocation(), args));

    private void Report(DiagnosticDescriptor descriptor, Location location, params object[] args)
        => _model.Diagnostics.Add(Diagnostic.Create(descriptor, location, args));

    private static string Short(SyntaxNode syntax)
    {
        var text = syntax.ToString().Replace("\r", " ").Replace("\n", " ");
        return text.Length > 80 ? text.Substring(0, 77) + "..." : text;
    }

    private void Set(Dictionary<string, FluentValue> settings, string name, object? value, Location location, string target)
    {
        if (settings.TryGetValue(name, out var previous) && previous.Profile != _profile && !FluentModel.SameValue(previous.Value, value))
            Report(Conflict, location, name, target, previous.Profile, _profile);
        settings[name] = new FluentValue(value, _profile, location);
    }

    /// <summary>A type as C# text: full name with global::, type arguments too; an open generic type with its type parameter names.</summary>
    private static string TypeName(ITypeSymbol type)
        => (type is INamedTypeSymbol { IsUnboundGenericType: true } unbound ? unbound.OriginalDefinition : type).ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

    private static bool IsTypeParameter(Call call, int index)
        => index < call.Method.Parameters.Length && call.Method.Parameters[index].Type is INamedTypeSymbol { Name: "Type", ContainingNamespace.Name: "System" };

    /// <summary>
    /// BaseType&lt;T&gt;() / BaseType(typeof(T)) set BaseType to the full name; Interface&lt;T&gt;() / Interface(typeof(T)) add it to Interfaces
    /// (the same one once; Interfaces(...) with strings still replaces). False when the call is none of them (BaseType("...")).
    /// </summary>
    private bool TypedSetting(Call call, Dictionary<string, FluentValue> settings, string target)
    {
        if (call.Name is not ("BaseType" or "Interface") || call.Name == "BaseType" && call.TypeArgument == null && !IsTypeParameter(call, 0))
            return false;
        if ((call.TypeArgument ?? call.TypeOf(0)) is not { } type)
            return true;
        var name = TypeName(type);
        if (call.Name == "BaseType")
        {
            Set(settings, "BaseType", name, call.Location, target);
            return true;
        }
        var current = settings.TryGetValue("Interfaces", out var previous) && previous.Value is string[] list ? list : [];
        if (!current.Contains(name))
            settings["Interfaces"] = new FluentValue(current.Append(name).ToArray(), _profile, call.Location);
        return true;
    }

    /// <summary>
    /// A typed Attribute&lt;T&gt;(...) adds to the PreClassString the fluent configuration set before (in call order, profiles in the order of
    /// their full names); the same attribute twice is written once. Attribute(string), Attributes and PreClassString still replace it.
    /// </summary>
    private void AddAttribute(Dictionary<string, FluentValue> settings, string attribute, Location location)
    {
        var current = settings.TryGetValue("PreClassString", out var previous) ? previous.Value as string : null;
        // ponytail: duplicate check by text; an identical attribute inside a string argument of another one would also count
        if (current != null && current.Contains(attribute))
            return;
        settings["PreClassString"] = new FluentValue(string.IsNullOrEmpty(current) ? attribute : current + " " + attribute, _profile, location);
    }

    private FluentTypeRules? DtoTarget(ITypeSymbol type, Location location, FluentModel model)
    {
        if (type is not INamedTypeSymbol { TypeKind: TypeKind.Class or TypeKind.Enum, IsStatic: false } named)
        {
            Report(NoDtoType, location, type.ToDisplayString());
            return null;
        }
        var rules = model.TypeRules(named, location);
        rules.Generate = true;
        return rules;
    }

    // ---- builder contexts ----

    private abstract class Context
    {
        /// <summary>Returned by <see cref="Invoke"/> for a method this generator does not know.</summary>
        public static readonly Context Unknown = new UnknownContext();

        public abstract Context? Invoke(FluentConfigReader reader, Call call);

        private sealed class UnknownContext : Context
        {
            public override Context? Invoke(FluentConfigReader reader, Call call) => null;
        }
    }

    /// <summary>CodeGenConfig / ICodeGenBuilder.</summary>
    private sealed class RootContext(FluentModel model) : Context
    {
        public override Context? Invoke(FluentConfigReader reader, Call call)
        {
            switch (call.Name)
            {
                case "Defaults":
                    call.Lambda(0, new SettingsContext(model, model.Defaults, "", DefaultSettings, "the defaults"));
                    return this;
                case "ViewDefaults":
                    call.Lambda(0, new DtoContext(model.ViewDefaults ??= new FluentTypeRules(null, null, null, call.Location), null, true, model));
                    return this;
                case "Facets":
                    if (call.TypeArgument is INamedTypeSymbol facetType)
                        call.Lambda(0, new FacetsContext(facetType, model));
                    return this;
                case "Dto":
                {
                    var type = call.TypeArgument ?? call.TypeOf(0);
                    if (type == null)
                        return this;
                    if (reader.DtoTarget(type, call.Location, model) is { } rules)
                        call.Lambda(call.TypeArgument != null ? 0 : 1, new DtoContext(rules, rules.Type, false, model));
                    return this;
                }
                case "IgnoreType":
                {
                    if ((call.TypeArgument ?? call.TypeOf(0)) is INamedTypeSymbol type)
                        model.IgnoredTypes[FluentModel.Key(type)] = ((INamedTypeSymbol)type.OriginalDefinition, call.Location);
                    return this;
                }
                case "ForNamespace":
                {
                    if (!call.TryString(0, out var ns) || string.IsNullOrWhiteSpace(ns))
                        return this;
                    call.Lambda(1, new DtoContext(model.NamespaceRules(ns!.Trim(), call.Location), null, false, model));
                    return this;
                }
                case "ForAssembly":
                {
                    if (!call.TryString(0, out var name))
                        return this;
                    var active = ReferenceEquals(model, reader._model)
                                 && string.Equals(name, reader._compilation.AssemblyName, StringComparison.OrdinalIgnoreCase);
                    // rules for other assemblies are read into a scratch model: checked, not applied
                    var target = active ? model : new FluentModel();
                    call.Lambda(1, new RootContext(target));
                    return this;
                }
                case "ExcelGeneration":
                {
                    var config = new ExcelGenerationConfig();
                    call.Lambda(0, new ObjectContext(config));
                    model.ExcelGenerations.Add(config);
                    return this;
                }
                case "StructureGeneration":
                {
                    var config = new ClassStructureCodeGenerationConfig();
                    call.Lambda(0, new ObjectContext(config));
                    model.StructureGenerations.Add(config);
                    return this;
                }
                case "Typescript":
                {
                    var config = new TypescriptGenerationConfig { IsFluent = true };
                    call.Lambda(0, new TypescriptGenerationContext(config));
                    model.TypescriptGenerations.Add(config);
                    return this;
                }
                default:
                    return Unknown;
            }
        }
    }

    /// <summary>Defaults (DtoGenerationConfig) and DefaultMappingSettings: settings by name into the model's defaults.</summary>
    private sealed class SettingsContext(FluentModel model, Dictionary<string, FluentValue> settings, string prefix, HashSet<string> names, string target) : Context
    {
        public override Context? Invoke(FluentConfigReader reader, Call call)
        {
            if (prefix.Length == 0 && call.Name == "DefaultMappingSettings")
            {
                call.Lambda(0, new SettingsContext(model, settings, "DefaultMappingSettings.", MappingSettings, "the mapping defaults"));
                return this;
            }
            if (prefix.Length == 0 && call.Name == "Emit")
            {
                if (reader.ReadEmit(call) is { } emit)
                    model.DefaultEmits.Add(emit);
                return this;
            }
            if (prefix.Length == 0 && reader.TypedSetting(call, settings, target))
                return this;
            if (!names.Contains(call.Name))
                return Unknown;
            if (call.TryConstant(0, out var value))
                reader.Set(settings, prefix + call.Name, value, call.Location, target);
            return this;
        }
    }

    /// <summary>An Excel or structure generation: settings by name straight onto its config object.</summary>
    private sealed class ObjectContext(object config) : Context
    {
        public override Context? Invoke(FluentConfigReader reader, Call call)
        {
            if (call.Name is "ColumnMapping" or "PropertyTypeOverride" && config is ExcelGenerationConfig excel)
            {
                // PropertyTypeOverride<T>(name) and PropertyTypeOverride(name, typeof(T)): the type by its full name
                var typed = call.TypeArgument ?? (call.Count == 2 && IsTypeParameter(call, 1) ? call.TypeOf(1) : null);
                string? value = typed == null ? null : TypeName(typed);
                if (!call.TryString(0, out var key) || typed == null && !call.TryString(1, out value) || key == null || value == null)
                    return this;
                var map = call.Name == "ColumnMapping"
                    ? excel.ColumnMappings ??= new Dictionary<string, string>()
                    : excel.PropertyTypeOverrides ??= new Dictionary<string, string>();
                map[key] = value;
                return this;
            }
            if (!FluentModel.SettingNames(config.GetType()).Contains(call.Name))
                return Unknown;
            if (call.TryConstant(0, out var v))
                FluentModel.Set(config, call.Name, v);
            return this;
        }
    }

    /// <summary>Dto&lt;T&gt;, DtoConfig&lt;T&gt;, Dto(typeof), ForNamespace and View: settings, member rules, views, Emit.</summary>
    private sealed class DtoContext(FluentTypeRules rules, INamedTypeSymbol? type, bool isView, FluentModel model) : Context
    {
        private string Target => rules.ViewKey != null ? $"view {rules.ViewKey} of {type?.Name}"
            : type?.Name ?? (rules.Namespace != null ? $"namespace {rules.Namespace}" : "the view defaults");

        public override Context? Invoke(FluentConfigReader reader, Call call)
        {
            switch (call.Name)
            {
                case "Ignore":
                case "Include":
                    foreach (var name in reader.MemberNames(call, type))
                        reader.Set(rules.Member(name).Settings, "Ignore", call.Name == "Ignore", call.Location, $"{name} of {Target}");
                    return this;
                case "Property":
                {
                    var name = reader.MemberNames(call, type).FirstOrDefault();
                    if (call.Count == 1)
                        return name == null ? null : new PropertyContext(rules.Member(name), $"{name} of {Target}");
                    // Property(x => x.A, p => ...) returns the builder itself
                    if (name != null)
                        call.Lambda(1, new PropertyContext(rules.Member(name), $"{name} of {Target}"));
                    return this;
                }
                case "Order":
                case "OrderLast":
                {
                    var names = reader.MemberNames(call, type).ToArray();
                    reader.Set(rules.Settings, call.Name, names, call.Location, Target);
                    return this;
                }
                case "Facet" when !isView && type != null:
                    reader.ReadFacet(call, type, model);
                    return this;
                case "View" when type == null || isView:
                    reader.Report(NotReadable, call.Location, "Views are defined on Dto<T> or Dto(typeof(...)); a namespace, the view defaults or a view cannot have views.");
                    return this;
                case "View" when !isView && type != null:
                {
                    if (!call.TryString(0, out var key) || string.IsNullOrWhiteSpace(key))
                    {
                        reader.Report(NotReadable, call.Location, "A view needs a constant, non-empty name (its GeneratedClassName).");
                        return this;
                    }
                    call.Lambda(1, new DtoContext(rules.View(key!.Trim(), call.Location), type, true, model));
                    return this;
                }
                case "Emit":
                    if (reader.ReadEmit(call) is { } emit)
                        rules.Emits.Add(emit);
                    return this;
                case "Typescript" when !isView && type != null:
                {
                    var key = TypescriptNames.Key(type);
                    if (!model.TypescriptTypes.TryGetValue(key, out var ts))
                        model.TypescriptTypes[key] = ts = new TypescriptTypeConfig();
                    call.Lambda(0, new TypescriptTypeContext(ts, type));
                    return this;
                }
                case "GeneratedClassName" when isView:
                    reader.Report(NotReadable, call.Location, "The name of a view is set by View(name).");
                    return this;
                case "Attribute" when call.TypeArgument != null:
                    if (reader.TypedAttribute(call) is { } attribute)
                        reader.AddAttribute(rules.Settings, attribute, call.Location);
                    return this;
                case "BaseType" or "Interface" when reader.TypedSetting(call, rules.Settings, Target):
                    return this;
                default:
                    var setting = Resolve(call.Name, member: false);
                    if (setting != "BaseMembersFirst" && !DtoSettings.Contains(setting))
                        return Unknown;
                    if (call.TryConstant(0, out var value))
                        reader.Set(rules.Settings, setting, AliasValue(call.Name, value), call.Location, Target);
                    return this;
            }
        }
    }

    /// <summary>Facets&lt;T&gt;(f => f.Facet(x => x.Member, o => ...)).</summary>
    private sealed class FacetsContext(INamedTypeSymbol type, FluentModel model) : Context
    {
        public override Context? Invoke(FluentConfigReader reader, Call call)
        {
            if (call.Name != "Facet")
                return Unknown;
            reader.ReadFacet(call, type, model);
            return this;
        }
    }

    // Facet(x => x.Member, o => ...): the settings become C# expressions of the generated registration
    private void ReadFacet(Call call, INamedTypeSymbol type, FluentModel model)
    {
        var member = MemberNames(call, type).FirstOrDefault();
        if (member == null)
            return;
        var facet = model.Facet(type, member, call.Location);
        call.Lambda(1, new FacetContext(facet, $"facet {member} of {type.Name}"));
    }

    /// <summary>The settings of one facet, named like the properties of [ProvideFacet]; read into C# expressions.</summary>
    private sealed class FacetContext(FluentFacet facet, string target) : Context
    {
        private static readonly HashSet<string> Names = ["Label", "Type", "MultiSelect", "GroupOperator", "Order", "TopDistinct", "ValuePath", "LabelPath", "ValueType"];

        public override Context? Invoke(FluentConfigReader reader, Call call)
        {
            if (!Names.Contains(call.Name))
                return Unknown;
            string? expression;
            if (call.TypeArgument != null)
                expression = $"typeof({FluentFacet.TypeOfName(call.TypeArgument)})";
            else if (call.Method.Parameters[0].Type is INamedTypeSymbol { Name: "Type" } && call.IsTypeOf(0))
                expression = call.TypeOf(0) is { } t ? $"typeof({FluentFacet.TypeOfName(t)})" : null;
            else if (!call.TryConstant(0, out var value))
                expression = null;
            else
                expression = FluentFacet.Literal(value, call.Method.Parameters[0].Type);
            if (expression != null)
                reader.Set(facet.Settings, call.Name, expression, call.Location, target);
            return this;
        }
    }

    /// <summary>Property(...): GenerationPropertySetting names plus Ignore()/Include().</summary>
    private sealed class PropertyContext(FluentMemberRules rules, string target) : Context
    {
        public override Context? Invoke(FluentConfigReader reader, Call call)
        {
            if (call.Name is "Ignore" or "Include")
            {
                reader.Set(rules.Settings, "Ignore", call.Name == "Ignore", call.Location, target);
                return this;
            }
            if (call.Name == "Attribute" && call.TypeArgument != null)
            {
                if (reader.TypedAttribute(call) is { } attribute)
                    reader.AddAttribute(rules.Settings, attribute, call.Location);
                return this;
            }
            var name = Resolve(call.Name, member: true);
            if (!PropertySettings.Contains(name))
                return Unknown;
            if (call.TryConstant(0, out var value))
                reader.Set(rules.Settings, name, AliasValue(call.Name, value), call.Location, target);
            return this;
        }
    }

    /// <summary>Typescript(t => ...): settings by name onto a TypescriptGenerationConfig, lists, type map and per-type rules.</summary>
    private sealed class TypescriptGenerationContext(TypescriptGenerationConfig config) : Context
    {
        private static readonly HashSet<string> Lists = ["IncludeNamespaces", "IncludeTypes", "IncludeBaseTypes", "ExcludeNamespaces", "ExcludeTypes", "ExcludeBaseTypes", "IncludeMembersWithAttributes", "IncludeTypesWithAttributes"];
        private static readonly HashSet<string> Settings = Without(FluentModel.SettingNames(typeof(TypescriptGenerationConfig)), "TypeMap", "Types", "IsFluent");

        public override Context? Invoke(FluentConfigReader reader, Call call)
        {
            switch (call.Name)
            {
                case "Include":
                case "Exclude":
                case "IncludeDerivedFrom":
                case "ExcludeDerivedFrom":
                {
                    if ((call.TypeArgument ?? call.TypeOf(0)) is not { } type)
                        return this;
                    var list = call.Name switch
                    {
                        "Include" => config.IncludeTypes,
                        "Exclude" => config.ExcludeTypes,
                        "IncludeDerivedFrom" => config.IncludeBaseTypes,
                        _ => config.ExcludeBaseTypes
                    };
                    list.Add(TypescriptNames.Key(type));
                    return this;
                }
                case "IncludeMembersWithAttribute":
                    if (call.TypeArgument != null)
                        config.IncludeMembersWithAttributes.Add(TypescriptNames.Key(call.TypeArgument));
                    return this;
                case "IncludeTypesWithAttribute":
                    if (call.TypeArgument != null && call.TryString(0, out var firstArgument))
                        config.IncludeTypesWithAttributes.Add(TypescriptNames.Key(call.TypeArgument) + (firstArgument == null ? "" : "=" + firstArgument));
                    return this;
                case "TypeMap":
                {
                    string? key;
                    int index;
                    if (call.TypeArgument != null || call.Method.Parameters[0].Type.Name == "Type")
                    {
                        var type = call.TypeArgument ?? call.TypeOf(0);
                        key = type == null ? null : TypescriptNames.Key(type);
                        index = call.TypeArgument != null ? 0 : 1;
                    }
                    else
                    {
                        if (!call.TryString(0, out key) || key == null)
                            return this;
                        key = TypescriptNames.Normalize(key);
                        index = 1;
                    }
                    if (key != null && call.TryString(index, out var ts) && ts != null)
                        config.TypeMap[key] = ts;
                    return this;
                }
                case "Type":
                {
                    string? key;
                    INamedTypeSymbol? type = null;
                    if (call.TypeArgument != null)
                    {
                        type = call.TypeArgument as INamedTypeSymbol;
                        key = TypescriptNames.Key(call.TypeArgument);
                    }
                    else if (!call.TryString(0, out key) || string.IsNullOrWhiteSpace(key))
                        return this;
                    else
                        key = TypescriptNames.Normalize(key!);
                    if (!config.Types.TryGetValue(key!, out var rules))
                        config.Types[key!] = rules = new TypescriptTypeConfig();
                    call.Lambda(call.TypeArgument != null ? 0 : 1, new TypescriptTypeContext(rules, type));
                    return this;
                }
            }
            if (Lists.Contains(call.Name))
            {
                if (call.TryConstant(0, out var values) && values is string[] items)
                    ((List<string>)typeof(TypescriptGenerationConfig).GetProperty(call.Name)!.GetValue(config)!).AddRange(items);
                return this;
            }
            if (!Settings.Contains(call.Name))
                return Unknown;
            if (call.TryConstant(0, out var value))
                FluentModel.Set(config, call.Name, value);
            return this;
        }
    }

    /// <summary>The TypeScript of one type: Name, Ignore() (the type), Ignore(members), Property(member), member attribute filter, derived types.</summary>
    private sealed class TypescriptTypeContext(TypescriptTypeConfig rules, INamedTypeSymbol? type) : Context
    {
        public override Context? Invoke(FluentConfigReader reader, Call call)
        {
            switch (call.Name)
            {
                case "Name":
                    if (call.TryString(0, out var name))
                        rules.Name = name;
                    return this;
                case "Ignore" when call.Count == 0:
                    rules.Ignore = true;
                    return this;
                case "Ignore":
                    foreach (var member in reader.MemberNames(call, type))
                        rules.Member(member).Ignore = true;
                    return this;
                case "Property":
                {
                    var member = reader.MemberNames(call, type).FirstOrDefault();
                    return member == null ? null : new TypescriptPropertyContext(rules.Member(member));
                }
                case "OptionalDefaultValues":
                    if (call.TryConstant(0, out var optional))
                        rules.OptionalDefaultValues = optional as bool? ?? true;
                    return this;
                case "IncludeMembersWithAttributes":
                    if (call.TryConstant(0, out var attributes) && attributes is string[] names)
                        rules.IncludeMembersWithAttributes = [.. names];
                    return this;
                case "IncludeMembersWithAttribute":
                    if (call.TypeArgument != null)
                        (rules.IncludeMembersWithAttributes ??= []).Add(TypescriptNames.Key(call.TypeArgument));
                    return this;
                case "DerivedTypes":
                    if (call.TryConstant(0, out var derived) && derived is string[] patterns)
                        rules.DerivedTypes.AddRange(patterns);
                    return this;
                case "DerivedType":
                {
                    var derivedType = call.TypeArgument ?? call.TypeOf(0);
                    if (derivedType != null && call.TryString(call.TypeArgument != null ? 0 : 1, out var value))
                        rules.DerivedTypes.Add(TypescriptNames.Key(derivedType) + (value == null ? "" : "=" + value));
                    return this;
                }
                case "Discriminator":
                    if (call.TryString(0, out var property))
                        rules.Discriminator = property;
                    return this;
                default:
                    return Unknown;
            }
        }
    }

    /// <summary>The TypeScript of one member.</summary>
    private sealed class TypescriptPropertyContext(TypescriptMemberConfig rules) : Context
    {
        public override Context? Invoke(FluentConfigReader reader, Call call)
        {
            switch (call.Name)
            {
                case "Name":
                case "Type":
                    if (call.TryString(0, out var value))
                    {
                        if (call.Name == "Name")
                            rules.Name = value;
                        else
                            rules.Type = value;
                    }
                    return this;
                case "Optional":
                    if (call.TryConstant(0, out var optional))
                        rules.Optional = optional as bool? ?? true;
                    return this;
                case "Ignore":
                case "Include":
                    rules.Ignore = call.Name == "Ignore";
                    return this;
                default:
                    return Unknown;
            }
        }
    }

    /// <summary>
    /// Attribute&lt;TAttribute&gt;(args) and Attribute&lt;TAttribute&gt;(a => a.Name = value, args) as C# text: the full name without the
    /// "Attribute" suffix (like kept attributes), the arguments as literals. Null and a diagnostic when an argument is not constant.
    /// </summary>
    private string? TypedAttribute(Call call)
    {
        if (call.TypeArgument is not INamedTypeSymbol type)
            return null;
        var arguments = new List<string>();
        switch (call.Argument(call.Count - 1) is { } args ? Unwrap(args) : null)
        {
            case null:
                break;
            case { ConstantValue: { HasValue: true, Value: null } }:
                arguments.Add("null"); // Attribute<X>(null) binds null to the params array itself
                break;
            case IArrayCreationOperation array:
                foreach (var item in array.Initializer?.ElementValues ?? [])
                {
                    if (Literal(item) is not { } literal)
                        return null;
                    arguments.Add(literal);
                }
                break;
            case var other:
                Report(NotReadable, other.Syntax, $"'{Short(other.Syntax)}' is not a constant.");
                return null;
        }
        if (call.Count == 2 && call.Argument(0) is { } properties)
        {
            if (AsLambda(properties) is not { Symbol.Parameters.Length: 1 } lambda)
            {
                Report(NotReadable, properties.Syntax, $"'{Short(properties.Syntax)}' must be a lambda (a => a.Name = value).");
                return null;
            }
            foreach (var statement in lambda.Body.Operations)
            {
                if (statement is IReturnOperation { ReturnedValue: null })
                    continue;
                var (member, instance, value) = statement is IExpressionStatementOperation { Operation: ISimpleAssignmentOperation assignment }
                    ? assignment.Target switch
                    {
                        IPropertyReferenceOperation p => ((ISymbol?)p.Property, p.Instance, assignment.Value),
                        IFieldReferenceOperation f => (f.Field, f.Instance, assignment.Value),
                        _ => (null, null, null)
                    }
                    : (null, null, null);
                if (member == null || value == null || instance is not IParameterReferenceOperation pr
                    || !SymbolEqualityComparer.Default.Equals(pr.Parameter, lambda.Symbol.Parameters[0]))
                {
                    Report(NotReadable, statement.Syntax, $"'{Short(statement.Syntax)}' must set a member of the attribute (a => a.Name = value).");
                    return null;
                }
                if (Literal(value) is not { } literal)
                    return null;
                arguments.Add($"{member.Name} = {literal}");
            }
        }

        var name = type.Name.Length > "Attribute".Length && type.Name.EndsWith("Attribute", StringComparison.Ordinal)
            ? type.Name.Substring(0, type.Name.Length - "Attribute".Length)
            : type.Name;
        var container = type.ContainingType != null ? type.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + "."
            : type.ContainingNamespace is { IsGlobalNamespace: false } ns ? ns.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + "."
            : "global::";
        var typeArguments = type.TypeArguments.Length == 0 ? ""
            : "<" + string.Join(", ", type.TypeArguments.Select(t => t.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))) + ">";
        return $"[{container}{name}{typeArguments}{(arguments.Count == 0 ? "" : "(" + string.Join(", ", arguments) + ")")}]";
    }

    /// <summary>A constant, typeof or a one-dimensional array of them as C# text; null and a diagnostic for anything else.</summary>
    private string? Literal(IOperation op)
    {
        // boxing to object and implicit conversions go; an explicit constant cast like (byte)1 keeps its type
        while (op is IConversionOperation conversion && (conversion.IsImplicit || !conversion.ConstantValue.HasValue))
            op = conversion.Operand;
        if (op.ConstantValue.HasValue)
            return FluentFacet.Literal(op.ConstantValue.Value, op.Type);
        switch (op)
        {
            case ITypeOfOperation typeOf:
                return $"typeof({FluentFacet.TypeOfName(typeOf.TypeOperand)})";
            case IArrayCreationOperation { Type: IArrayTypeSymbol { Rank: 1 } arrayType } array
                when array.Initializer != null || array.DimensionSizes.All(d => d.ConstantValue is { HasValue: true, Value: 0 }):
            {
                var items = new List<string>();
                foreach (var item in array.Initializer?.ElementValues ?? [])
                {
                    if (Literal(item) is not { } literal)
                        return null;
                    items.Add(literal);
                }
                var elementType = arrayType.ElementType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                return items.Count == 0 ? $"new {elementType}[0]" : $"new {elementType}[] {{ {string.Join(", ", items)} }}";
            }
            default:
                Report(NotReadable, op.Syntax, $"'{Short(op.Syntax)}' is not a constant.");
                return null;
        }
    }

    /// <summary>The member names of a call: selectors or constant strings; unknown names are reported.</summary>
    private IEnumerable<string> MemberNames(Call call, INamedTypeSymbol? type)
    {
        if (call.FirstIsLambdaArray || call.Method.Parameters.FirstOrDefault()?.Type is INamedTypeSymbol { Name: "Expression" })
            return call.Selectors(0).Select(m => m.Name).ToList();
        if (!call.TryConstant(0, out var value))
            return [];
        var names = value switch
        {
            string s => [s],
            string[] array => array,
            _ => Array.Empty<string>()
        };
        if (type != null)
        {
            var members = AllMembers(type);
            foreach (var name in names.Where(n => !members.Contains(n)))
                Report(UnknownMember, call.Location, type.Name, name);
        }
        return names;
    }

    private static HashSet<string> AllMembers(INamedTypeSymbol type)
    {
        var names = new HashSet<string>(StringComparer.Ordinal);
        for (var t = type; t != null; t = t.BaseType)
            foreach (var member in t.GetMembers())
                if (member is IPropertySymbol or IFieldSymbol { IsConst: true })
                    names.Add(member.Name);
        return names;
    }

    private FluentEmit? ReadEmit(Call call)
    {
        if (!call.TryString(0, out var fileName) || !call.TryString(1, out var template) || !call.TryString(2, out var outputPath))
            return null;
        if (string.IsNullOrWhiteSpace(fileName) || template == null)
        {
            Report(BadEmit, call.Location, fileName ?? "", "needs a file name and a template");
            return null;
        }
        return new FluentEmit(fileName!, template, outputPath, call.Location);
    }

    private static HashSet<string> With(HashSet<string> set, params string[] names)
    {
        set.UnionWith(names);
        return set;
    }

    private static HashSet<string> Without(HashSet<string> set, params string[] names)
    {
        set.ExceptWith(names);
        return set;
    }
