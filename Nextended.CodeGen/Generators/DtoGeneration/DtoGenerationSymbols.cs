public class DtoGenerationSymbols
{
    public INamedTypeSymbol? AutoGenerateDto, Ignore, PropertySetting, GenerateBeforeAndAfterAssignPartialsInMapping;
    public DtoGenerationConfig Config { get; private set; } = null!;
    private bool deepProperties => Config?.DeepProperties ?? false;

    /// <summary>The DTO being generated (default DTO or view); null outside of a unit.</summary>
    internal DtoUnit? Current { get; private set; }

    /// <summary>All valid views of the generated types (every [AutoGenerateDto] after the first on a type).</summary>
    internal List<DtoUnit> Views { get; } = [];

    internal List<Diagnostic> Diagnostics { get; } = [];

    /// <summary>The fluent configuration of the compilation (empty without configuration classes).</summary>
    internal FluentModel Fluent { get; private set; } = FluentModel.Empty;

    private HashSet<string> _generated = new(StringComparer.Ordinal);

    private readonly Dictionary<ISymbol, DtoUnit> _defaultUnits = new(SymbolEqualityComparer.Default);

    /// <summary>Makes <paramref name="unit"/> the DTO being generated until the result is disposed.</summary>
    internal IDisposable Enter(DtoUnit unit)
    {
        var previous = Current;
        Current = unit;
        return new Scope(() => Current = previous);
    }

    private sealed class Scope(Action dispose) : IDisposable
    {
        public void Dispose() => dispose();
    }

    /// <summary>The default DTO of a type; its view settings come from its first [AutoGenerateDto], or the one of the nearest base that has one.</summary>
    internal DtoUnit DefaultUnit(INamedTypeSymbol type)
    {
        if (_defaultUnits.TryGetValue(type, out var unit))
            return unit;
        AttributeData? data = null;
        var chain = new List<INamedTypeSymbol>();
        for (var t = type; t != null && data == null; t = t.BaseType)
        {
            chain.Add(t);
            data = t.GetAttributes().FirstOrDefault(a => IsAutoGenerateDto(a.AttributeClass));
        }
        unit = DtoUnit.Default(type, data);
        if (Fluent.HasRules) // the fluent rules from the type that declares the attribute down to this one, nearest last
            for (var i = chain.Count - 1; i >= 0; i--)
                foreach (var rules in Fluent.TypeLevel(chain[i]))
                    unit.Apply(rules);
        return _defaultUnits[type] = unit;
    }

    /// <summary>True while a view of <paramref name="type"/> is generated: it is flat (all members, no base DTO).</summary>
    internal bool IsView(ITypeSymbol? type)
        => Current is { IsView: true } unit && type != null
           && SymbolEqualityComparer.Default.Equals(unit.Type.OriginalDefinition, type.OriginalDefinition);

    /// <summary>The view whose settings these are, null for the settings of a default DTO.</summary>
    internal DtoUnit? ViewOf(AutoGenerateDtoAttribute? cfg) => cfg == null ? null : Views.FirstOrDefault(v => ReferenceEquals(v.ViewAttr, cfg));

    /// <summary>
    /// The view a member type takes in the DTO being generated: one listed in its UseViews, declared by the type or a base of it.
    /// Types of the generated type's own hierarchy keep their DTOs (base DTOs, derived type mappings).
    /// </summary>
    internal DtoUnit? FindUsedView(INamedTypeSymbol type)
    {
        if (Current is not { UseViews.Length: > 0 } unit || Views.Count == 0)
            return null;
        if (DtoUnit.IsSelfOrBase(unit.Type, type) || DtoUnit.IsSelfOrBase(type, unit.Type))
            return null;
        for (var t = type; t != null; t = t.BaseType)
            foreach (var view in Views)
                if (SymbolEqualityComparer.Default.Equals(view.Type.OriginalDefinition, t.OriginalDefinition) && unit.UseViews.Contains(view.Key))
                    return view;
        return null;
    }

    internal bool IsAutoGenerateDto(INamedTypeSymbol? attributeClass)
    {
        for (var a = attributeClass; a != null && AutoGenerateDto != null; a = a.BaseType)
            if (SymbolEqualityComparer.Default.Equals(a, AutoGenerateDto))
                return true;
        return false;
    }

    private static readonly DiagnosticDescriptor ViewWithoutName = new(
        "NCG010", "DTO view without a name", "The additional [AutoGenerateDto] on {0} is a DTO view and needs a GeneratedClassName; it is not generated",
        "Nextended.CodeGen", DiagnosticSeverity.Warning, isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor ViewNameTaken = new(
        "NCG011", "DTO view name taken", "The DTO view {0} of {1} is not generated: {2} already generates the type {3}. Several entities share one view through a common base type that declares it.",
        "Nextended.CodeGen", DiagnosticSeverity.Error, isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor ViewMethodTaken = new(
        "NCG012", "DTO view mapping method taken", "The DTO view {0} of {1} is not generated: its mapping method {2} is already used by another DTO of {1}; set ToDtoMethodName",
        "Nextended.CodeGen", DiagnosticSeverity.Error, isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor UnknownView = new(
        "NCG013", "Unknown DTO view", "UseViews of {0} names '{1}', but no generated type declares a DTO view with that GeneratedClassName",
        "Nextended.CodeGen", DiagnosticSeverity.Warning, isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor BadPropertyName = new(
        "NCG014", "Invalid PropertyNames entry", "PropertyNames of {0}: '{1}' {2}",
        "Nextended.CodeGen", DiagnosticSeverity.Warning, isEnabledByDefault: true);

    /// <summary>Reads the views of the generated types and checks every UseViews and PropertyNames entry.</summary>
    internal void CollectViews(List<INamedTypeSymbol> types)
    {
        var taken = new Dictionary<string, INamedTypeSymbol>(StringComparer.Ordinal);
        foreach (var type in types)
        {
            var cfg = type.DefaultClassCfg(this);
            taken[$"{Namespace(type, cfg)}.{GetDtoClassName(type, cfg, false)}"] = type;
        }

        foreach (var type in types)
        {
            var methods = new HashSet<string>(StringComparer.Ordinal);
            var defaultCfg = type.DefaultClassCfg(this);
            if (defaultCfg.GenerateMapping)
                methods.Add(GetToDtoMethodName(type, defaultCfg));

            foreach (var (data, attr, ownRules) in ViewCandidates(type))
            {
                var fluentRules = WithViewDefaults(type, data, attr, ownRules);
                if (fluentRules != null)
                    FluentModel.Apply(attr, fluentRules.Settings);
                var location = data?.ApplicationSyntaxReference?.GetSyntax().GetLocation() ?? fluentRules?.Location ?? Location.None;
                if (string.IsNullOrWhiteSpace(attr.GeneratedClassName))
                {
                    Diagnostics.Add(Diagnostic.Create(ViewWithoutName, location, type.Name));
                    continue;
                }
                // a view is named To<ViewClassName> unless it sets ToDtoMethodName; the configuration's ToDtoMethodName is for default DTOs
                var ownToDto = attr.ToDtoMethodName;
                attr.ApplyConfigDefaults(Config);
                var name = GetDtoClassName(type, attr, false);
                attr.ToDtoMethodName = !string.IsNullOrWhiteSpace(ownToDto) ? ownToDto : $"To{name}";

                var fullName = $"{Namespace(type, attr)}.{name}";
                if (taken.TryGetValue(fullName, out var owner))
                {
                    Diagnostics.Add(Diagnostic.Create(ViewNameTaken, location, attr.GeneratedClassName, type.Name, owner.Name, fullName));
                    continue;
                }
                if (attr.GenerateMapping && !methods.Add(attr.ToDtoMethodName!))
                {
                    Diagnostics.Add(Diagnostic.Create(ViewMethodTaken, location, attr.GeneratedClassName, type.Name, attr.ToDtoMethodName));
                    continue;
                }
                taken[fullName] = type;
                var view = DtoUnit.View(type, data, attr);
                view.FluentRules = fluentRules;
                view.Apply(fluentRules);
                Views.Add(view);
            }
        }

        if (Fluent.HasRules)
            CheckInheritedMemberRules(types);

        var keys = new HashSet<string>(Views.Select(v => v.Key!), StringComparer.Ordinal);
        var reported = new HashSet<object>();
        foreach (var unit in types.Select(DefaultUnit).Concat(Views))
        {
            var origin = (object?)unit.Data ?? unit.FluentRules;
            if (origin == null || !reported.Add(origin))
                continue;
            var location = unit.Location;
            foreach (var key in unit.UseViews.Where(k => !keys.Contains(k)))
                Diagnostics.Add(Diagnostic.Create(UnknownView, location, unit.Type.Name, key));
            foreach (var entry in unit.MalformedPropertyNames)
                Diagnostics.Add(Diagnostic.Create(BadPropertyName, location, unit.Type.Name, entry, "is not \"SourceName=DtoName\""));
            var members = new HashSet<string>(AllProperties(unit.Type).Select(p => p.Name), StringComparer.Ordinal);
            foreach (var source in unit.PropertyNames.Keys.Where(k => !members.Contains(k)))
                Diagnostics.Add(Diagnostic.Create(BadPropertyName, location, unit.Type.Name, source, $"is no property of {unit.Type.Name}"));
        }
    }

    /// <summary>The views of a type: its further [AutoGenerateDto]s, refined by fluent View(...)s of the same key, then the fluent-only views.</summary>
    private List<(AttributeData? Data, AutoGenerateDtoAttribute Attr, FluentTypeRules? Rules)> ViewCandidates(INamedTypeSymbol type)
    {
        var candidates = type.GetAttributes().Where(a => IsAutoGenerateDto(a.AttributeClass)).Skip(1)
            .Select(d => ((AttributeData?)d, d.MapTo<AutoGenerateDtoAttribute>(null), (FluentTypeRules?)null)).ToList();
        foreach (var rules in Fluent.Type(type)?.Views ?? [])
        {
            var index = candidates.FindIndex(c => c.Item2.GeneratedClassName == rules.ViewKey);
            if (index >= 0)
                candidates[index] = (candidates[index].Item1, candidates[index].Item2, rules);
            else
                candidates.Add((null, new AutoGenerateDtoAttribute { GeneratedClassName = rules.ViewKey }, rules));
        }
        return candidates;
    }

    /// <summary>
    /// The fluent rules of a view with the ViewDefaults under them: a default setting applies unless the view's [AutoGenerateDto] or its
    /// View(...) sets it. The member rules of the defaults are looked up last (<see cref="CollectMemberRules"/>).
    /// </summary>
    private FluentTypeRules? WithViewDefaults(INamedTypeSymbol type, AttributeData? data, AutoGenerateDtoAttribute attr, FluentTypeRules? own)
    {
        if (Fluent.ViewDefaults is not { } defaults)
            return own;
        var merged = new FluentTypeRules(type, null, attr.GeneratedClassName, own?.Location ?? defaults.Location);
        foreach (var setting in defaults.Settings)
            if (data == null || data.NamedArguments.All(a => a.Key != setting.Key))
                merged.Settings[setting.Key] = setting.Value;
        if (own != null)
        {
            foreach (var setting in own.Settings)
                merged.Settings[setting.Key] = setting.Value;
            foreach (var member in own.Members)
                merged.Members[member.Key] = member.Value;
            merged.Emits.AddRange(own.Emits);
        }
        merged.Emits.AddRange(defaults.Emits);
        return merged;
    }

    /// <summary>NCG023: a member rule on a type for an inherited member that its default DTO takes from a base DTO.</summary>
    private void CheckInheritedMemberRules(List<INamedTypeSymbol> types)
    {
        foreach (var type in types)
        {
            if (Fluent.Type(type) is not { } rules)
                continue;
            foreach (var entry in rules.Members)
            {
                var member = AllProperties(type).FirstOrDefault(p => p.Name == entry.Key);
                if (member == null)
                    continue;
                var owner = Owner(type, member);
                if (SymbolEqualityComparer.Default.Equals(owner.OriginalDefinition, type.OriginalDefinition))
                    continue;
                var location = entry.Value.Settings.Values.Select(v => v.Location).FirstOrDefault() ?? Location.None;
                Diagnostics.Add(Diagnostic.Create(FluentConfigReader.InheritedMemberRule, location, entry.Key, type.Name, owner.Name));
            }
        }
    }

    /// <summary>
    /// The type whose default DTO carries <paramref name="member"/> when generating the default DTO of <paramref name="dtoType"/>:
    /// the highest generated base whose DTO contains it (an inherited member lives in the base DTO), else <paramref name="dtoType"/>
    /// (also when every base DTO leaves the member out and the derived DTO takes it in again).
    /// </summary>
    private INamedTypeSymbol Owner(INamedTypeSymbol dtoType, ISymbol member)
    {
        var containing = member.ContainingType;
        var owner = dtoType;
        if (containing == null || SymbolEqualityComparer.Default.Equals(containing.OriginalDefinition, dtoType.OriginalDefinition))
            return owner;
        for (var t = dtoType.BaseType; t != null; t = t.BaseType)
        {
            var declares = SymbolEqualityComparer.Default.Equals(t.OriginalDefinition, containing.OriginalDefinition);
            if (_generated.Contains(FluentModel.Key(t)) && (deepProperties || declares)
                && !IsExcluded(t, member, t.DefaultClassCfg(this)?.PropertiesToIgnore ?? [], Ignore))
                owner = t;
            if (declares)
                break;
        }
        return owner;
    }

    /// <summary>
    /// The fluent settings of a member in the DTO of <paramref name="dtoType"/> (a view when <paramref name="view"/> is set), nearest first:
    /// the view, the type whose DTO carries the member and its bases, the namespace rules. Null without fluent rules for it.
    /// </summary>
    internal Dictionary<string, FluentValue>? MemberRules(INamedTypeSymbol dtoType, ISymbol member, DtoUnit? view)
        => Fluent.HasRules ? CollectMemberRules(view != null ? dtoType : Owner(dtoType, member), member, view) : null;

    // the view, then start and its bases, then the namespace rules of start; the nearest setting wins
    private Dictionary<string, FluentValue>? CollectMemberRules(INamedTypeSymbol start, ISymbol member, DtoUnit? view)
    {
        Dictionary<string, FluentValue>? result = null;
        void Add(FluentTypeRules? rules)
        {
            if (rules == null || !rules.Members.TryGetValue(member.Name, out var memberRules))
                return;
            foreach (var setting in memberRules.Settings)
                if (!(result ??= new Dictionary<string, FluentValue>(StringComparer.Ordinal)).ContainsKey(setting.Key))
                    result[setting.Key] = setting.Value;
        }

        Add(view?.FluentRules);
        for (var t = start; t != null; t = t.BaseType)
            Add(Fluent.Type(t));
        foreach (var rules in Fluent.NamespaceRulesOf(start).Reverse())
            Add(rules);
        if (view != null)
            Add(Fluent.ViewDefaults);
        return result;
    }

    /// <summary>
    /// True when a member stays out of the DTO of <paramref name="dtoType"/>: the most specific fluent Ignore/Include decides (the view,
    /// the type itself, then its bases: an Include on Dto&lt;Currency&gt; beats an Ignore on Dto&lt;Entity&gt;), else the attributes.
    /// </summary>
    internal bool IsExcluded(INamedTypeSymbol dtoType, ISymbol member, ICollection<string> ignoredByName, INamedTypeSymbol? ignoreAttr)
    {
        if (Fluent.HasRules && CollectMemberRules(dtoType, member, IsView(dtoType) ? Current : null) is { } rules
                            && rules.TryGetValue("Ignore", out var ignore) && ignore.Value is bool b)
            return b;
        return ignoredByName.Contains(member.Name)
               || ignoreAttr != null && member.GetAttributes().Any(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, ignoreAttr));
    }

    /// <summary>
    /// The fluent Order / OrderLast / BaseMembersFirst of the DTO of <paramref name="type"/> applied to its members (depth 0 = own members):
    /// BaseMembersFirst sorts by depth, then the Order members go first and the OrderLast members last, each in the order given.
    /// </summary>
    private List<IPropertySymbol> Ordered(INamedTypeSymbol type, List<(IPropertySymbol Property, int Depth)> members)
    {
        object? order = null, last = null, baseFirst = null;
        if (IsView(type))
        {
            order = Current!.FluentRules?.Get("Order");
            last = Current.FluentRules?.Get("OrderLast");
            baseFirst = Current.FluentRules?.Get("BaseMembersFirst");
        }
        else
        {
            foreach (var rules in Fluent.TypeLevel(type))
            {
                order = rules.Get("Order") ?? order;
                last = rules.Get("OrderLast") ?? last;
                baseFirst = rules.Get("BaseMembersFirst") ?? baseFirst;
            }
        }
        IEnumerable<(IPropertySymbol Property, int Depth)> result = members;
        if (baseFirst is true)
            result = result.OrderByDescending(m => m.Depth);
        var first = order as string[] ?? [];
        var end = last as string[] ?? [];
        if (first.Length > 0 || end.Length > 0)
            result = result.OrderBy(m => Array.IndexOf(first, m.Property.Name) is var i && i >= 0 ? i
                : Array.IndexOf(end, m.Property.Name) is var j && j >= 0 ? first.Length + 1 + j
                : first.Length);
        return result.Select(m => m.Property).ToList();
    }

    /// <summary>The members of the DTO of a type with fluent rules (Ignore/Include, Order, BaseMembersFirst); lazily, like the attribute-only path.</summary>
    private IEnumerable<IPropertySymbol> FluentDtoProperties(INamedTypeSymbol type, INamedTypeSymbol? ignoreAttr, bool deep)
    {
        var ignoredByName = type.ClassCfg(this)?.PropertiesToIgnore ?? [];
        var seen = new HashSet<string>(StringComparer.Ordinal);
        var members = new List<(IPropertySymbol, int)>();
        var depth = 0;
        for (var t = type; t != null; t = deep ? t.BaseType : null, depth++)
        {
            foreach (var p in t.MembersInSourceOrder().OfType<IPropertySymbol>())
            {
                if (p.DeclaredAccessibility != Accessibility.Public || p.IsStatic) continue;
                if (IsExcluded(type, p, ignoredByName, ignoreAttr)) continue;
                if (seen.Add(p.Name)) members.Add((p, depth));
            }
        }
        foreach (var p in Ordered(type, members))
            yield return p;
    }

    private static IEnumerable<IPropertySymbol> AllProperties(INamedTypeSymbol type)
    {
        for (var t = type; t != null; t = t.BaseType)
            foreach (var p in t.MembersInSourceOrder().OfType<IPropertySymbol>())
                yield return p;
    }

    internal static ITypeSymbol NormalizeForLookup(ITypeSymbol type)
    {
        // Nullable<T> -> T
        type = type.UnwrapNullableTypeSymbol(); // RoslynHelper

        // Referenz-Nullability "?" entfernen
        if (type.NullableAnnotation == NullableAnnotation.Annotated)
            type = type.WithNullableAnnotation(NullableAnnotation.None);

        return type;
    }

    public IEnumerable<IPropertySymbol> GetDtoPropertiesDeep(
        INamedTypeSymbol type,
        INamedTypeSymbol? ignoreAttr)
    {
        if (Fluent.HasRules)
        {
            foreach (var p in FluentDtoProperties(type, ignoreAttr, deep: true))
                yield return p;
            yield break;
        }

        var ignoredByName = type.ClassCfg(this)?.PropertiesToIgnore ?? [];

        var seen = new HashSet<string>(StringComparer.Ordinal);
        for (var t = type; t != null; t = t.BaseType)
        {
            foreach (var p in t.MembersInSourceOrder().OfType<IPropertySymbol>())
            {
                if (p.DeclaredAccessibility != Accessibility.Public || p.IsStatic) continue;
                if (ignoredByName.Contains(p.Name)) continue;
                if (ignoreAttr != null && p.GetAttributes().Any(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, ignoreAttr))) continue;
                if (seen.Add(p.Name)) yield return p;
            }
        }
    }

    public IEnumerable<IPropertySymbol> GetDtoProperties(INamedTypeSymbol type, INamedTypeSymbol? ignoreAttr)
    {
        if (Fluent.HasRules)
            return FluentDtoProperties(type, ignoreAttr, deepProperties || IsView(type));

        var ignoredByName = type.ClassCfg(this)?.PropertiesToIgnore ?? [];

        if (deepProperties || IsView(type))
            return GetDtoPropertiesDeep(type, ignoreAttr);
        return type.MembersInSourceOrder().OfType<IPropertySymbol>().Where(p =>
            p.DeclaredAccessibility == Accessibility.Public &&
            !p.IsStatic &&
            !ignoredByName.Contains(p.Name) &&
            (ignoreAttr == null || !p.GetAttributes().Any(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, ignoreAttr)))
        );
    }

    public static DtoGenerationSymbols Collect(Compilation c, DtoGenerationConfig config) => Collect(c, config, null);

    internal static DtoGenerationSymbols Collect(Compilation c, DtoGenerationConfig config, FluentModel? fluent) => new()
    {
        Fluent = fluent ?? FluentModel.Empty,
        AutoGenerateDto = c.GetTypeByMetadataName(typeof(AutoGenerateDtoAttribute).FullName!),
        GenerateBeforeAndAfterAssignPartialsInMapping = c.GetTypeByMetadataName(typeof(GenerateBeforeAndAfterAssignPartialsInMappingAttribute).FullName!),
        Ignore = c.GetTypeByMetadataName(typeof(IgnoreOnGenerationAttribute).FullName!),
        PropertySetting = c.GetTypeByMetadataName(typeof(GenerationPropertySettingAttribute).FullName!),
        Config = config
    };

    public List<INamedTypeSymbol> FindTypesWithAttribute(Compilation compilation)
    {
        if (AutoGenerateDto == null)
            return new List<INamedTypeSymbol>();
        List<INamedTypeSymbol> types;
        if (!Fluent.HasRules)
        {
            types = FindTypesWithAttributeFromAllAssemblies(compilation, AutoGenerateDto);
            types = Config?.TypesToIgnore is { Length: > 0 } ignored ? types.Where(t => !IsIgnoredType(t, ignored)).ToList() : types;
        }
        else
        {
            var fluentTypes = Fluent.Types.Values.Where(r => r.Generate && r.Type != null).Select(r => r.Type!).ToList();
            types = FindTypesWithAttributeFromAllAssemblies(compilation, [AutoGenerateDto], fluentTypes, FluentAutoGenerateDerived);
            var ignored = Config?.TypesToIgnore ?? [];
            types = types.Where(t => !IsIgnoredType(t, ignored)).ToList();
        }
        _generated = new HashSet<string>(types.Select(FluentModel.Key), StringComparer.Ordinal);
        return types;
    }

    // the AutoGenerateDerived a fluent rule sets for a type, null when none does
    private bool? FluentAutoGenerateDerived(INamedTypeSymbol type)
    {
        bool? result = null;
        foreach (var rules in Fluent.TypeLevel(type))
            if (rules.Get(nameof(AutoGenerateDtoAttribute.AutoGenerateDerived)) is bool b)
                result = b;
        return result;
    }

    // listed itself, or marked only through the AutoGenerateDerived of a base and derived from a listed type
    private bool IsIgnoredType(INamedTypeSymbol type, string[] ignored)
    {
        bool Listed(INamedTypeSymbol t, string[] names)
            => names.Contains(t.Name) || names.Contains($"{t.ContainingNamespace?.ToDisplayString()}.{t.Name}") || Fluent.IsIgnoredType(t);

        if (Listed(type, ignored))
            return true;
        if (type.GetAttributeInstance<AutoGenerateDtoAttribute>(AutoGenerateDto!) != null || Fluent.Type(type) is { Generate: true })
            return false;
        for (var t = type.BaseType; t != null; t = t.BaseType)
            if (Listed(t.OriginalDefinition, ignored))
                return true;
        return false;
    }

    public static List<INamedTypeSymbol> FindTypesWithAttributeFromAllAssemblies(
        Compilation compilation, params INamedTypeSymbol[] attributeTypes)
        => FindTypesWithAttributeFromAllAssemblies(compilation, attributeTypes, null, null);

    /// <summary>
    /// The types with one of the attributes plus <paramref name="extraTypes"/> (fluent Dto&lt;T&gt;), and the types derived from those whose
    /// AutoGenerateDerived is set (<paramref name="autoGenerateDerived"/> overrides the attribute when it returns a value).
    /// </summary>
    internal static List<INamedTypeSymbol> FindTypesWithAttributeFromAllAssemblies(
        Compilation compilation, INamedTypeSymbol[] attributeTypes, IEnumerable<INamedTypeSymbol>? extraTypes, Func<INamedTypeSymbol, bool?>? autoGenerateDerived)
    {
        static IEnumerable<INamedTypeSymbol> FindAllTypes(INamespaceSymbol ns)
        {
            foreach (var member in ns.GetMembers())
            {
                if (member is INamespaceSymbol childNs)
                {
                    foreach (var t in FindAllTypes(childNs))
                        yield return t;
                }
                else if (member is INamedTypeSymbol t)
                {
                    yield return t;
                }
            }
        }

        static bool IsAttributeOrDerived(INamedTypeSymbol? attrClass, INamedTypeSymbol expectedBase)
        {
            while (attrClass != null)
            {
                if (SymbolEqualityComparer.Default.Equals(attrClass, expectedBase))
                    return true;
                attrClass = attrClass.BaseType;
            }
            return false;
        }

        var allTypes = FindAllTypes(compilation.GlobalNamespace).ToList();

        var attributedTypes = allTypes
            .Where(symbol => symbol.GetAttributes().Any(a =>
                attributeTypes.Any(attr => IsAttributeOrDerived(a.AttributeClass, attr))))
            .ToList();
        if (extraTypes != null)
            attributedTypes = attributedTypes.Concat(extraTypes).Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default).ToList();

        // Neue Liste, damit keine Duplikate und übersichtlich!
        var result = new HashSet<INamedTypeSymbol>(attributedTypes, SymbolEqualityComparer.Default);

        // Abgeleitete Typen finden (nur falls AutoGenerateDerived)
        foreach (var baseType in attributedTypes)
        {
            var autoAttr = baseType.GetAttributeInstance<AutoGenerateDtoAttribute>(attributeTypes[0]);
            if ((autoGenerateDerived?.Invoke(baseType) ?? autoAttr?.AutoGenerateDerived) == true)
            {
                foreach (var t in allTypes.Where(t => t.TypeKind == TypeKind.Class))
                {
                    var curr = t.BaseType;
                    while (curr != null)
                    {
                        // WICHTIG: bei Generics immer OriginalDefinition vergleichen
                        var currDef = (curr as INamedTypeSymbol)?.OriginalDefinition ?? curr;
                        var baseDef = (baseType as INamedTypeSymbol)?.OriginalDefinition ?? baseType;

                        if (SymbolEqualityComparer.Default.Equals(currDef, baseDef))
                        {
                            result.Add(t);
                            break;
                        }
                        curr = curr.BaseType;
                    }
                }
            }
        }

        return result.ToList();
    }

    public static string GetDtoClassName(ITypeSymbol type, AutoGenerateDtoAttribute? attr, bool asInterface)
    {
        var main = !string.IsNullOrEmpty(attr?.GeneratedClassName) ? attr.GeneratedClassName : type.Name;
        int idx = main.IndexOf('`');
        if (idx >= 0) main = main.Substring(0, idx);
        var prefix = attr?.Prefix ?? string.Empty;
        var suffix = attr?.Suffix ?? string.Empty;
        return $"{(asInterface ? "I" : "")}{prefix}{main}{suffix}";
    }

    public static string GetDtoPropertyName(IPropertySymbol prop, GenerationPropertySettingAttribute? info)
        => !string.IsNullOrEmpty(info?.PropertyName) ? info.PropertyName : prop.Name;

    public static string GetToDtoMethodName(ISymbol type, AutoGenerateDtoAttribute? attr)
