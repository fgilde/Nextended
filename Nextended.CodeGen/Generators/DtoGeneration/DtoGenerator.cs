using System;
using System.Collections.Generic;
using System.Linq;
using Microsoft.CodeAnalysis;
using Nextended.CodeGen.Config;
using Nextended.CodeGen.Contracts;
using Nextended.CodeGen.Fluent;
using Nextended.CodeGen.Helper;

namespace Nextended.CodeGen.Generators.DtoGeneration;

public class DtoGenerator : ISourceSubGenerator
{
    private DtoGenerationConfig _config = null!;
    public bool RequireConfig => false;

    /// <summary>The diagnostics of the last run (DTO views); reported to the compilation when run as source generator.</summary>
    public List<Diagnostic> Diagnostics { get; } = [];

    public DtoGenerator()
    { }

    public DtoGenerator(DtoGenerationConfig config)
    {
        _config = config;
    }

    public IEnumerable<GeneratedFile> Execute(GenerationContext context)
    {
        _config = context.Config?.DtoGeneration ?? new DtoGenerationConfig();

        if (context.ExecutionContext.HasValue)
            return Report(context, Execute(context.ExecutionContext.Value));

        if (context.Compilation is null)
            return [];

        return Report(context, Execute(context.Compilation));
    }

    private List<GeneratedFile> Report(GenerationContext context, IEnumerable<GeneratedFile> files)
    {
        var result = files.ToList();
        foreach (var diagnostic in Diagnostics)
            context.ReportDiagnostic(diagnostic);
        return result;
    }

    public IEnumerable<GeneratedFile> Execute(GeneratorExecutionContext context)
        => Execute(context.Compilation);

    public IEnumerable<GeneratedFile> Execute(Compilation compilation)
    {
        // the fluent defaults override the json values (on a copy); attributes still win over them
        _fluent = FluentConfigReader.Read(compilation);
        _config = _fluent.ApplyDefaults(_config ?? new DtoGenerationConfig());
        if (_config.DisableGeneration)
            return [];
        var prefix = !_config.EmitNullableAnnotations || compilation.Options.NullableContextOptions == NullableContextOptions.Disable
            ? "// <auto-generated/>\n"
            : "// <auto-generated/>\n#nullable enable annotations\n";
        return Generate(compilation).Where(f => f != null)
            .Select(f => new GeneratedFile(f.FileName, f.Namespace, prefix + f.Content, f.OutputPath))
            .Concat(EmittedFiles()); // after Generate: the DTO units exist then
    }

    private FluentModel _fluent = FluentModel.Empty;
    private DtoGenerationSymbols? _symbols;
    private DtoCodeGenerator? _generator;
    private List<INamedTypeSymbol> _types = [];

    /// <summary>The additional files of fluent Emit(...) rules: per default DTO (type, namespace, defaults) and per view (view, defaults).</summary>
    private IEnumerable<GeneratedFile> EmittedFiles()
    {
        if (_symbols == null || _generator == null || !_fluent.HasRules)
            yield break;
        var written = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var units = _types.Select(_symbols.DefaultUnit).Concat(_symbols.Views).ToList();
        foreach (var unit in units)
        {
            var emits = new List<FluentEmit>(_fluent.DefaultEmits);
            if (unit.IsView)
                emits.AddRange(unit.FluentRules?.Emits ?? []);
            else
                emits.AddRange(_fluent.TypeLevel(unit.Type).SelectMany(r => r.Emits));
            if (emits.Count == 0)
                continue;

            using var scope = _symbols.Enter(unit);
            var cfg = unit.Type.ClassCfg(_symbols);
            var ns = _generator.Namespace(unit.Type);
            var dto = DtoGenerationSymbols.GetDtoClassName(unit.Type, cfg, false);
            var values = new Dictionary<string, string>
            {
                ["{Dto}"] = dto,
                ["{Interface}"] = DtoGenerationSymbols.GetDtoClassName(unit.Type, cfg, true),
                ["{DtoNamespace}"] = ns,
                ["{DtoFullName}"] = $"{ns}.{dto}",
                ["{Source}"] = unit.Type.Name,
                ["{SourceNamespace}"] = unit.Type.ContainingNamespace?.ToDisplayString() ?? "",
                ["{SourceFullName}"] = unit.Type.ToDisplayString(),
                ["{View}"] = unit.Key ?? ""
            };
            string Fill(string text) => values.Aggregate(text, (current, v) => current.Replace(v.Key, v.Value));

            foreach (var emit in emits)
            {
                var fileName = Fill(emit.FileName);
                var outputPath = emit.OutputPath ?? unit.OutputPath ?? _config.OutputPath;
                if (outputPath == null && !fileName.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
                {
                    Diagnostics.Add(Diagnostic.Create(FluentConfigReader.BadEmit, emit.Location, fileName, "a file that is not .cs needs an output path on disk (Emit(..., outputPath) or the DTO's OutputPath)"));
                    continue;
                }
                if (!written.Add($"{outputPath}|{fileName}"))
                {
                    Diagnostics.Add(Diagnostic.Create(FluentConfigReader.BadEmit, emit.Location, fileName, "another DTO already writes a file of this name; put a placeholder such as {Dto} into the file name"));
                    continue;
                }
                yield return new GeneratedFile(fileName, ns, Fill(emit.Template), outputPath);
            }
        }
    }

    /// <summary>The DTOs of the last run (default DTOs and views): source type and DTO metadata name, for the TypeScript generation.</summary>
    public List<GeneratedDto> GeneratedDtos()
    {
        var result = new List<GeneratedDto>();
        if (_symbols == null || _generator == null)
            return result;
        foreach (var unit in _types.Select(_symbols.DefaultUnit).Concat(_symbols.Views))
        {
            using var scope = _symbols.Enter(unit);
            var cfg = unit.Type.ClassCfg(_symbols);
            var arity = unit.Type.TypeParameters.Length;
            result.Add(new GeneratedDto(unit.Type, $"{_generator.Namespace(unit.Type)}.{DtoGenerationSymbols.GetDtoClassName(unit.Type, cfg, false)}{(arity > 0 ? "`" + arity : "")}"));
        }
        return result;
    }

    private IEnumerable<GeneratedFile> Generate(Compilation compilation)
    {
        Diagnostics.Clear();
        Diagnostics.AddRange(_fluent.Diagnostics);
        var symbols = DtoGenerationSymbols.Collect(compilation, _config, _fluent);
        if (symbols.AutoGenerateDto == null)
            yield break;

        string[] allNs = [];
        var types = symbols.FindTypesWithAttribute(compilation);
        var generator = new DtoCodeGenerator(_config, symbols, compilation);
        symbols.CollectViews(types);
        Diagnostics.AddRange(symbols.Diagnostics);
        (_symbols, _generator, _types) = (symbols, generator, types);

        if (_config.OneFilePerClass)
        {
            foreach (var type in types)
            {
                using var unit = symbols.Enter(symbols.DefaultUnit(type));
                yield return generator.GenerateAllForType(type, types);
            }
        }
        else
        {
            var typesByNs = types.GroupBy(t => generator.Namespace(t));
            allNs = typesByNs.OrderBy(g => g.Key).Select(t => t.Key).Distinct().ToArray();

            foreach (var group in typesByNs)
            {
                var ns = group.Key;
                var dtoTypeDict = types.ToDictionary(t => t.ToDisplayString(), t => t);
                var res = generator.GenerateNamespaceFile(ns, group, dtoTypeDict);

                yield return new GeneratedFile(
                    res.FileName,
                    res.Namespace,
                    res.Content.InsertUsings(allNs),
                    res.OutputPath ?? _config?.OutputPath);
            }
        }

        // every view in a file of its own, also with OneFilePerClass = false
        foreach (var view in symbols.Views)
        {
            using var unit = symbols.Enter(view);
            yield return generator.GenerateAllForType(view.Type, types);
        }

        if (generator.HasGuids)
        {
            yield return generator.GenerateComIdFile(types);
        }

        var mappingFiles = generator.GenerateMappingExtensions(types.ToList(), symbols.Views);
        foreach (var mappingFile in mappingFiles)
        {
            if (mappingFile != null)
            {
                yield return new GeneratedFile(
                    mappingFile.FileName,
                    mappingFile.Namespace,
                    mappingFile.Content.InsertUsings(allNs),
                    mappingFile.OutputPath ?? _config?.OutputPath);
            }
        }
    }
}
