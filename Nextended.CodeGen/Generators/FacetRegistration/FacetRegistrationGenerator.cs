using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Nextended.CodeGen.Config;
using Nextended.CodeGen.Contracts;
using Nextended.CodeGen.Fluent;

namespace Nextended.CodeGen.Generators.FacetRegistration;

/// <summary>
/// Writes the fluent <c>Facet(...)</c> rules as a module initializer that registers them with <c>Nextended.Core.Facets.FacetRegistry</c>,
/// so the facet builder (reflection at run time) sees them like <c>[ProvideFacet]</c>. Nothing without Facet(...) rules.
/// </summary>
public sealed class FacetRegistrationGenerator : ISourceSubGenerator
{
    public const string FileName = "NextendedFacetRegistrations.g.cs";

    internal static readonly DiagnosticDescriptor NotSupported = new(
        "NCG027", "Facets cannot be registered",
        "The Facet(...) rules are not registered: {0}. Register them yourself with FacetRegistry.Register, or use [ProvideFacet].",
        "Nextended.CodeGen", DiagnosticSeverity.Warning, isEnabledByDefault: true);

    public bool RequireConfig => false;

    public IEnumerable<GeneratedFile> Execute(GenerationContext context)
    {
        var compilation = context.Compilation ?? context.ExecutionContext?.Compilation;
        if (compilation == null)
            return [];
        // switched off like the DTOs' attribute: json "DtoGeneration" with the fluent defaults on top
        var generatedCode = FluentConfigReader.Read(compilation).ApplyDefaults(context.Config?.DtoGeneration ?? new DtoGenerationConfig()).GeneratedCodeAttribute;
        var file = Generate(compilation, out var diagnostic, generatedCode);
        if (diagnostic != null)
            context.ReportDiagnostic(diagnostic);
        return file == null ? [] : [file];
    }

    /// <summary>The registration file of the compilation's Facet(...) rules; null without rules (or with a diagnostic when they cannot be registered).</summary>
    public static GeneratedFile? Generate(Compilation compilation, out Diagnostic? diagnostic, bool generatedCode = true)
    {
        diagnostic = null;
        var fluent = FluentConfigReader.Read(compilation);
        if (fluent.Facets.Count == 0)
            return null;
        var location = fluent.Facets.Values.First().Location;
        if (compilation.GetTypeByMetadataName("Nextended.Core.Facets.FacetRegistry") == null)
        {
            diagnostic = Diagnostic.Create(NotSupported, location, "the referenced Nextended.Core has no FacetRegistry (update Nextended.Core)");
            return null;
        }
        if (compilation.GetTypeByMetadataName("System.Runtime.CompilerServices.ModuleInitializerAttribute") == null)
        {
            diagnostic = Diagnostic.Create(NotSupported, location, "module initializers need .NET 5 or later");
            return null;
        }

        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n");
        sb.Append("#pragma warning disable CA2255 // the registration has to run before the facet builder reads the types\n");
        sb.Append("namespace Nextended.CodeGen.Generated\n{\n");
        sb.Append("    /// <summary>The Facet(...) rules of the fluent configuration, registered when the assembly is loaded.</summary>\n");
        if (generatedCode)
            sb.Append("    [global::System.CodeDom.Compiler.GeneratedCode(\"Nextended.CodeGen\", null)]\n");
        sb.Append("    internal static class NextendedFacetRegistrations\n    {\n");
        sb.Append("        [global::System.Runtime.CompilerServices.ModuleInitializer]\n");
        sb.Append("        internal static void Register()\n        {\n");
        foreach (var facet in fluent.Facets.Values.OrderBy(f => FluentModel.Key(f.Type), StringComparer.Ordinal).ThenBy(f => f.Member, StringComparer.Ordinal))
        {
            sb.Append($"            global::Nextended.Core.Facets.FacetRegistry.Register(typeof({FluentFacet.TypeOfName(facet.Type)}), \"{facet.Member}\"");
            if (facet.Settings.Count > 0)
            {
                sb.Append(", f =>\n            {\n");
                foreach (var setting in facet.Settings)
                    sb.Append($"                f.{setting.Key} = {setting.Value.Value};\n");
                sb.Append("            }");
            }
            sb.Append(");\n");
        }
        sb.Append("        }\n    }\n}\n");
        return new GeneratedFile(FileName, "Nextended.CodeGen.Generated", sb.ToString());
    }
}
