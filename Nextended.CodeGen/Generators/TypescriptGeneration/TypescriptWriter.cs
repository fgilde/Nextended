using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace Nextended.CodeGen.Generators.TypescriptGeneration;

/// <summary>
/// Writes a TypeScript generation to disk: only changed files, '\n' line endings, files of an earlier run that are no longer generated
/// removed (they are listed in a manifest; other files in the folder are never touched). In check mode nothing is written and the
/// differences are returned.
/// </summary>
public static class TypescriptWriter
{
    public const string ManifestName = ".nextended-typescript";

    /// <summary>Writes (or, with <paramref name="check"/>, compares) and returns the relative paths that differ from the disk.</summary>
    public static List<string> Write(string root, IReadOnlyDictionary<string, string> files, bool check)
    {
        var differences = new List<string>();
        var manifestPath = Path.Combine(root, ManifestName);
        var previous = File.Exists(manifestPath)
            ? File.ReadAllLines(manifestPath).Select(l => l.Trim()).Where(l => l.Length > 0 && !l.StartsWith("#", StringComparison.Ordinal)).ToList()
            : [];

        foreach (var file in files)
        {
            var path = Full(root, file.Key);
            // a checkout with core.autocrlf turns '\n' into "\r\n": the same file, not rewritten (and not stale in check mode)
            if (File.Exists(path) && Lf(File.ReadAllText(path)) == file.Value)
                continue;
            differences.Add(file.Key);
            if (check)
                continue;
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, file.Value);
        }

        foreach (var stale in previous.Where(p => !files.ContainsKey(p) && IsInside(p)))
        {
            var path = Full(root, stale);
            if (!File.Exists(path))
                continue;
            differences.Add(stale);
            if (check)
                continue;
            File.Delete(path);
            for (var dir = Path.GetDirectoryName(path); dir != null && IsBelow(dir, root) && !Directory.EnumerateFileSystemEntries(dir).Any(); dir = Path.GetDirectoryName(dir))
                Directory.Delete(dir);
        }

        var manifest = "# Files generated by Nextended.CodeGen (TypeScript); files not listed here are never touched.\n"
                       + string.Concat(files.Keys.OrderBy(k => k, StringComparer.Ordinal).Select(k => k + "\n"));
        if (!File.Exists(manifestPath) || Lf(File.ReadAllText(manifestPath)) != manifest)
        {
            if (check)
            {
                if (files.Count > 0 && !File.Exists(manifestPath))
                    differences.Add(ManifestName);
            }
            else
            {
                Directory.CreateDirectory(root);
                File.WriteAllText(manifestPath, manifest);
            }
        }
        return differences;
    }

    private static string Lf(string text) => text.Replace("\r\n", "\n");

    private static string Full(string root, string relative) => Path.Combine(root, relative.Replace('/', Path.DirectorySeparatorChar));

    /// <summary>A manifest entry that stays inside the output folder (no rooted paths, no "..").</summary>
    private static bool IsInside(string relative)
        => !Path.IsPathRooted(relative) && !relative.Split('/', '\\').Any(s => s == "..");

    private static bool IsBelow(string dir, string root)
        => Path.GetFullPath(dir).TrimEnd(Path.DirectorySeparatorChar).Length > Path.GetFullPath(root).TrimEnd(Path.DirectorySeparatorChar).Length
           && Path.GetFullPath(dir).StartsWith(Path.GetFullPath(root), StringComparison.OrdinalIgnoreCase);
}
