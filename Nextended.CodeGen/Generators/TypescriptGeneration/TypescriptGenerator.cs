/// <summary>What one TypeScript generation produces: files by relative path ('/' separated), never written by the generator itself.</summary>
public sealed class TypescriptResult
{
    public SortedDictionary<string, string> Files { get; } = new(StringComparer.Ordinal);

    /// <summary>A source file of a generated type has syntax errors (typing in the IDE): the output may be incomplete, do not write it.</summary>
    public bool Unstable { get; set; }
}

/// <summary>
/// TypeScript declarations of compiled C# types, following the server serializer (System.Text.Json attributes, naming policy, enum
/// converters). Selection: namespaces, names, base types, [GenerateTypescript], and optionally the DTOs the DTO generator just generated.
/// </summary>
public sealed class TypescriptGenerator
{
    public const string Header = "// <auto-generated>\n//     Generated by Nextended.CodeGen from C# types. Do not edit: changes are lost on the next build.\n// </auto-generated>\n/* eslint-disable */\n";

    private static readonly string[] Scalars = ["Guid", "DateTime", "DateTimeOffset", "DateOnly", "TimeOnly", "TimeSpan"];

    private enum EnumMode { Number, String }

    private readonly Compilation _compilation;
    private readonly TypescriptGenerationConfig _config;
    private readonly FluentModel _fluent;
    private readonly EnumMode _enumMode;
    private readonly Dictionary<INamedTypeSymbol, INamedTypeSymbol> _dtoSources = new(SymbolEqualityComparer.Default);
    private readonly HashSet<INamedTypeSymbol> _dtoTypes = new(SymbolEqualityComparer.Default);
    private readonly Dictionary<INamedTypeSymbol, Decl> _decls = new(SymbolEqualityComparer.Default);
    private readonly Queue<Decl> _queue = new();
    private readonly Dictionary<string, Regex> _globs = new(StringComparer.Ordinal);
    private bool _discovering;
    private readonly Dictionary<string, string> _typeMap;
    private readonly Dictionary<string, TypescriptTypeConfig> _types;
    private readonly string _prefix;
    private List<INamedTypeSymbol>? _classes;

    private TypescriptGenerator(Compilation compilation, TypescriptGenerationConfig config, FluentModel fluent)
    {
        _compilation = compilation;
        _config = config;
        _fluent = fluent;
        // the keys as users write them (Page<T>, Page`1, global::...) in key form
        _typeMap = config.TypeMap.GroupBy(e => TypescriptNames.Normalize(e.Key)).ToDictionary(g => g.Key, g => g.Last().Value, StringComparer.Ordinal);
        _types = config.Types.GroupBy(e => TypescriptNames.Normalize(e.Key)).ToDictionary(g => g.Key, g => g.Last().Value, StringComparer.Ordinal);
        _enumMode = config.EnumValues == TypescriptEnumValues.String ? EnumMode.String : EnumMode.Number;
        // the header, then an empty line; no header: the declarations start at the top
        var header = config.Header == null ? Header : config.Header.Replace("\r\n", "\n");
        _prefix = header.Trim().Length == 0 ? "" : header.TrimEnd('\n') + "\n\n";
    }

    /// <summary>
    /// Generates the TypeScript of one generation. <paramref name="generatedFiles"/> and <paramref name="generatedDtos"/> come from the DTO
    /// generator of the same run (used with <c>FromGeneratedDtos</c>).
    /// </summary>
    public static TypescriptResult Generate(Compilation compilation, TypescriptGenerationConfig config,
        IEnumerable<GeneratedFile>? generatedFiles = null, IEnumerable<GeneratedDto>? generatedDtos = null)
    {
        var fluent = FluentConfigReader.Read(compilation);
        var original = compilation;
        if (config.FromGeneratedDtos && generatedFiles != null)
            compilation = WithGeneratedDtos(compilation, generatedFiles);
        var generator = new TypescriptGenerator(compilation, config, fluent);
        if (config.FromGeneratedDtos && generatedDtos != null)
        {
            foreach (var dto in generatedDtos)
            {
                if (compilation.GetTypeByMetadataName(dto.MetadataName) is { } type)
                {
                    generator._dtoTypes.Add(type);
                    var source = compilation.GetTypeByMetadataName(MetadataName(dto.Source.OriginalDefinition));
                    generator._dtoSources[type] = source ?? dto.Source;
                }
            }
        }
        return generator.Run(original);
    }

    private static string MetadataName(INamedTypeSymbol type)
    {
        var name = type.MetadataName;
        for (var c = type.ContainingType; c != null; c = c.ContainingType)
            name = c.MetadataName + "+" + name;
        return type.ContainingNamespace is { IsGlobalNamespace: false } ns ? ns.ToDisplayString() + "." + name : name;
    }

    /// <summary>The TypeScript generations of the fluent configuration classes of a compilation (<c>Typescript(t => ...)</c>).</summary>
    public static IReadOnlyList<TypescriptGenerationConfig> FluentGenerations(Compilation compilation)
        => FluentConfigReader.Read(compilation).TypescriptGenerations;

    /// <summary>The compilation with the generated DTO files that it does not contain yet (files on disk from an earlier build are in it).</summary>
    private static Compilation WithGeneratedDtos(Compilation compilation, IEnumerable<GeneratedFile> files)
    {
        var existing = new HashSet<string>(compilation.SyntaxTrees.Select(t => System.IO.Path.GetFileName(t.FilePath)), StringComparer.OrdinalIgnoreCase);
        var options = compilation.SyntaxTrees.FirstOrDefault()?.Options as CSharpParseOptions ?? new CSharpParseOptions(LanguageVersion.Latest);
        var trees = files.Where(f => f.FileName.EndsWith(".cs", StringComparison.OrdinalIgnoreCase) && !existing.Contains(f.FileName))
            .Select(f => CSharpSyntaxTree.ParseText(f.Content, options, "NextendedTs/" + f.FileName))
            .ToList();
        return trees.Count == 0 ? compilation : compilation.AddSyntaxTrees(trees);
    }

    // ---------------------------------------------------------------- model

    private sealed class Decl(INamedTypeSymbol type)
    {
        public INamedTypeSymbol Type { get; } = type;
        public string Name { get; set; } = "";
        public string? UnionName { get; set; }
        public string Folder { get; set; } = "";
        public string Path => (Folder.Length == 0 ? "" : Folder + "/") + (UnionName ?? Name) + ".ts";
        public List<(INamedTypeSymbol Type, object? Discriminator)> Derived { get; } = [];
        public string DiscriminatorProperty { get; set; } = "$type";
        public bool IsEnum => Type.TypeKind == TypeKind.Enum;
        public bool IsValue => IsEnum;
        public IEnumerable<string> Exports => UnionName == null ? [Name] : [Name, UnionName];
    }

    private TypescriptResult Run(Compilation original)
    {
        var result = new TypescriptResult();
        foreach (var type in Select())
            Add(type);

        // discovery: render everything once; referenced types join the set
        _discovering = true;
        while (_queue.Count > 0)
            Render(_queue.Dequeue());
        _discovering = false;

        AssignNames();
        foreach (var decl in _decls.Values.OrderBy(d => d.Path, StringComparer.Ordinal))
            result.Files[decl.Path] = Render(decl);
        if (_config.TypeAliases)
            result.Files["scalars.ts"] = _prefix + string.Concat(Scalars.Select(s => $"export type {s} = string;\n"));
        if (_config.Barrel && result.Files.Count > 0)
            result.Files["index.ts"] = Barrel();

        result.Unstable = _decls.Keys.SelectMany(t => t.DeclaringSyntaxReferences).Select(r => r.SyntaxTree).Distinct()
            .Any(tree => original.ContainsSyntaxTree(tree) && tree.GetDiagnostics().Any(d => d.Severity == DiagnosticSeverity.Error));
        return result;
    }

    private Decl Add(INamedTypeSymbol type)
    {
        type = type.OriginalDefinition;
        if (_decls.TryGetValue(type, out var decl))
            return decl;
        _decls[type] = decl = new Decl(type);
        if ((Polymorphic(type) ?? ConfiguredUnion(type)) is { } poly)
        {
            decl.DiscriminatorProperty = poly.Property;
            decl.Derived.AddRange(poly.Derived);
        }
        _queue.Enqueue(decl);
        return decl;
    }

    /// <summary>The declaration of a referenced type; during discovery it is added when it may be generated.</summary>
    private Decl? DeclOf(INamedTypeSymbol type)
    {
        var def = type.OriginalDefinition;
        if (_decls.TryGetValue(def, out var decl))
            return decl;
        if (!_discovering || !_config.IncludeReferencedTypes || !Generatable(def, explicitly: false) || IsExcluded(def) || IsMapped(def))
            return null;
        return Add(def);
    }

    // ---------------------------------------------------------------- selection

    private IEnumerable<INamedTypeSymbol> Select()
    {
        var candidates = new List<INamedTypeSymbol>();
        Collect(_compilation.Assembly.GlobalNamespace, candidates, _ => true);
        var includes = _config.IncludeNamespaces.Where(n => !string.IsNullOrWhiteSpace(n)).Select(n => n.Trim()).ToList();
        if (includes.Count > 0)
        {
            bool Relevant(string ns) => includes.Any(i => ns.Length == 0 || i == ns || i.StartsWith(ns + ".", StringComparison.Ordinal) || ns.StartsWith(i + ".", StringComparison.Ordinal));
            foreach (var assembly in _compilation.SourceModule.ReferencedAssemblySymbols)
                Collect(assembly.GlobalNamespace, candidates, Relevant);
        }
        foreach (var name in _config.IncludeTypes.Where(t => t.IndexOf('*') < 0))
            if (_compilation.GetTypeByMetadataName(TypescriptNames.Normalize(name)) is { } exact)
                candidates.Add(exact);

        return candidates.Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default)
            .Where(IsSelected)
            .OrderBy(TypescriptNames.Key, StringComparer.Ordinal)
            .ToList();
    }

    private static void Collect(INamespaceSymbol ns, List<INamedTypeSymbol> into, Func<string, bool> relevant)
    {
        foreach (var child in ns.GetNamespaceMembers())
            if (relevant(child.ToDisplayString()))
                Collect(child, into, relevant);
        if (ns.IsGlobalNamespace || relevant(ns.ToDisplayString()))
            foreach (var type in ns.GetTypeMembers())
                CollectNested(type, into);
    }

    private static void CollectNested(INamedTypeSymbol type, List<INamedTypeSymbol> into)
    {
        into.Add(type);
        foreach (var nested in type.GetTypeMembers())
            CollectNested(nested, into);
    }

    private bool IsSelected(INamedTypeSymbol type)
    {
        var byName = Matches(type, _config.IncludeTypes);
        var marked = Attr(type, "Nextended.Core.Attributes.GenerateTypescriptAttribute") != null;
        if (!Generatable(type, explicitly: byName || marked || _dtoTypes.Contains(type)))
            return false;
        if (IsExcluded(type) || IsMapped(type))
            return false;
        if (byName || marked || _dtoTypes.Contains(type))
            return true;
        if (type.TypeKind == TypeKind.Interface)
            return false;
        var ns = Namespace(type);
        return _config.IncludeNamespaces.Any(i => !string.IsNullOrWhiteSpace(i) && (ns == i.Trim() || ns.StartsWith(i.Trim() + ".", StringComparison.Ordinal)))
               || DerivesFrom(type, _config.IncludeBaseTypes);
    }

    private bool IsExcluded(INamedTypeSymbol type)
    {
        var ns = Namespace(type);
        if (_config.ExcludeNamespaces.Any(e => !string.IsNullOrWhiteSpace(e) && (ns == e.Trim() || ns.StartsWith(e.Trim() + ".", StringComparison.Ordinal))))
            return true;
        if (Matches(type, _config.ExcludeTypes) || DerivesFrom(type, _config.ExcludeBaseTypes))
            return true;
        var json = JsonLayer(type);
        var ignored = json?.Ignore ?? false;
        if (Attr(type, "Nextended.Core.Attributes.TypescriptIgnoreAttribute") != null)
            ignored = true;
        foreach (var layer in TypeLayers(type).Where(l => !ReferenceEquals(l, json)))
            if (layer.Ignore is { } ignore)
                ignored = ignore;
        return ignored;
    }

    /// <summary>A type the generator can write: a class, struct, record, enum (interfaces only when chosen explicitly), not static, accessible.</summary>
    private bool Generatable(INamedTypeSymbol type, bool explicitly)
    {
        if (type.IsStatic || type.IsImplicitlyDeclared || type.Name.IndexOf('<') >= 0 || type.Name.Length == 0)
            return false;
        if (type.TypeKind is not (TypeKind.Class or TypeKind.Struct or TypeKind.Enum or TypeKind.Interface))
            return false;
        if (type.TypeKind == TypeKind.Interface && !explicitly)
            return false;
        if (type.SpecialType != SpecialType.None)
            return false;
        for (var b = type.BaseType; b != null; b = b.BaseType)
            if (b.ToDisplayString() is "System.Attribute" or "System.Exception" or "System.Delegate")
                return false;
        var source = SymbolEqualityComparer.Default.Equals(type.ContainingAssembly, _compilation.Assembly);
        for (var t = type; t != null; t = t.ContainingType)
            if (!(t.DeclaredAccessibility == Accessibility.Public || source && t.DeclaredAccessibility == Accessibility.Internal))
                return false;
        if (!explicitly && IsFramework(type))
            return false;
        return true;
    }

    private static bool IsFramework(INamedTypeSymbol type)
    {
        var ns = Namespace(type);
        return ns == "System" || ns.StartsWith("System.", StringComparison.Ordinal) || ns == "Microsoft" || ns.StartsWith("Microsoft.", StringComparison.Ordinal)
               || ns.StartsWith("Newtonsoft.", StringComparison.Ordinal);
    }

    private bool Matches(INamedTypeSymbol type, List<string> patterns)
    {
        if (patterns.Count == 0)
            return false;
        var key = TypescriptNames.Key(type);
        var plain = TypescriptNames.WithoutArity(key);
        foreach (var raw in patterns)
        {
            if (string.IsNullOrWhiteSpace(raw))
                continue;
            var pattern = TypescriptNames.Normalize(raw);
            if (pattern.IndexOf('*') < 0)
            {
                if (pattern == key || pattern == plain || pattern == type.Name || pattern == key.Substring(key.LastIndexOf('.') + 1))
                    return true;
                continue;
            }
            if (!_globs.TryGetValue(pattern, out var regex))
                _globs[pattern] = regex = new Regex("^" + Regex.Escape(pattern).Replace("\\*", ".*") + "$", RegexOptions.CultureInvariant);
            if (regex.IsMatch(key) || regex.IsMatch(plain) || regex.IsMatch(type.Name))
                return true;
        }
        return false;
    }

    private static bool DerivesFrom(INamedTypeSymbol type, List<string> bases)
    {
        if (bases.Count == 0)
            return false;
        var keys = new HashSet<string>(bases.Where(b => !string.IsNullOrWhiteSpace(b)).Select(TypescriptNames.Normalize), StringComparer.Ordinal);
        IEnumerable<INamedTypeSymbol> Ancestors()
        {
            for (var b = type.BaseType; b != null; b = b.BaseType)
                yield return b;
            foreach (var i in type.AllInterfaces)
                yield return i;
        }
        return Ancestors().Any(a => keys.Contains(TypescriptNames.Key(a)) || keys.Contains(TypescriptNames.WithoutArity(TypescriptNames.Key(a))));
    }

    // ---------------------------------------------------------------- per-type and per-member settings

    /// <summary>The configured rules of a type, lowest precedence first: json "Types", fluent DtoConfig&lt;T&gt;.Typescript (source, type), fluent "Types".</summary>
    private IEnumerable<TypescriptTypeConfig> TypeLayers(INamedTypeSymbol type)
    {
        if (!_config.IsFluent && Lookup(_types, type) is { } json)
            yield return json;
        if (_dtoSources.TryGetValue(type.OriginalDefinition, out var source) && Lookup(_fluent.TypescriptTypes, source) is { } fromSource)
            yield return fromSource;
        if (Lookup(_fluent.TypescriptTypes, type) is { } global)
            yield return global;
        if (_config.IsFluent && Lookup(_types, type) is { } own)
            yield return own;
    }

    private static TypescriptTypeConfig? Lookup(Dictionary<string, TypescriptTypeConfig> types, INamedTypeSymbol type)
    {
        if (types.Count == 0)
            return null;
        var key = TypescriptNames.Key(type);
        return types.TryGetValue(key, out var rules) || types.TryGetValue(TypescriptNames.WithoutArity(key), out rules) ? rules : null;
    }

    /// <summary>The json "Types" entry of a type (a json generation only): it loses to the attributes.</summary>
    private TypescriptTypeConfig? JsonLayer(INamedTypeSymbol type) => _config.IsFluent ? null : Lookup(_types, type);

    /// <summary>json "Types" → [GenerateTypescript(Name)] → fluent.</summary>
    private string TypeName(INamedTypeSymbol type)
    {
        var name = string.Concat(Containing(type).Select(t => t.Name));
        var json = JsonLayer(type);
        if (json?.Name is { Length: > 0 } jsonName)
            name = jsonName;
        if (Named(Attr(type, "Nextended.Core.Attributes.GenerateTypescriptAttribute"), "Name") is string { Length: > 0 } attrName)
            name = attrName;
        foreach (var layer in TypeLayers(type).Where(l => !ReferenceEquals(l, json)))
            if (layer.Name is { Length: > 0 } n)
                name = n;
        return name;
    }

    private static IEnumerable<INamedTypeSymbol> Containing(INamedTypeSymbol type)
    {
        var chain = new List<INamedTypeSymbol>();
        for (var t = type; t != null; t = t.ContainingType)
            chain.Insert(0, t);
        return chain;
    }

    private sealed class Member(ISymbol symbol, ITypeSymbol type, string name, bool optional, string? typeOverride, EnumMode? enumMode)
    {
        public ISymbol Symbol { get; } = symbol;
        public ITypeSymbol Type { get; } = type;
        public string Name { get; } = name;
        public bool Optional { get; } = optional;
        public string? TypeOverride { get; } = typeOverride;
        public EnumMode? EnumMode { get; } = enumMode;
    }

    /// <summary>The serialized members a type declares itself (public instance properties with a public getter, [JsonInclude] members).</summary>
    private List<(ISymbol Symbol, ITypeSymbol Type, int Order)> DeclaredMembers(INamedTypeSymbol type)
    {
        var result = new List<(ISymbol, ITypeSymbol, int)>();
        foreach (var symbol in type.MembersInSourceOrder())
        {
            if (symbol.IsStatic || symbol.IsImplicitlyDeclared)
                continue;
            var include = Attr(symbol, "System.Text.Json.Serialization.JsonIncludeAttribute") != null;
            ITypeSymbol? memberType = symbol switch
            {
                IPropertySymbol { IsIndexer: false, ExplicitInterfaceImplementations.Length: 0 } p
                    when p.GetMethod != null && (include || type.TypeKind == TypeKind.Interface || p.DeclaredAccessibility == Accessibility.Public && p.GetMethod.DeclaredAccessibility == Accessibility.Public) => p.Type,
                IFieldSymbol { IsConst: false } f when include => f.Type,
                _ => null
            };
            if (memberType == null)
                continue;
            var order = Attr(symbol, "System.Text.Json.Serialization.JsonPropertyOrderAttribute") is { ConstructorArguments.Length: 1 } o && o.ConstructorArguments[0].Value is int i ? i : 0;
            result.Add((symbol, memberType, order));
        }
        return result;
    }

    private Member? Resolve(INamedTypeSymbol owner, ISymbol symbol, ITypeSymbol type)
    {
        var name = symbol.Name;
        string? jsonName = null;
        var ignore = false;
        var optional = false;
        string? typeOverride = null;

        var sources = new List<ISymbol> { symbol };
        if (_dtoSources.TryGetValue(owner.OriginalDefinition, out var source))
            sources.AddRange(AllMembers(source).Where(m => m.Name == name));

        if (Attr(symbol, "System.Text.Json.Serialization.JsonPropertyNameAttribute") is { ConstructorArguments.Length: 1 } jp)
            jsonName = jp.ConstructorArguments[0].Value as string;
        else if (Attr(symbol, "Newtonsoft.Json.JsonPropertyAttribute") is { } np)
            jsonName = (np.ConstructorArguments.Length == 1 ? np.ConstructorArguments[0].Value as string : null) ?? Named(np, "PropertyName") as string;
        if (Attr(symbol, "System.Text.Json.Serialization.JsonIgnoreAttribute") is { } ji)
        {
            var condition = Named(ji, "Condition") is int c ? c : 1;
            ignore = condition == 1;
            optional = condition is 2 or 3;
        }
        if (Attr(symbol, "Newtonsoft.Json.JsonIgnoreAttribute") != null)
            ignore = true;
        if (_config.OptionalNullable && IsNullable(type))
            optional = true;

        // json "Types" → attributes → fluent
        var layers = TypeLayers(owner).ToList();
        if ((layers.LastOrDefault(l => l.OptionalDefaultValues != null)?.OptionalDefaultValues ?? _config.OptionalDefaultValues) && HasDefaultValue(symbol))
            optional = true;
        var only = layers.LastOrDefault(l => l.IncludeMembersWithAttributes != null)?.IncludeMembersWithAttributes ?? _config.IncludeMembersWithAttributes;
        if (only.Count > 0 && !sources.Any(s => s.GetAttributes().Any(a => a.AttributeClass is { } c && IsAttribute(c, only))))
            ignore = true;
        var jsonLayer = JsonLayer(owner);
        void Apply(TypescriptMemberConfig? m)
        {
            if (m == null)
                return;
            ignore = m.Ignore ?? ignore;
            optional = m.Optional ?? optional;
            jsonName = m.Name ?? jsonName;
            typeOverride = m.Type ?? typeOverride;
        }
        if (jsonLayer != null && jsonLayer.Members.TryGetValue(name, out var jsonMember))
            Apply(jsonMember);
        foreach (var s in sources)
        {
            if (Attr(s, "Nextended.Core.Attributes.TypescriptIgnoreAttribute") != null)
                ignore = true;
            if (Attr(s, "Nextended.Core.Attributes.TypescriptPropertyAttribute") is { } tp)
            {
                jsonName = Named(tp, "Name") as string ?? jsonName;
                typeOverride = Named(tp, "Type") as string ?? typeOverride;
                if (Named(tp, "Optional") is true)
                    optional = true;
            }
        }
        foreach (var layer in layers.Where(l => !ReferenceEquals(l, jsonLayer)))
            if (layer.Members.TryGetValue(name, out var member))
                Apply(member);

        if (ignore)
            return null;
        var tsName = jsonName ?? (_config.PropertyNaming == TypescriptNaming.CamelCase ? TypescriptNames.CamelCase(name) : name);
        return new Member(symbol, type, tsName, optional, typeOverride, ConverterMode(symbol));
    }

    /// <summary>An attribute class named in the list: full or simple name, with or without "Attribute".</summary>
    private static bool IsAttribute(INamedTypeSymbol attribute, List<string> names)
    {
        var key = TypescriptNames.Key(attribute);
        foreach (var raw in names.Where(n => !string.IsNullOrWhiteSpace(n)))
        {
            var name = TypescriptNames.Normalize(raw);
            var full = name.EndsWith("Attribute", StringComparison.Ordinal) ? name : name + "Attribute";
            if (key == name || key == full || attribute.Name == name || attribute.Name == full)
                return true;
        }
        return false;
    }

    /// <summary>
    /// [DefaultValue], or an initializer (property, field, record parameter) that is not <c>null</c>/<c>default</c> (also with <c>!</c>);
    /// never for a member the client must send (<c>required</c>, [Required], [JsonRequired]).
    /// </summary>
    private static bool HasDefaultValue(ISymbol symbol)
    {
        if (symbol is IPropertySymbol { IsRequired: true } or IFieldSymbol { IsRequired: true }
            || Attr(symbol, "System.ComponentModel.DataAnnotations.RequiredAttribute") != null || Attr(symbol, "System.Text.Json.Serialization.JsonRequiredAttribute") != null)
            return false;
        if (Attr(symbol, "System.ComponentModel.DefaultValueAttribute") != null)
            return true;
        foreach (var reference in symbol.DeclaringSyntaxReferences)
        {
            var value = reference.GetSyntax() switch
            {
                PropertyDeclarationSyntax p => p.Initializer?.Value,
                VariableDeclaratorSyntax v => v.Initializer?.Value,
                ParameterSyntax p => p.Default?.Value,
                _ => null
            };
            while (true)
            {
                if (value is PostfixUnaryExpressionSyntax bang && bang.IsKind(SyntaxKind.SuppressNullableWarningExpression))
                    value = bang.Operand;
                else if (value is ParenthesizedExpressionSyntax parenthesized)
                    value = parenthesized.Expression;
                else
                    break;
            }
            if (value != null && !value.IsKind(SyntaxKind.NullLiteralExpression) && !value.IsKind(SyntaxKind.DefaultLiteralExpression) && value is not DefaultExpressionSyntax)
                return true;
        }
        return false;
    }

    private static IEnumerable<ISymbol> AllMembers(INamedTypeSymbol type)
    {
        for (var t = type; t != null; t = t.BaseType)
            foreach (var m in t.GetMembers())
                yield return m;
    }

    private static bool IsNullable(ITypeSymbol type)
        => type.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T || type.NullableAnnotation == NullableAnnotation.Annotated && (type.IsReferenceType || type is ITypeParameterSymbol);

    // ---------------------------------------------------------------- polymorphism

    private sealed class PolymorphicInfo(string property, List<(INamedTypeSymbol, object?)> derived)
    {
        public string Property { get; } = property;
        public List<(INamedTypeSymbol Type, object? Discriminator)> Derived { get; } = derived;
    }

    private static PolymorphicInfo? Polymorphic(INamedTypeSymbol type)
    {
        if (type.Arity > 0)
            return null;
        var derived = new List<(INamedTypeSymbol, object?)>();
        foreach (var attr in type.GetAttributes().Where(a => a.AttributeClass?.ToDisplayString() == "System.Text.Json.Serialization.JsonDerivedTypeAttribute"))
            if (attr.ConstructorArguments.Length >= 1 && attr.ConstructorArguments[0].Value is INamedTypeSymbol d)
                derived.Add(((INamedTypeSymbol)d.OriginalDefinition, attr.ConstructorArguments.Length > 1 ? attr.ConstructorArguments[1].Value : null));
        if (derived.Count == 0)
            return null;
        var poly = Attr(type, "System.Text.Json.Serialization.JsonPolymorphicAttribute");
        return new PolymorphicInfo(Named(poly, "TypeDiscriminatorPropertyName") as string ?? "$type", derived);
    }

    /// <summary>
    /// "DerivedTypes" of a base type without [JsonDerivedType]: the derived classes of the compilation (and of the base's assembly) whose
    /// name, or the name of the entity a generated DTO comes from, matches an entry; "Name=value" gives the discriminator value.
    /// </summary>
    private PolymorphicInfo? ConfiguredUnion(INamedTypeSymbol type)
    {
        var layers = TypeLayers(type).ToList();
        var entries = layers.LastOrDefault(l => l.DerivedTypes.Count > 0)?.DerivedTypes;
        if (entries == null || type.Arity > 0)
            return null;
        _classes ??= Classes(_compilation.Assembly);
        var candidates = SymbolEqualityComparer.Default.Equals(type.ContainingAssembly, _compilation.Assembly)
            ? _classes
            : _classes.Concat(Classes(type.ContainingAssembly));
        var derivedClasses = candidates.Where(c => Inherits(c, type)).ToList();

        var derived = new List<(INamedTypeSymbol, object?)>();
        if (!type.IsAbstract && type.TypeKind == TypeKind.Class)
            derived.Add((type, null)); // a base that can be instantiated is sent as itself too
        foreach (var entry in entries.Where(e => !string.IsNullOrWhiteSpace(e)))
        {
            var split = entry.IndexOf('=');
            var pattern = new List<string> { split < 0 ? entry : entry.Substring(0, split) };
            object? value = split < 0 ? null : entry.Substring(split + 1).Trim();
            foreach (var candidate in derivedClasses)
                if (derived.All(d => !SymbolEqualityComparer.Default.Equals(d.Item1, candidate))
                    && (Matches(candidate, pattern) || _dtoSources.TryGetValue(candidate, out var source) && Matches(source, pattern)))
                    derived.Add((candidate, value));
        }
        if (derived.All(d => SymbolEqualityComparer.Default.Equals(d.Item1, type)))
            return null;
        return new PolymorphicInfo(layers.LastOrDefault(l => l.Discriminator is { Length: > 0 })?.Discriminator ?? "$type", derived);
    }

    /// <summary>The non-generic, non-abstract classes of an assembly, in key order.</summary>
    private static List<INamedTypeSymbol> Classes(IAssemblySymbol assembly)
    {
        var all = new List<INamedTypeSymbol>();
        Collect(assembly.GlobalNamespace, all, _ => true);
        return all.Where(t => t is { TypeKind: TypeKind.Class, IsAbstract: false, Arity: 0 }).OrderBy(TypescriptNames.Key, StringComparer.Ordinal).ToList();
    }

    private static bool Inherits(INamedTypeSymbol type, INamedTypeSymbol baseType)
    {
        for (var b = type.BaseType; b != null; b = b.BaseType)
            if (SymbolEqualityComparer.Default.Equals(b.OriginalDefinition, baseType))
                return true;
        return false;
    }

    /// <summary>The discriminator a derived type carries: from the nearest polymorphic base that lists it.</summary>
    private (string Property, object Value)? DiscriminatorOf(INamedTypeSymbol type)
    {
        for (var b = type.BaseType; b != null; b = b.BaseType)
        {
            if (_decls.TryGetValue(b.OriginalDefinition, out var decl) && decl.Derived.Count > 0)
            {
                foreach (var (d, value) in decl.Derived)
                    if (value != null && SymbolEqualityComparer.Default.Equals(d, type.OriginalDefinition))
                        return (decl.DiscriminatorProperty, value);
                return null;
            }
        }
        return null;
    }

    // ---------------------------------------------------------------- names and files

    private void AssignNames()
    {
        foreach (var decl in _decls.Values)
        {
            var name = TypeName(decl.Type);
            if (decl.Derived.Count > 0)
            {
                decl.UnionName = name;
                decl.Name = name + "Base";
            }
            else
                decl.Name = name;
            decl.Folder = _config.Layout == TypescriptLayout.Flat ? "" : Folder(Namespace(decl.Type));
        }

        // the same file twice: types of the same name in different namespaces (flat), or of different arity
        foreach (var group in _decls.Values.GroupBy(d => d.Path, StringComparer.OrdinalIgnoreCase).Where(g => g.Count() > 1).ToList())
        {
            var members = group.OrderBy(d => TypescriptNames.Key(d.Type), StringComparer.Ordinal).ToList();
            var byNamespace = members.Select(d => Namespace(d.Type)).Distinct().Count() > 1;
            var taken = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            for (var i = 0; i < members.Count; i++)
            {
                var decl = members[i];
                string Rename(string n)
                {
                    // types of different namespaces all get their namespace; of different arity the first keeps the name
                    var candidate = byNamespace ? Pascal(StripRoot(Namespace(decl.Type))) + n : i == 0 ? n : n + decl.Type.Arity;
                    for (var k = 2; !taken.Add(candidate); k++)
                        candidate = (byNamespace ? Pascal(StripRoot(Namespace(decl.Type))) + n : n) + k;
                    return candidate;
                }
                if (decl.UnionName != null)
                {
                    decl.UnionName = Rename(decl.UnionName);
                    decl.Name = decl.UnionName + "Base";
                }
                else
                    decl.Name = Rename(decl.Name);
            }
        }
    }

    private string StripRoot(string ns)
    {
        var root = _config.RootNamespace?.Trim();
        if (string.IsNullOrEmpty(root))
            return ns;
        if (ns == root)
            return "";
        return ns.StartsWith(root + ".", StringComparison.Ordinal) ? ns.Substring(root!.Length + 1) : ns;
    }

    private string Folder(string ns) => StripRoot(ns).Replace('.', '/');

    private static string Pascal(string ns) => string.Concat(ns.Split(['.'], StringSplitOptions.RemoveEmptyEntries).Select(s => char.ToUpperInvariant(s[0]) + s.Substring(1)));

    private static string Namespace(INamedTypeSymbol type) => type.ContainingNamespace is { IsGlobalNamespace: false } ns ? ns.ToDisplayString() : "";

    private static string Relative(string fromFolder, string toPath)
    {
        var from = fromFolder.Length == 0 ? [] : fromFolder.Split('/');
        var to = toPath.Split('/');
        var common = 0;
        while (common < from.Length && common < to.Length - 1 && from[common] == to[common])
            common++;
        var up = from.Length - common;
        var rest = string.Join("/", to.Skip(common));
        if (rest.EndsWith(".ts", StringComparison.Ordinal))
            rest = rest.Substring(0, rest.Length - 3);
        return (up == 0 ? "./" : string.Concat(Enumerable.Repeat("../", up))) + rest;
    }

    private string Barrel()
    {
        var counts = _decls.Values.SelectMany(d => d.Exports).GroupBy(n => n, StringComparer.Ordinal).ToDictionary(g => g.Key, g => g.Count(), StringComparer.Ordinal);
        var sb = new StringBuilder(_prefix);
        if (_config.TypeAliases)
            sb.Append("export * from './scalars';\n");
        foreach (var decl in _decls.Values.OrderBy(d => d.Path, StringComparer.Ordinal))
        {
            var path = Relative("", decl.Path);
            if (decl.Exports.All(e => counts[e] == 1))
            {
                sb.Append($"export * from '{path}';\n");
                continue;
            }
            // a name exported by two files: both get a qualified alias
            var names = decl.Exports.Select(e => counts[e] == 1 ? e : $"{e} as {Pascal(StripRoot(Namespace(decl.Type)))}{e}");
            sb.Append(decl.IsValue ? $"export {{ {string.Join(", ", names)} }} from '{path}';\n" : $"export type {{ {string.Join(", ", names)} }} from '{path}';\n");
        }
        return sb.ToString();
    }

    // ---------------------------------------------------------------- rendering

    private sealed class FileContext(Decl owner, IEnumerable<string> reserved)
    {
        public Decl Owner { get; } = owner;
        public HashSet<string> Names { get; } = new(reserved, StringComparer.Ordinal);
        public Dictionary<(string Module, string Export), string> Imports { get; } = new();

        public string Import(string module, string export, string alias)
        {
            if (Imports.TryGetValue((module, export), out var local))
                return local;
            local = export;
            if (!Names.Add(local))
            {
                local = alias;
                for (var i = 2; !Names.Add(local); i++)
                    local = alias + i;
            }
            Imports[(module, export)] = local;
            return local;
        }
    }

    private string Use(FileContext file, Decl decl, bool union)
    {
        var export = union ? decl.UnionName ?? decl.Name : decl.Name;
        if (_discovering || decl.Path == file.Owner.Path)
            return export;
        return file.Import(Relative(file.Owner.Folder, decl.Path), export, Pascal(StripRoot(Namespace(decl.Type))) + export);
    }

    private string Scalar(FileContext file, string name)
        => _config.TypeAliases && !_discovering ? file.Import(Relative(file.Owner.Folder, "scalars.ts"), name, "Scalar" + name) : _config.TypeAliases ? name : "string";

    private string Render(Decl decl)
    {
        var reserved = decl.Exports.Concat(decl.Type.TypeParameters.Select(p => p.Name));
        var file = new FileContext(decl, reserved);
        var body = decl.IsEnum ? RenderEnum(decl) : RenderInterface(decl, file);
        if (_discovering)
            return "";
        var sb = new StringBuilder(_prefix);
        foreach (var module in file.Imports.GroupBy(i => i.Key.Module).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            var names = module.OrderBy(i => i.Key.Export, StringComparer.Ordinal).Select(i => i.Value == i.Key.Export ? i.Key.Export : $"{i.Key.Export} as {i.Value}");
            sb.Append($"import type {{ {string.Join(", ", names)} }} from '{module.Key}';\n");
        }
        if (file.Imports.Count > 0)
            sb.Append('\n');
        return sb.Append(body).ToString();
    }

    private string RenderEnum(Decl decl)
    {
        var type = decl.Type;
        var mode = DeclaredMode(type);
        var fields = type.GetMembers().OfType<IFieldSymbol>().Where(f => f.HasConstantValue && !f.IsImplicitlyDeclared).ToList();
        string Value(IFieldSymbol f) => mode == EnumMode.String
            ? TypescriptNames.Literal(EnumName(f))
            : Convert.ToString(f.ConstantValue, CultureInfo.InvariantCulture)!;
        var sb = new StringBuilder();
        if (_config.EnumStyle == TypescriptEnumStyle.Const)
        {
            sb.Append($"export const {decl.Name} = {{\n");
            foreach (var f in fields)
                sb.Append($"    {TypescriptNames.PropertyName(f.Name)}: {Value(f)},\n");
            sb.Append("} as const;\n");
            sb.Append($"export type {decl.Name} = (typeof {decl.Name})[keyof typeof {decl.Name}];\n");
        }
        else
        {
            sb.Append($"export enum {decl.Name} {{\n");
            foreach (var f in fields)
                sb.Append($"    {TypescriptNames.PropertyName(f.Name)} = {Value(f)},\n");
            sb.Append("}\n");
        }
        return sb.ToString();
    }

    private static string EnumName(IFieldSymbol field)
        => (Attr(field, "System.Text.Json.Serialization.JsonStringEnumMemberNameAttribute") is { ConstructorArguments.Length: 1 } a ? a.ConstructorArguments[0].Value as string : null)
           ?? Named(Attr(field, "System.Runtime.Serialization.EnumMemberAttribute"), "Value") as string
           ?? field.Name;

    private static bool IsFlags(INamedTypeSymbol type) => Attr(type, "System.FlagsAttribute") != null;

    /// <summary>How an enum type's values are written: numbers for [Flags], strings with a string converter on the type or by setting.</summary>
    private EnumMode DeclaredMode(INamedTypeSymbol type)
        => IsFlags(type) ? EnumMode.Number : ConverterMode(type) ?? _enumMode;

    private static EnumMode? ConverterMode(ISymbol symbol)
    {
        foreach (var attr in symbol.GetAttributes().Where(a => a.AttributeClass?.Name == "JsonConverterAttribute"))
        {
            if (attr.ConstructorArguments.Length != 1 || attr.ConstructorArguments[0].Value is not INamedTypeSymbol converter)
                continue;
            switch (converter.Name)
            {
                case "JsonStringEnumConverter":
                case "StringEnumConverter":
                    return EnumMode.String;
                case "JsonNumberEnumConverter":
                    return EnumMode.Number;
            }
        }
        return null;
    }

    private string RenderInterface(Decl decl, FileContext file)
    {
        var type = decl.Type;
        var sb = new StringBuilder();
        var heritage = new List<string>();
        var members = new List<(ISymbol Symbol, ITypeSymbol Type, int Order)>();
        var hidden = new List<string>();

        if (type.TypeKind == TypeKind.Interface)
        {
            foreach (var i in type.Interfaces)
                if (Reference(i, file, extends: true) is { } r)
                    heritage.Add(r);
            members.AddRange(DeclaredMembers(type));
        }
        else
        {
            var flattened = new List<INamedTypeSymbol>();
            INamedTypeSymbol? extended = null;
            for (var b = type.BaseType; b != null && b.SpecialType is not (SpecialType.System_Object or SpecialType.System_ValueType); b = b.BaseType)
            {
                if (Reference(b, file, extends: true) is { } r)
                {
                    heritage.Add(r);
                    extended = b;
                    break;
                }
                if (IsFramework(b))
                    break;
                flattened.Insert(0, b);
            }
            foreach (var b in flattened)
                members.AddRange(DeclaredMembers(b));
            members.AddRange(DeclaredMembers(type));

            // a member a derived type declares again: overrides stay with the base, `new` members replace it (Omit)
            var baseNames = extended == null ? new HashSet<string>() : new HashSet<string>(AllMembers(extended).OfType<IPropertySymbol>().Select(p => p.Name));
            members = members.GroupBy(m => m.Symbol.Name).Select(g => g.Last()).ToList();
            members.RemoveAll(m => m.Symbol is IPropertySymbol { IsOverride: true } && baseNames.Contains(m.Symbol.Name));
            hidden.AddRange(members.Where(m => baseNames.Contains(m.Symbol.Name)).Select(m => m.Symbol.Name));
        }

        var resolved = members.Select((m, i) => (Member: Resolve(type, m.Symbol, m.Type), m.Order, Index: i))
            .Where(m => m.Member != null)
            .OrderBy(m => m.Order).ThenBy(m => m.Index)
            .Select(m => m.Member!)
            .ToList();
        if (hidden.Count > 0 && heritage.Count == 1)
        {
            var names = resolved.Where(m => hidden.Contains(m.Symbol.Name)).Select(m => TypescriptNames.Literal(m.Name)).Distinct().ToList();
            if (names.Count > 0)
                heritage[0] = $"Omit<{heritage[0]}, {string.Join(" | ", names)}>";
        }

        sb.Append($"export interface {decl.Name}{TypeParameters(type, file)}");
        if (heritage.Count > 0)
            sb.Append(" extends ").Append(string.Join(", ", heritage));
        sb.Append(" {\n");
        if (DiscriminatorOf(type) is { } discriminator && resolved.All(m => m.Name != discriminator.Property))
            sb.Append($"    {TypescriptNames.PropertyName(discriminator.Property)}: {DiscriminatorLiteral(discriminator.Value)};\n");
        foreach (var member in resolved)
        {
            if (Attr(member.Symbol, "System.Text.Json.Serialization.JsonExtensionDataAttribute") != null || Attr(member.Symbol, "Newtonsoft.Json.JsonExtensionDataAttribute") != null)
            {
                sb.Append("    [key: string]: unknown;\n");
                continue;
            }
            var ts = member.TypeOverride ?? Ts(member.Type, file, member.EnumMode);
            sb.Append($"    {TypescriptNames.PropertyName(member.Name)}{(member.Optional ? "?" : "")}: {ts};\n");
        }
        sb.Append("}\n");

        if (decl.Derived.Count > 0)
        {
            var parts = new List<string>();
            foreach (var (derived, value) in decl.Derived)
            {
                if (SymbolEqualityComparer.Default.Equals(derived, type))
                {
                    parts.Add(value == null ? decl.Name : $"({decl.Name} & {{ {TypescriptNames.PropertyName(decl.DiscriminatorProperty)}: {DiscriminatorLiteral(value)} }})");
                    continue;
                }
                if (DeclOf(derived) is { } d)
                    parts.Add(Use(file, d, union: false));
            }
            sb.Append($"export type {decl.UnionName} = {(parts.Count == 0 ? decl.Name : string.Join(" | ", parts.Distinct()))};\n");
        }
        return sb.ToString();
    }

    private static string DiscriminatorLiteral(object value)
        => value is string s ? TypescriptNames.Literal(s) : Convert.ToString(value, CultureInfo.InvariantCulture)!;

    private string TypeParameters(INamedTypeSymbol type, FileContext file)
    {
        if (type.TypeParameters.Length == 0)
            return "";
        var parts = type.TypeParameters.Select(p =>
        {
            var constraints = p.ConstraintTypes.Select(c => Ts(c, file, null)).Where(c => c != "unknown").ToList();
            return constraints.Count == 0 ? p.Name : $"{p.Name} extends {string.Join(" & ", constraints)}";
        });
        return "<" + string.Join(", ", parts) + ">";
    }

    /// <summary>A generated (or mapped) type as a reference, with its type arguments; null when it is neither.</summary>
    private string? Reference(INamedTypeSymbol type, FileContext file, bool extends)
    {
        if (MapType(type, file) is { } mapped)
            return mapped;
        if (DeclOf(type) is not { } decl || decl.IsEnum)
            return null;
        var name = Use(file, decl, union: !extends);
        return name + Arguments(type, file);
    }

    private string Arguments(INamedTypeSymbol type, FileContext file)
    {
        var args = new List<ITypeSymbol>();
        foreach (var t in Containing(type))
            args.AddRange(t.TypeArguments);
        return args.Count == 0 ? "" : "<" + string.Join(", ", args.Select(a => Ts(a, file, null))) + ">";
    }

    private bool IsMapped(INamedTypeSymbol type)
        => _typeMap.Count > 0 && (_typeMap.ContainsKey(TypescriptNames.Key(type)) || _typeMap.ContainsKey(TypescriptNames.WithoutArity(TypescriptNames.Key(type))));

    /// <summary>"TypeMap": the TypeScript of a mapped type, with its import; type arguments appended unless the mapping has its own.</summary>
    private string? MapType(INamedTypeSymbol type, FileContext file)
    {
        if (_typeMap.Count == 0)
            return null;
        var key = TypescriptNames.Key(type);
        if (!_typeMap.TryGetValue(key, out var ts) && !_typeMap.TryGetValue(TypescriptNames.WithoutArity(key), out ts))
            return null;
        var from = ts.IndexOf(" from ", StringComparison.Ordinal);
        if (from > 0)
        {
            var name = ts.Substring(0, from).Trim();
            var module = ts.Substring(from + 6).Trim().Trim('\'', '"');
            if (module.StartsWith(".", StringComparison.Ordinal) && file.Owner.Folder.Length > 0)
                module = string.Concat(Enumerable.Repeat("../", file.Owner.Folder.Split('/').Length)) + (module.StartsWith("./", StringComparison.Ordinal) ? module.Substring(2) : module);
            ts = _discovering ? name : file.Import(module, name, "Mapped" + name);
        }
        return ts.IndexOf('<') >= 0 ? ts : ts + Arguments(type, file);
    }

    private string Ts(ITypeSymbol type, FileContext file, EnumMode? mode)
    {
        if (type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable)
            return OrNull(TsCore(nullable.TypeArguments[0], file, mode));
        var core = TsCore(type, file, mode);
        return type.NullableAnnotation == NullableAnnotation.Annotated && (type.IsReferenceType || type is ITypeParameterSymbol) ? OrNull(core) : core;
    }

    private static string OrNull(string ts) => ts.EndsWith(" | null", StringComparison.Ordinal) || ts == "unknown" ? ts : ts + " | null";

    private static string ArrayOf(string element)
        => (element.IndexOf(" | ", StringComparison.Ordinal) >= 0 || element.IndexOf(" & ", StringComparison.Ordinal) >= 0 || element.StartsWith("keyof", StringComparison.Ordinal) ? $"({element})" : element) + "[]";

    private string TsCore(ITypeSymbol type, FileContext file, EnumMode? mode)
    {
        switch (type)
        {
            case ITypeParameterSymbol parameter:
                return parameter.Name;
            case IArrayTypeSymbol array:
                return array.ElementType.SpecialType == SpecialType.System_Byte ? "string" : ArrayOf(Ts(array.ElementType, file, null));
            case IDynamicTypeSymbol:
                return "unknown";
            case not INamedTypeSymbol:
                return "unknown";
        }
        var named = (INamedTypeSymbol)type;

        switch (named.SpecialType)
        {
            case SpecialType.System_Boolean:
                return "boolean";
            case SpecialType.System_String:
            case SpecialType.System_Char:
                return "string";
            case SpecialType.System_Object:
                return "unknown";
            case SpecialType.System_Int64:
            case SpecialType.System_UInt64:
                return _config.LongAsString ? "string" : "number";
            case SpecialType.System_Decimal:
                return _config.DecimalAsString ? "string" : "number";
            case SpecialType.System_SByte:
            case SpecialType.System_Byte:
            case SpecialType.System_Int16:
            case SpecialType.System_UInt16:
            case SpecialType.System_Int32:
            case SpecialType.System_UInt32:
            case SpecialType.System_Single:
            case SpecialType.System_Double:
            case SpecialType.System_IntPtr:
            case SpecialType.System_UIntPtr:
                return "number";
            case SpecialType.System_DateTime:
                return Scalar(file, "DateTime");
        }

        if (MapType(named, file) is { } mapped)
            return mapped;

        switch (named.OriginalDefinition.ToDisplayString())
        {
            case "System.Guid": return Scalar(file, "Guid");
            case "System.DateTimeOffset": return Scalar(file, "DateTimeOffset");
            case "System.DateOnly": return Scalar(file, "DateOnly");
            case "System.TimeOnly": return Scalar(file, "TimeOnly");
            case "System.TimeSpan": return Scalar(file, "TimeSpan");
            case "System.Uri":
            case "System.Version":
                return "string";
            case "System.Half":
                return "number";
            case "System.Int128":
            case "System.UInt128":
                return _config.LongAsString ? "string" : "number";
            case "System.Numerics.BigInteger":
                return "number";
            case "System.Text.Json.JsonElement":
            case "System.Text.Json.JsonDocument":
            case "System.Text.Json.Nodes.JsonNode":
            case "System.Text.Json.Nodes.JsonValue":
            case "Newtonsoft.Json.Linq.JToken":
            case "Newtonsoft.Json.Linq.JValue":
                return "unknown";
            case "System.Text.Json.Nodes.JsonObject":
            case "Newtonsoft.Json.Linq.JObject":
                return "Record<string, unknown>";
            case "System.Text.Json.Nodes.JsonArray":
            case "Newtonsoft.Json.Linq.JArray":
                return "unknown[]";
            case "System.Collections.Generic.KeyValuePair<TKey, TValue>":
                return $"{{ {MemberName("Key")}: {Ts(named.TypeArguments[0], file, null)}; {MemberName("Value")}: {Ts(named.TypeArguments[1], file, null)} }}";
        }

        if (named.TypeKind == TypeKind.Enum)
            return EnumReference(named, file, mode);

        var self = new[] { named }.Concat(named.AllInterfaces).ToList();
        if (self.FirstOrDefault(i => IsGeneric(i, "System.Collections.Generic", "IDictionary", 2) || IsGeneric(i, "System.Collections.Generic", "IReadOnlyDictionary", 2)) is { } dictionary)
            return Record(dictionary.TypeArguments[0], dictionary.TypeArguments[1], file);
        if (self.Any(i => i.ToDisplayString() == "System.Collections.IDictionary"))
            return "Record<string, unknown>";
        if (self.FirstOrDefault(i => IsGeneric(i, "System.Collections.Generic", "IEnumerable", 1)) is { } enumerable)
            return ArrayOf(Ts(enumerable.TypeArguments[0], file, null));
        if (self.Any(i => i.ToDisplayString() == "System.Collections.IEnumerable"))
            return "unknown[]";

        return Reference(named, file, extends: false) ?? "unknown";
    }

    private string MemberName(string name) => _config.PropertyNaming == TypescriptNaming.CamelCase ? TypescriptNames.CamelCase(name) : name;

    private static bool IsGeneric(INamedTypeSymbol type, string ns, string name, int arity)
        => type.Arity == arity && type.Name == name && type.ContainingNamespace?.ToDisplayString() == ns;

    /// <summary>A dictionary: enum keys as the union of their names (the serializer writes names), numbers as number, the rest as string.</summary>
    private string Record(ITypeSymbol key, ITypeSymbol value, FileContext file)
    {
        var v = Ts(value, file, null);
        var k = key.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T ? ((INamedTypeSymbol)key).TypeArguments[0] : key;
        if (k is INamedTypeSymbol { TypeKind: TypeKind.Enum } e)
        {
            var fields = e.GetMembers().OfType<IFieldSymbol>().Where(f => f.HasConstantValue && !f.IsImplicitlyDeclared).ToList();
            string keys;
            if (DeclOf(e) is { } decl && fields.All(f => EnumName(f) == f.Name))
                keys = $"keyof typeof {Use(file, decl, union: false)}";
            else
                keys = fields.Count == 0 ? "string" : string.Join(" | ", fields.Select(f => TypescriptNames.Literal(EnumName(f))));
            return $"Partial<Record<{keys}, {v}>>";
        }
        var numeric = k.SpecialType is >= SpecialType.System_SByte and <= SpecialType.System_Double;
        return $"Record<{(numeric ? "number" : "string")}, {v}>";
    }

    private string EnumReference(INamedTypeSymbol type, FileContext file, EnumMode? mode)
    {
        var declared = DeclaredMode(type);
        var wanted = mode ?? declared;
        if (IsFlags(type) && (mode ?? ConverterMode(type) ?? _enumMode) == EnumMode.String)
            return "string"; // a string converter writes flags as "A, B"; the declaration keeps the numbers
        var decl = DeclOf(type);
        if (decl == null)
            return wanted == EnumMode.String ? "string" : "number";
        if (wanted == declared)
            return Use(file, decl, union: false);
        if (wanted == EnumMode.Number)
            return "number";
        var fields = type.GetMembers().OfType<IFieldSymbol>().Where(f => f.HasConstantValue && !f.IsImplicitlyDeclared).ToList();
        return fields.All(f => EnumName(f) == f.Name)
            ? $"keyof typeof {Use(file, decl, union: false)}"
            : string.Join(" | ", fields.Select(f => TypescriptNames.Literal(EnumName(f))));
    }

    // ---------------------------------------------------------------- attributes

    private static AttributeData? Attr(ISymbol symbol, string fullName)
        => symbol.GetAttributes().FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == fullName);

    private static object? Named(AttributeData? attr, string name)
    {
        if (attr == null)
            return null;
        foreach (var argument in attr.NamedArguments)
            if (argument.Key == name)
                return argument.Value.Value;
        return null;
    }
